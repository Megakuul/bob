// header is the first entry of every file bob generates (R-FW-060).
const header = "Code generated by bob from bob.go. DO NOT EDIT."

// kv is one key of an ordered JSON object.
type kv struct {
	k string
	v any
}

// object is a JSON object whose keys keep their order (package.json has a fixed key order).
type object []kv

func (o object) MarshalJSON() ([]byte, error) {
	var b bytes.Buffer
	b.WriteByte('{')
	for i, e := range o {
		if i > 0 {
			b.WriteByte(',')
		}
		k, err := marshal(e.k)
		if err != nil {
			return nil, err
		}
		v, err := marshal(e.v)
		if err != nil {
			return nil, err
		}
		b.Write(k)
		b.WriteByte(':')
		b.Write(v)
	}
	b.WriteByte('}')
	return b.Bytes(), nil
}

// marshal is json.Marshal without HTML escaping.
func marshal(v any) ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return bytes.TrimSuffix(b.Bytes(), []byte("\n")), nil
}

// indent writes v with 2-space indentation and a trailing newline.
func indent(v any) ([]byte, error) {
	raw, err := marshal(v)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	if err := json.Indent(&b, raw, "", "  "); err != nil {
		return nil, err
	}
	b.WriteByte('\n')
	return b.Bytes(), nil
}

// sortedObject turns a map into an object sorted by key.
func sortedObject(m map[string]string) object {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	o := make(object, 0, len(keys))
	for _, k := range keys {
		o = append(o, kv{k, m[k]})
	}
	return o
}

// manifestDeps are an importer's dependency objects as package.json writes them: registry
// packages at their exact locked version (an alias as npm:<name>@<version>), local libraries as
// file:<relative dir>; a dependency the lock does not resolve yet keeps its declared range.
type manifestDeps struct {
	deps, dev, optional, peers map[string]string
}

func importerDeps(im *importer, byID map[string]*importer, sec *lock.NpmSection) (manifestDeps, error) {
	md := manifestDeps{deps: map[string]string{}, dev: map[string]string{}, optional: map[string]string{}, peers: map[string]string{}}
	var locked lock.NpmImporter
	if sec != nil {
		locked = sec.Importers[im.dir]
	}
	for _, d := range im.spec.Deps {
		alias, value := d.Alias, ""
		if d.Link >= 0 && d.Alias == "" {
			lib, err := depImporter(im.node, d.Link, byID)
			if err != nil {
				return md, err
			}
			alias, value = lib.spec.Name, "file:"+relDir(im.dir, lib.dir)
		} else {
			value = d.Req
			if value == "" {
				value = "*"
			}
			if key, ok := locked.Deps[alias]; ok && sec != nil {
				if p, ok := sec.Packages[key]; ok {
					value = p.Version
				}
			}
			if d.Name != "" && d.Name != d.Alias {
				value = "npm:" + d.Name + "@" + value
			}
		}
		switch {
		case d.Dev:
			md.dev[alias] = value
		case d.Optional:
			md.optional[alias] = value
		default:
			md.deps[alias] = value
		}
	}
	for _, d := range im.spec.Peers {
		req := d.Req
		if req == "" {
			req = "*"
		}
		md.peers[d.Alias] = req
	}
	return md, nil
}

// packageJSON is the importer's package.json (SPEC §03.4.6): "//" header, name, version
// "0.0.0", private, type module, the library's exports/types/peerDependencies, then the
// dependency objects sorted by name (the order the resolver reads them in).
func packageJSON(im *importer, md manifestDeps) ([]byte, error) {
	o := object{{"//", header}, {"name", packageName(im)}, {"version", "0.0.0"}, {"private", true}, {"type", "module"}}
	if im.node.Kind == npmspec.KindLib {
		js, dts := libEntry(im.spec.Entry)
		o = append(o, kv{"exports", object{{".", object{{"types", dts}, {"import", js}}}}}, kv{"types", dts})
		if len(md.peers) > 0 {
			o = append(o, kv{"peerDependencies", sortedObject(md.peers)})
		}
	}
	if len(md.deps) > 0 {
		o = append(o, kv{"dependencies", sortedObject(md.deps)})
	}
	if len(md.optional) > 0 {
		o = append(o, kv{"optionalDependencies", sortedObject(md.optional)})
	}
	if len(md.dev) > 0 {
		o = append(o, kv{"devDependencies", sortedObject(md.dev)})
	}
	return indent(o)
}

// packageName is the importer's npm name: a library's Name, else the label name.
func packageName(im *importer) string {
	if im.node.Kind == npmspec.KindLib {
		return im.spec.Name
	}
	_, name, _ := strings.Cut(strings.TrimPrefix(im.node.Label, "//"), ":")
	return name
}

// compilerOptions are the TSConfig defaults plus Extra, keys sorted, plus what the importer's
// build needs: a library emits declarations into dist/, apps and sites only type-check (their
// output comes from esbuild or Vite).
func compilerOptions(im *importer) map[string]any {
	t := im.spec.TSConfig
	co := map[string]any{"target": t.Target, "module": t.Module, "moduleResolution": t.ModuleResolution, "strict": t.Strict}
	if t.JSX != "" {
		co["jsx"] = t.JSX
	}
	if len(t.Lib) > 0 {
		co["lib"] = t.Lib
	}
	if len(t.Types) > 0 {
		co["types"] = t.Types
	}
	switch im.node.Kind {
	case npmspec.KindLib:
		co["declaration"], co["outDir"], co["rootDir"] = true, "dist", "src"
	default:
		co["noEmit"] = true
	}
	for k, v := range t.Extra {
		co[k] = v
	}
	return co
}

// tsconfigJSON is the importer's tsconfig.json: header comment, extends, compilerOptions
// (sorted), include, exclude.
func tsconfigJSON(im *importer) ([]byte, error) {
	t := im.spec.TSConfig
	var o object
	if t.Extends != "" {
		o = append(o, kv{"extends", t.Extends})
	}
	co := compilerOptions(im)
	keys := make([]string, 0, len(co))
	for k := range co {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	opts := make(object, 0, len(keys))
	for _, k := range keys {
		opts = append(opts, kv{k, co[k]})
	}
	o = append(o, kv{"compilerOptions", opts})
	if !t.Inherit {
		o = append(o, kv{"include", t.Include}, kv{"exclude", t.Exclude})
	}
	body, err := indent(o)
	if err != nil {
		return nil, err
	}
	return append([]byte("// "+header+"\n"), body...), nil
}

// nativeFiles returns package.json and tsconfig.json of every importer.
func nativeFiles(ims []*importer, byID map[string]*importer, sec *lock.NpmSection) ([]engine.GeneratedFile, error) {
	var out []engine.GeneratedFile
	for _, im := range ims {
		md, err := importerDeps(im, byID, sec)
		if err != nil {
			return nil, err
		}
		pj, err := packageJSON(im, md)
		if err != nil {
			return nil, err
		}
		tc, err := tsconfigJSON(im)
		if err != nil {
			return nil, err
		}
		out = append(out,
			engine.GeneratedFile{Path: path.Join(im.dir, "package.json"), Content: pj, Mode: 0o444, Owner: im.node.Label,
				Explain: explainJSON(pj, []string{"dependencies", "optionalDependencies", "devDependencies", "peerDependencies"})},
			engine.GeneratedFile{Path: path.Join(im.dir, "tsconfig.json"), Content: tc, Mode: 0o444, Owner: im.node.Label,
				Explain: explainJSON(tc, []string{"compilerOptions"})})
	}
	return out, nil
}

// stripComments drops the leading "//" comment lines of a tsconfig.json.
func stripComments(b []byte) []byte {
	for bytes.HasPrefix(bytes.TrimLeft(b, " \t\r\n"), []byte("//")) {
		b = bytes.TrimLeft(b, " \t\r\n")
		i := bytes.IndexByte(b, '\n')
		if i < 0 {
			return nil
		}
		b = b[i+1:]
	}
	return b
}

// explainJSON maps the edits made to a generated JSON file to drift lines: per object of
// sections, the keys added, removed or changed outside bob (R-FW-061).
func explainJSON(generated []byte, sections []string) func([]byte) []engine.DriftLine {
	return func(onDisk []byte) []engine.DriftLine {
		var want, have map[string]json.RawMessage
		if json.Unmarshal(stripComments(generated), &want) != nil {
			return nil
		}
		if err := json.Unmarshal(stripComments(onDisk), &have); err != nil {
			return []engine.DriftLine{{Op: "~", Text: "the file is no longer valid JSON"}}
		}
		var out []engine.DriftLine
		for _, s := range sections {
			var w, h map[string]json.RawMessage
			_ = json.Unmarshal(want[s], &w)
			_ = json.Unmarshal(have[s], &h)
			for _, k := range unionKeys(w, h) {
				wv, inW := w[k]
				hv, inH := h[k]
				switch {
				case !inW:
					out = append(out, engine.DriftLine{Op: "+", Text: fmt.Sprintf("%s.%s %s  (not declared in bob.go)", s, k, compactJSON(hv))})
				case !inH:
					out = append(out, engine.DriftLine{Op: "-", Text: fmt.Sprintf("%s.%s %s  (declared in bob.go)", s, k, compactJSON(wv))})
				case compactJSON(wv) != compactJSON(hv):
					out = append(out, engine.DriftLine{Op: "~", Text: fmt.Sprintf("%s.%s %s  (bob.go: %s)", s, k, compactJSON(hv), compactJSON(wv))})
				}
			}
		}
		return out
	}
}

func unionKeys(a, b map[string]json.RawMessage) []string {
	seen := map[string]bool{}
	var out []string
	for _, m := range []map[string]json.RawMessage{a, b} {
		for k := range m {
			if !seen[k] {
				seen[k] = true
				out = append(out, k)
			}
		}
	}
	sort.Strings(out)
	return out
}

func compactJSON(raw json.RawMessage) string {
	var b bytes.Buffer
	if json.Compact(&b, raw) != nil {
		return string(raw)
	}
	return b.String()
}
