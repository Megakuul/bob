// proxyModule writes one module version (go.mod + files) into a file:// GOPROXY directory.
func proxyModule(t *testing.T, root, path, version, gomod string, files map[string]string) {
	t.Helper()
	m := resolve.Module{Path: path, Version: version}
	dir := filepath.Join(root, filepath.FromSlash(resolve.EscapePath(path)), "@v")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	f, err := os.Create(filepath.Join(dir, version+".zip"))
	if err != nil {
		t.Fatal(err)
	}
	zw := zip.NewWriter(f)
	for name, body := range map[string]string{"go.mod": gomod} {
		w, _ := zw.Create(m.String() + "/" + name)
		w.Write([]byte(body))
	}
	for name, body := range files {
		w, _ := zw.Create(m.String() + "/" + name)
		w.Write([]byte(body))
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	f.Close()
	if err := os.WriteFile(filepath.Join(dir, version+".mod"), []byte(gomod), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := resolve.WriteVersionInfo(root, m); err != nil {
		t.Fatal(err)
	}
}

func moduleGraph(t *testing.T, reqs ...gospec.Requirement) *ir.Graph {
	t.Helper()
	spec := gospec.Module{Path: "example.com/tools", Go: "1.26", Require: reqs, Generated: []gospec.Generated{}}
	return &ir.Graph{Module: "example.com/r", Nodes: []*ir.Node{{ID: "m", Kind: gospec.KindModule, Label: "//tools:module",
		DefinedAt: ir.Pos{File: "tools/bob.go", Line: 9}, Spec: rawJSON(t, spec)}}}
}

// TestLockNativeStale: bob lock writes build list and module entries from the proxy,
// go.mod/go.sum follow from the section alone, the go command agrees offline, a second lock
// reads only bob's proxy directory, and Stale follows the declarations.
func TestLockNativeStale(t *testing.T) {
	proxy := t.TempDir()
	proxyModule(t, proxy, "golang.org/x/text", "v0.1.0", "module golang.org/x/text\n\ngo 1.20\n", map[string]string{"text.go": "package text\n"})
	proxyModule(t, proxy, "golang.org/x/net", "v0.1.0", "module golang.org/x/net\n\ngo 1.20\n\nrequire golang.org/x/text v0.1.0\n",
		map[string]string{"net.go": "package net\n\nimport _ \"golang.org/x/text\"\n"})
	cache := t.TempDir()
	t.Setenv(proxyEnv, "file://"+proxy)
	t.Setenv("XDG_CACHE_HOME", cache)
	root := t.TempDir()
	writeTree(t, root, map[string]string{"tools/main.go": "package main\n\nimport _ \"golang.org/x/net\"\n\nfunc main() {}\n"})
	g := moduleGraph(t, gospec.Requirement{Path: "golang.org/x/net", Version: "v0.1.0"})

	raw, err := Ecosystem{}.Lock(context.Background(), engine.LockRequest{Graph: g, Root: root})
	if err != nil {
		t.Fatal(err)
	}
	v, err := lock.DecodeSection(lock.SectionGo, raw)
	if err != nil {
		t.Fatal(err)
	}
	sec := v.(*lock.GoSection)
	if got := strings.Join(sec.Workspaces["example.com/tools"].Modules, " "); got != "golang.org/x/net@v0.1.0 golang.org/x/text@v0.1.0" {
		t.Errorf("build list %s", got)
	}
	if sec.Proxy != resolve.DefaultProxy {
		t.Errorf("a file:// proxy is recorded as %q, want the default proxy", sec.Proxy)
	}
	for _, m := range sec.Modules {
		if !m.Packages || m.H1 == "" || !strings.HasPrefix(m.Tree, "sha256-") || m.Go != "1.20" {
			t.Errorf("module entry %+v: both modules provide packages", m)
		}
	}

	files, err := Ecosystem{}.Native(context.Background(), engine.PlanRequest{Graph: g, Lock: raw})
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 2 {
		t.Fatalf("native files %d, want go.mod and go.sum", len(files))
	}
	wantMod := "// Code generated by bob from bob.go. DO NOT EDIT.\n// Edit tools/bob.go and run bob lock.\nmodule example.com/tools\n\ngo 1.26.0\n\n" +
		"require (\n\tgolang.org/x/net v0.1.0\n)\n\nrequire (\n\tgolang.org/x/text v0.1.0 // indirect\n)\n"
	if string(files[0].Content) != wantMod {
		t.Errorf("go.mod:\n%s\nwant:\n%s", files[0].Content, wantMod)
	}
	for _, f := range files {
		writeTree(t, root, map[string]string{f.Path: string(f.Content)})
	}
	if goBin, err := exec.LookPath("go"); err == nil {
		cmd := exec.Command(goBin, "list", "-m", "all")
		cmd.Dir = filepath.Join(root, "tools")
		cmd.Env = append(os.Environ(), "GOPROXY=file://"+filepath.Join(cache, "bob", "goproxy"), "GOFLAGS=-mod=readonly",
			"GOSUMDB=off", "GOTOOLCHAIN=local", "GOWORK=off", "GOMODCACHE="+t.TempDir(), "CGO_ENABLED=0")
		out, err := cmd.CombinedOutput()
		if err != nil || !strings.Contains(string(out), "golang.org/x/text v0.1.0") {
			t.Errorf("go list -m all with bob's proxy directory: %v\n%s", err, out)
		}
	}

	// A second lock needs no proxy: everything is in bob's proxy directory.
	t.Setenv(proxyEnv, "file:///nonexistent")
	raw2, err := Ecosystem{}.Lock(context.Background(), engine.LockRequest{Graph: g, Root: root, Prev: raw})
	if err != nil {
		t.Fatalf("second lock: %v", err)
	}
	var a, b any
	json.Unmarshal(raw, &a)
	json.Unmarshal(raw2, &b)
	if string(rawJSON(t, a)) != string(rawJSON(t, b)) {
		t.Errorf("second lock changed the section:\n%s\n%s", raw, raw2)
	}

	if what, _, err := (Ecosystem{}).Stale(context.Background(), engine.LockRequest{Graph: g, Prev: raw}); err != nil || what != "" {
		t.Errorf("fresh section reported stale: %q %v", what, err)
	}
	g2 := moduleGraph(t, gospec.Requirement{Path: "golang.org/x/net", Version: "v0.2.0"})
	what, at, err := Ecosystem{}.Stale(context.Background(), engine.LockRequest{Graph: g2, Prev: raw})
	if err != nil || !strings.Contains(what, "golang.org/x/net v0.2.0") || at.File != "tools/bob.go" {
		t.Errorf("changed requirement: stale %q at %v (%v)", what, at, err)
	}
}

// TestLockErrors: a missing module is BOB-E-1015 at the module's bob.go, a module needing a
// newer Go is BOB-E-1008 with the §03.2.4 text.
func TestLockErrors(t *testing.T) {
	proxy := t.TempDir()
	proxyModule(t, proxy, "github.com/foo/bar", "v1.2.0", "module github.com/foo/bar\n\ngo 1.27.0\n", map[string]string{"bar.go": "package bar\n"})
	t.Setenv(proxyEnv, "file://"+proxy)
	t.Setenv("XDG_CACHE_HOME", t.TempDir())
	_, err := Ecosystem{}.Lock(context.Background(), engine.LockRequest{Graph: moduleGraph(t, gospec.Requirement{Path: "github.com/foo/bar", Version: "v1.2.0"})})
	de, ok := err.(*diag.Error)
	if !ok || de.Code != 1008 || !strings.Contains(de.Error(), "github.com/foo/bar@v1.2.0 needs go 1.27.0, but example.com/tools uses go 1.26 (set Go in tools/bob.go)") {
		t.Errorf("toolchain: %#v", err)
	}
	_, err = Ecosystem{}.Lock(context.Background(), engine.LockRequest{Graph: moduleGraph(t, gospec.Requirement{Path: "golang.org/x/net", Version: "v0.99.0"})})
	de, ok = err.(*diag.Error)
	if !ok || de.Code != 1015 || !strings.Contains(de.Error(), "golang.org/x/net@v0.99.0: not found on") || de.DefinedAt.File != "tools/bob.go" {
		t.Errorf("not found: %#v", err)
	}
}

// TestGoLineCoversDependencies: a dependency of the same language version with a higher patch
// raises the go line (the go command would want to update go.mod otherwise).
func TestGoLineCoversDependencies(t *testing.T) {
	m := &wsModule{spec: gospec.Module{Path: "example.com/m", Go: "1.26"}}
	sec := &lock.GoSection{Modules: []lock.GoModule{
		{Path: "a.example/x", Version: "v1.0.0", Go: "1.26.1"},
		{Path: "a.example/x", Version: "v0.9.0", Go: "1.26.4"}, // not selected
		{Path: "b.example/y", Version: "v1.0.0", Go: "1.25.7"},
	}}
	bl := []resolve.Module{{Path: "a.example/x", Version: "v1.0.0"}, {Path: "b.example/y", Version: "v1.0.0"}}
	if got := goDirectiveOf(m, bl, sec); got != "1.26.1" {
		t.Errorf("go line %s, want 1.26.1", got)
	}
}
