package gen

import (
	"fmt"
	"path"
	"slices"
	"sort"
	"strings"

	"github.com/megakuul/bob/pkg/engine"
	"github.com/megakuul/bob/pkg/ocaml/internal/mlspec"
)

// merlinHeader is the first line of every generated .merlin (SPEC §03.0.2).
const merlinHeader = "# generated by bob from bob.go — do not edit\n"

// merlin is the content of one directory's .merlin.
type merlin struct {
	owner string
	src   []string // S
	pkg   []string // PKG
	flg   []string // FLG
}

func (m *merlin) add(list *[]string, v string) {
	if !slices.Contains(*list, v) {
		*list = append(*list, v)
	}
}

// merlinFiles writes <dir>/.merlin for every directory with local OCaml packages (§03.5.4):
// the directory's sources, every findlib package it uses (opam packages and local libraries:
// the dev environment's OCAMLPATH points into bob's store for both), the source directories of
// the local libraries (go-to-definition), and -open <Lib>__ inside a wrapped library. No path
// in it names the store, so it needs no build and never drifts with one.
func merlinFiles(req engine.PlanRequest) ([]engine.GeneratedFile, error) {
	ts, err := targets(req.Graph)
	if err != nil {
		return nil, err
	}
	byID := map[string]*target{}
	for _, t := range ts {
		byID[t.n.ID] = t
	}
	dirs := map[string]*merlin{}
	for _, t := range ts {
		if !strings.HasPrefix(t.n.Label, "//") {
			continue // dependency repositories' packages are not in this working tree
		}
		dir := labelDir(t.n.Label)
		m := dirs[dir]
		if m == nil {
			m = &merlin{owner: t.n.Label}
			dirs[dir] = m
		}
		for _, o := range t.spec.Opam {
			m.add(&m.pkg, o.Lib)
		}
		if t.spec.Type == mlspec.TypeLibrary && t.spec.Wrapped {
			m.add(&m.flg, "-open "+capital(t.spec.Name)+"__")
		}
		for _, i := range t.spec.Local {
			d := byID[t.n.Deps[i]]
			if d == nil {
				continue
			}
			m.add(&m.pkg, d.spec.Name)
			if strings.HasPrefix(d.n.Label, "//") {
				rel := relDir(dir, labelDir(d.n.Label))
				m.add(&m.src, rel)
			}
		}
	}
	var out []engine.GeneratedFile
	for _, dir := range sortedKeys(dirs) {
		m := dirs[dir]
		var b strings.Builder
		b.WriteString(merlinHeader)
		b.WriteString("S .\nB .\n")
		for _, s := range m.src {
			fmt.Fprintf(&b, "S %s\n", s)
		}
		pkgs := slices.Clone(m.pkg)
		sort.Strings(pkgs)
		for _, p := range pkgs {
			fmt.Fprintf(&b, "PKG %s\n", p)
		}
		for _, f := range m.flg {
			fmt.Fprintf(&b, "FLG %s\n", f)
		}
		out = append(out, engine.GeneratedFile{Path: path.Join(dir, ".merlin"), Content: []byte(b.String()), Mode: 0o444, Owner: m.owner})
	}
	return out, nil
}

// relDir is the path of to relative to from (both repository-relative directories).
func relDir(from, to string) string {
	f := splitDir(from)
	t := splitDir(to)
	i := 0
	for i < len(f) && i < len(t) && f[i] == t[i] {
		i++
	}
	var parts []string
	for range f[i:] {
		parts = append(parts, "..")
	}
	parts = append(parts, t[i:]...)
	if len(parts) == 0 {
		return "."
	}
	return strings.Join(parts, "/")
}

func splitDir(d string) []string {
	if d == "" || d == "." {
		return nil
	}
	return strings.Split(d, "/")
}

// capital is OCaml's String.capitalize_ascii.
func capital(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
