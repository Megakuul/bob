var update = flag.Bool("update", false, "rewrite the code-table golden and append new codes to codes.lock")

const (
	lockPath   = "codes.lock"
	goldenPath = "../../../tests/goldens/diag/codes.golden"
)

func variantKey(v Variant) string {
	if v.Name == "" {
		return "-"
	}
	return v.Name
}

func list(xs []string) string {
	if len(xs) == 0 {
		return "-"
	}
	return strings.Join(xs, ",")
}

// lockLines returns one line per code variant: code, class, variant, message args, hint args.
func lockLines() []string {
	var out []string
	for _, e := range table {
		for _, v := range e.Variants {
			var hargs []string
			for _, h := range v.Hints {
				hargs = append(hargs, TemplateArgs(h)...)
			}
			sort.Strings(hargs)
			hargs = dedup(hargs)
			out = append(out, fmt.Sprintf("%04d %s %s args=%s hint=%s", e.Code, e.Code.Class(),
				variantKey(v), list(TemplateArgs(v.Message)), list(hargs)))
		}
	}
	return out
}

func dedup(xs []string) []string {
	var out []string
	for i, x := range xs {
		if i == 0 || x != xs[i-1] {
			out = append(out, x)
		}
	}
	return out
}

func key(line string) string {
	f := strings.Fields(line)
	return f[0] + " " + f[2]
}

// TestCodesLock is the R-NIX-028 stability check: every code in codes.lock still exists with the
// same class and argument names. New codes are appended (go test -update); lines are never
// rewritten or removed.
func TestCodesLock(t *testing.T) {
	data, err := os.ReadFile(lockPath)
	if err != nil {
		t.Fatal(err)
	}
	cur := map[string]string{}
	for _, l := range lockLines() {
		cur[key(l)] = l
	}
	locked := map[string]bool{}
	for _, l := range strings.Split(string(data), "\n") {
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		k := key(l)
		locked[k] = true
		got, ok := cur[k]
		switch {
		case !ok:
			t.Errorf("code removed (R-NIX-028): %s", l)
		case got != l:
			t.Errorf("code changed (R-NIX-028):\n lock: %s\n now:  %s", l, got)
		}
	}
	var added []string
	for _, l := range lockLines() {
		if !locked[key(l)] {
			added = append(added, l)
		}
	}
	if len(added) == 0 {
		return
	}
	if !*update {
		t.Fatalf("codes missing from %s (run go test -update to append):\n%s", lockPath, strings.Join(added, "\n"))
	}
	f, err := os.OpenFile(lockPath, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	if _, err := f.WriteString(strings.Join(added, "\n") + "\n"); err != nil {
		t.Fatal(err)
	}
}

func golden() string {
	var b strings.Builder
	b.WriteString("# bob error code table (SPEC §02.3). Generated by go test ./pkg/bob/diag -update.\n")
	for _, e := range table {
		for _, v := range e.Variants {
			fmt.Fprintf(&b, "\n%s %s %s exit=%d\n  message: %s\n", e.Code.ID(), e.Code.Class(), variantKey(v),
				ExitCode([]*Error{{Code: e.Code}}), v.Message)
			for _, h := range v.Hints {
				fmt.Fprintf(&b, "  hint:    %s\n", h)
			}
		}
	}
	return b.String()
}

func TestCodeTableGolden(t *testing.T) {
	got := golden()
	if *update {
		if err := os.WriteFile(goldenPath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("%v (run go test -update)", err)
	}
	if string(want) != got {
		t.Errorf("code table differs from %s (rewording a template needs a golden update)", goldenPath)
	}
}

func TestTableWellFormed(t *testing.T) {
	var prev Code
	for i, e := range table {
		if i > 0 && e.Code <= prev {
			t.Errorf("table not strictly ascending at %d", e.Code)
		}
		prev = e.Code
		if e.Code > 9999 || len(e.Variants) == 0 {
			t.Errorf("bad entry %d", e.Code)
		}
		names := map[string]bool{}
		for i, v := range e.Variants {
			// Only the first variant may be unnamed: a code that gained variants later keeps
			// its original form (and codes.lock line, R-NIX-028) as the default.
			if i > 0 && v.Name == "" || len(e.Variants) == 1 && v.Name != "" {
				t.Errorf("%s: variant names must be set iff there are several (the first may stay unnamed)", e.Code.ID())
			}
			if names[v.Name] {
				t.Errorf("%s: duplicate variant %q", e.Code.ID(), v.Name)
			}
			names[v.Name] = true
			if v.Message == "" || strings.Contains(v.Message, "\n") {
				t.Errorf("%s: message must be one non-empty line", e.Code.ID())
			}
		}
	}
}

// argsFor returns key/value pairs for every argument of v (message and hints).
func argsFor(v Variant) []string {
	var kv []string
	if v.Name != "" {
		kv = append(kv, "variant", v.Name)
	}
	all := TemplateArgs(v.Message)
	for _, h := range v.Hints {
		all = append(all, TemplateArgs(h)...)
	}
	sort.Strings(all)
	for _, a := range dedup(all) {
		kv = append(kv, a, "<"+a+">")
	}
	return kv
}

// TestNewEveryCode calls New for every code with its arguments (R-NIX-028 acceptance).
func TestNewEveryCode(t *testing.T) {
	for _, e := range table {
		for _, v := range e.Variants {
			err := New(e.Code, argsFor(v)...)
			msg := err.Error()
			if strings.ContainsAny(msg, "{}") && !strings.Contains(v.Message, "{}") {
				t.Errorf("%s: unfilled template: %s", e.Code.ID(), msg)
			}
			if len(v.Hints) > 0 && err.Hint() == "" {
				t.Errorf("%s: hint missing with all arguments given", e.Code.ID())
			}
			if err.Severity != SeverityError || Warn(e.Code, argsFor(v)...).Severity != SeverityWarning {
				t.Errorf("%s: wrong severity", e.Code.ID())
			}
		}
	}
}

func mustPanic(t *testing.T, name string, f func()) {
	t.Helper()
	defer func() {
		if recover() == nil {
			t.Errorf("%s: no panic", name)
		}
	}()
	f()
}

func TestNewPanics(t *testing.T) {
	mustPanic(t, "unknown code", func() { New(1999) })
	mustPanic(t, "missing argument", func() { New(2003, "label", "//api:api") })
	//lint:ignore SA5012 the odd argument count is what this case tests
	mustPanic(t, "odd arguments", func() { New(2003, "label") })
	mustPanic(t, "unknown variant", func() { New(1025, "variant", "nope", "file", "x") })
	mustPanic(t, "variant missing", func() { New(4009) })
}

func TestExamples(t *testing.T) {
	err := New(2003, "label", "//api:api", "header", "rcore.h")
	if got := err.Error(); got != "//api:api: header rcore.h not found" {
		t.Errorf("Error() = %q", got)
	}
	if got := err.Hint(); got != "add the package that provides rcore.h to Deps" {
		t.Errorf("Hint() = %q", got)
	}
	if err.Label != "//api:api" {
		t.Errorf("Label = %q", err.Label)
	}
	if got := New(1, "kind", "command", "name", "biuld").Hint(); got != "run bob help" {
		t.Errorf("0001 fallback hint = %q", got)
	}
	if got := New(1, "kind", "command", "name", "biuld", "suggest", "build").Hint(); got != "did you mean build?" {
		t.Errorf("0001 hint = %q", got)
	}
	if got := New(4009, "variant", "none").Error(); got != "no bob server configured" {
		t.Errorf("4009 none = %q", got)
	}
	if got := NotImplemented("bob build").Error(); got != "bob build is not implemented yet" {
		t.Errorf("NotImplemented = %q", got)
	}
	if got := Code(42).ID(); got != "BOB-E-0042" {
		t.Errorf("ID = %q", got)
	}
}

func TestExitCode(t *testing.T) {
	cases := []struct {
		errs []*Error
		want int
	}{
		{nil, 0},
		{[]*Error{Warn(4001, "cache", "c")}, 0},
		{[]*Error{New(2001, "label", "l", "file", "f"), New(4003, "cache", "c", "reason", "r")}, 4},
		{[]*Error{New(4, "flag", "-C", "what", "a dir")}, 2},
		{[]*Error{New(1006, "cycle", "a")}, 3},
		{[]*Error{New(2000, "label", "l")}, 1},
		{[]*Error{New(5001, "attr", "a", "users", "u"), New(1006, "cycle", "a")}, 5},
		{[]*Error{New(6001, "what", "w"), New(5001, "attr", "a", "users", "u")}, 6},
		{[]*Error{New(7001), New(6001, "what", "w")}, 7},
		{[]*Error{NotImplemented("x"), New(7001)}, 70},
		{[]*Error{New(8001), NotImplemented("x")}, 130},
	}
	for i, c := range cases {
		if got := ExitCode(c.errs); got != c.want {
			t.Errorf("case %d: ExitCode = %d, want %d", i, got, c.want)
		}
	}
}
