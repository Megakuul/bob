// cacheNixosOrg is the default substituter and its key (SPEC R-NIX-024).
const (
	cacheNixosOrg    = "https://cache.nixos.org"
	cacheNixosOrgKey = "cache.nixos.org-1:6NCHdD59X431o0gWypbMrAURkbJ16ZPMQFGspcDShjY="
)

// HomeDir resolves the state home: $BOB_HOME, else ${XDG_DATA_HOME:-$HOME/.local/share}/bob
// (SPEC R-NIX-024). An explicit home wins over both.
func HomeDir(explicit string) (string, error) {
	h := explicit
	if h == "" {
		h = os.Getenv("BOB_HOME")
	}
	if h == "" {
		data := os.Getenv("XDG_DATA_HOME")
		if data == "" {
			home, err := os.UserHomeDir()
			if err != nil || home == "" {
				return "", diag.New(7002, "reason", "neither BOB_HOME nor HOME is set")
			}
			data = filepath.Join(home, ".local", "share")
		}
		h = filepath.Join(data, "bob")
	}
	abs, err := filepath.Abs(h)
	if err != nil {
		return "", fmt.Errorf("store: state home %s: %w", h, err)
	}
	return filepath.Clean(abs), nil
}

// stateDirs are the directories of <home> created before the namespace is entered. <home>/nix
// must exist to be mounted; its store and database are created only after the namespace works
// (there is no fallback mode, R-NIX-022).
var stateDirs = []string{
	"nix", "nsroot", "bin", "etc/nix",
	"xdg/config", "xdg/cache", "xdg/data", "xdg/state",
	"cache/go-build", "cache/drv", "cache/nixpkgs", "cache/eval",
}

// mkdirs creates the state layout below home.
func mkdirs(home string) error {
	for _, d := range stateDirs {
		if err := os.MkdirAll(filepath.Join(home, filepath.FromSlash(d)), 0o755); err != nil {
			return accessError(err)
		}
	}
	return nil
}

// accessError maps a failure to create or write bob's state to 7002.
func accessError(err error) error {
	reason := err.Error()
	var pe *os.PathError
	if errors.As(err, &pe) {
		reason = pe.Path + ": " + pe.Err.Error()
	}
	d := diag.New(7002, "reason", reason)
	d.Raw = []string{err.Error()}
	return d
}

// lockState takes the flock on <home>/lock that serialises state creation, extraction and
// nix.conf rewrites (R-NIX-026). The returned function releases it.
func lockState(home string) (func(), error) {
	f, err := os.OpenFile(filepath.Join(home, "lock"), os.O_RDWR|os.O_CREATE, 0o644)
	if err != nil {
		return nil, accessError(err)
	}
	for {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX)
		if !errors.Is(err, syscall.EINTR) {
			break
		}
	}
	if err != nil {
		f.Close()
		return nil, fmt.Errorf("store: lock %s: %w", f.Name(), err)
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		f.Close()
	}, nil
}

// nixConf renders the dev-profile nix.conf (SPEC R-NIX-024), byte for byte.
func nixConf(home string, subs []Substituter) []byte {
	urls := []string{cacheNixosOrg}
	keys := []string{cacheNixosOrgKey}
	for _, s := range subs {
		urls = append(urls, s.URL)
		if s.PublicKey != "" {
			keys = append(keys, s.PublicKey)
		}
	}
	var b bytes.Buffer
	b.WriteString("# Generated by bob. DO NOT EDIT.\n")
	b.WriteString("build-users-group =\n")
	b.WriteString("sandbox = true\n")
	b.WriteString("sandbox-fallback = false\n")
	b.WriteString("require-drop-supplementary-groups = false\n")
	b.WriteString("experimental-features = nix-command\n")
	b.WriteString("substituters = " + strings.Join(urls, " ") + "\n")
	b.WriteString("trusted-public-keys = " + strings.Join(keys, " ") + "\n")
	b.WriteString("netrc-file = " + filepath.Join(home, "etc", "nix", "netrc") + "\n")
	b.WriteString("narinfo-cache-negative-ttl = 60\n")
	b.WriteString("fallback = true\n")
	b.WriteString("connect-timeout = 5\n")
	b.WriteString("max-jobs = auto\n")
	b.WriteString("cores = 0\n")
	b.WriteString("eval-cache = false\n")
	b.WriteString("allow-import-from-derivation = false\n")
	b.WriteString("auto-optimise-store = false\n")
	b.WriteString("warn-dirty = false\n")
	return b.Bytes()
}

// netrc renders the credentials of the substituters that have one: one
// `machine <host> login bob password <token>` line each.
func netrc(subs []Substituter) ([]byte, error) {
	var b bytes.Buffer
	for _, s := range subs {
		if s.NetrcPassword == "" {
			continue
		}
		m := s.NetrcMachine
		if m == "" {
			u, err := url.Parse(s.URL)
			if err != nil || u.Hostname() == "" {
				return nil, fmt.Errorf("store: substituter %q has no host for its credential", s.URL)
			}
			m = u.Hostname()
		}
		for _, f := range []string{m, s.NetrcPassword} {
			if f == "" || strings.ContainsAny(f, " \t\r\n#") {
				return nil, fmt.Errorf("store: substituter %q has a credential that cannot be written to netrc", s.URL)
			}
		}
		fmt.Fprintf(&b, "machine %s login bob password %s\n", m, s.NetrcPassword)
	}
	return b.Bytes(), nil
}

// writeConfig writes nix.conf (0644), netrc (0600) and the empty user.conf, each only when its
// content or mode differs, through a temporary file and an atomic rename.
func writeConfig(home string, subs []Substituter) error {
	rc, err := netrc(subs)
	if err != nil {
		return err
	}
	dir := filepath.Join(home, "etc", "nix")
	for _, f := range []struct {
		name string
		data []byte
		mode os.FileMode
	}{
		{"nix.conf", nixConf(home, subs), 0o644},
		{"netrc", rc, 0o600},
		{"user.conf", nil, 0o644},
	} {
		if err := writeIfChanged(filepath.Join(dir, f.name), f.data, f.mode); err != nil {
			return accessError(err)
		}
	}
	return nil
}

// writeIfChanged replaces path atomically unless it already has exactly data and mode.
func writeIfChanged(path string, data []byte, mode os.FileMode) error {
	if fi, err := os.Lstat(path); err == nil && fi.Mode().IsRegular() && fi.Mode().Perm() == mode {
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
			return nil
		}
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
