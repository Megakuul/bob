// Evaluator generation, the part the sandbox needs (S1 §5.3, R-FW-043.2): a generated go.mod
// that pulls in the framework, an overlay that hides every other compilable file of a bob.go
// directory, and the virtual main <root>/_bobeval/main.go. R-FW-043 (eval key, rules R1-R7,
// package main renames, dependency bob repos, compiler message mapping) completes it.

const (
	genDir  = ".bob/eval"
	mainDir = "_bobeval"
)

// generate writes .bob/eval/{go.mod,go.sum,overlay.json,main.go} for the repository at root.
// Paths inside them are sandbox paths (the repository is /src there).
func generate(root, fwGo string) error {
	gomod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return fmt.Errorf("the repository has no go.mod: %w", err)
	}
	mod := modulePath(gomod)
	if mod == "" {
		return fmt.Errorf("%s has no module line", filepath.Join(root, "go.mod"))
	}
	dirs, err := bobDirs(root)
	if err != nil {
		return err
	}
	out := filepath.Join(root, genDir)
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	replace := map[string]string{srcDir + "/" + mainDir + "/main.go": srcDir + "/" + genDir + "/main.go"}
	var imports []string
	for _, d := range dirs {
		ents, err := os.ReadDir(filepath.Join(root, d))
		if err != nil {
			return err
		}
		for _, e := range ents {
			if !e.IsDir() && e.Name() != "bob.go" && strings.HasSuffix(e.Name(), ".go") {
				replace[path.Join(srcDir, d, e.Name())] = "" // hidden from the evaluator build
			}
		}
		imports = append(imports, path.Join(mod, d))
	}
	ov, err := json.MarshalIndent(map[string]any{"Replace": replace}, "", "  ")
	if err != nil {
		return err
	}
	var main strings.Builder
	main.WriteString("// Code generated by bob. DO NOT EDIT.\n\npackage main\n\nimport (\n")
	for _, imp := range imports {
		fmt.Fprintf(&main, "\t_ %q\n", imp)
	}
	fmt.Fprintf(&main, "\n\t%q\n)\n\nfunc main() { bob.Main() }\n", frameworkModule+"/pkg/bob")
	gosum, _ := os.ReadFile(filepath.Join(root, "go.sum"))
	files := map[string][]byte{
		"go.mod":       evalGoMod(gomod, fwGo),
		"go.sum":       gosum,
		"overlay.json": append(ov, '\n'),
		"main.go":      []byte(main.String()),
	}
	for name, content := range files {
		if err := writeIfChanged(filepath.Join(out, name), content); err != nil {
			return err
		}
	}
	return nil
}

// evalGoMod is the user's go.mod plus the framework requirement, with the framework resolved
// to the sources bound at /fw. The go directive is raised to the framework's when lower: go
// would otherwise rewrite go.mod, which is read-only in the sandbox.
func evalGoMod(gomod []byte, fwGo string) []byte {
	lines := strings.Split(string(gomod), "\n")
	found := false
	for i, l := range lines {
		if v, ok := strings.CutPrefix(strings.TrimSpace(l), "go "); ok {
			found = true
			if versionLess(strings.TrimSpace(v), fwGo) {
				lines[i] = "go " + fwGo
			}
		}
	}
	s := strings.Join(lines, "\n")
	if !found {
		s += "\ngo " + fwGo + "\n"
	}
	if !strings.Contains(s, frameworkModule+" ") {
		s += "\nrequire " + frameworkModule + " v0.0.0\n"
	}
	return []byte(s + "\nreplace " + frameworkModule + " => " + frameworkDir + "\n")
}

// versionLess compares Go versions such as "1.26" and "1.26.9" numerically.
func versionLess(a, b string) bool {
	as, bs := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(as) || i < len(bs); i++ {
		var x, y int
		if i < len(as) {
			x, _ = strconv.Atoi(as[i])
		}
		if i < len(bs) {
			y, _ = strconv.Atoi(bs[i])
		}
		if x != y {
			return x < y
		}
	}
	return false
}

// bobDirs lists the repo-relative directories holding a bob.go ("." for the root), sorted
// (R-FW-002 scan rules).
func bobDirs(root string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			name := d.Name()
			if p != root && (strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") ||
				name == "node_modules" || name == "testdata") {
				return filepath.SkipDir
			}
			if p != root {
				if _, err := os.Stat(filepath.Join(p, "go.mod")); err == nil {
					return filepath.SkipDir
				}
			}
			return nil
		}
		if d.Name() == "bob.go" && d.Type().IsRegular() {
			rel, err := filepath.Rel(root, filepath.Dir(p))
			if err != nil {
				return err
			}
			dirs = append(dirs, filepath.ToSlash(rel))
		}
		return nil
	})
	sort.Strings(dirs)
	return dirs, err
}

func writeIfChanged(p string, content []byte) error {
	if old, err := os.ReadFile(p); err == nil && string(old) == string(content) {
		return nil
	}
	tmp := p + ".tmp"
	if err := os.WriteFile(tmp, content, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, p)
}
