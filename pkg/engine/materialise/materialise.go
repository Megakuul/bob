// Root is one owned directory to bring into the working tree.
type Root struct {
	Dir    string // repo-relative owned directory ("gen/proto", "web/node_modules")
	Label  string // the package whose output it is (named in conflicts)
	Source string // store path of the output: the manifest's "source"
	Tree   string // host directory holding the output; its files and symlinks become Dir's
	// LinkStore is the host directory of the store ("<home>/nix/store"): symlink targets in
	// /nix/store are rewritten below it, so that tools outside bob's namespace can follow them.
	// "" keeps targets unchanged.
	LinkStore string
	// Keep are top-level names inside Dir that bob never owns, never touches and never counts
	// as conflicts (tool caches: node_modules/.vite, node_modules/.cache).
	Keep []string
	// Record is a repo-relative file that receives Source and a newline once Dir is up to date
	// (an npm importer's .bob/node_modules.path); "" for none.
	Record string
	// Inputs is a digest of the declarations and sources Source was made from; it is recorded
	// in the manifest for bob status ("" when unknown: the root then shows as stale).
	Inputs string
}

// Options configures Apply.
type Options struct {
	Repo string // repository root (absolute)
	// Force renames conflicting files (edited or foreign, never git-tracked ones) to
	// .bob/gen/backup/<UTC time>/<path> before writing (bob gen --force). Nothing is deleted.
	Force bool
	// Prune removes the owned directories of the manifest that roots does not list (bob gen of
	// the whole repository); otherwise they are left as they are.
	Prune bool
	Now   func() time.Time // nil = time.Now
}

// Result is what Apply did.
type Result struct {
	Written   []string      // owned directories whose files changed (written, removed), sorted
	Conflicts []*diag.Error // BOB-E-1016, one per conflicting file; their directory was left alone
}

// tmpPrefix names bob's temp files; one left by an interrupted write is deleted.
const tmpPrefix = ".bob-tmp-"

// gitignore is the .gitignore bob writes into every owned directory (SPEC §03.6.6).
const gitignore = "# Generated by bob. Do not edit files in this directory: change the inputs and run `bob gen`.\n*\n"

// maxTreeFiles bounds one output tree (a hoisted node_modules has some ten thousand files).
const maxTreeFiles = 500_000

// want is one file an owned directory should hold.
type want struct {
	ManifestFile
	from    string // host path of the content ("" for content and symlinks)
	content []byte // the .gitignore
}

// Apply brings every root into the working tree with the write protocol of SPEC §03.6.6: it
// takes .bob/gen/lock, classifies each file on disk by sha256 against the manifest, skips a root
// with conflicts entirely (others proceed), writes through temp files and renames, deletes
// stale files and empty directories, writes the root's .gitignore and the final manifest.
func Apply(ctx context.Context, o Options, roots []Root) (*Result, error) {
	if o.Now == nil {
		o.Now = time.Now
	}
	res := &Result{}
	if err := checkRoots(roots); err != nil {
		return res, err
	}
	gen := filepath.Join(o.Repo, ".bob", "gen")
	if err := os.MkdirAll(gen, 0o755); err != nil {
		return res, fmt.Errorf("materialise: %w", err)
	}
	if err := ensureIgnoreAll(filepath.Join(o.Repo, ".bob")); err != nil {
		return res, err
	}
	unlock, err := lockDir(ctx, filepath.Join(gen, "lock"))
	if err != nil {
		return res, err
	}
	defer unlock()
	m, err := readManifest(o.Repo)
	if err != nil {
		return res, err
	}
	before, _ := encode(m)
	listed := map[string]bool{}
	dirs := []string{}
	for _, r := range roots {
		listed[r.Dir] = true
		dirs = append(dirs, r.Dir)
	}
	if o.Prune {
		for d := range m.Roots {
			if !listed[d] {
				dirs = append(dirs, d)
			}
		}
	}
	tracked := gitTracked(ctx, o.Repo, dirs)
	a := &applier{o: o, m: m, tracked: tracked, stamp: o.Now().UTC().Format("20060102T150405Z")}

	sorted := append([]Root(nil), roots...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Dir < sorted[j].Dir })
	for _, r := range sorted {
		if err := ctx.Err(); err != nil {
			return res, err
		}
		files, err := a.wanted(r)
		if err != nil {
			return res, err
		}
		changed, conflicts, err := a.apply(r, files)
		if err != nil {
			return res, err
		}
		res.Conflicts = append(res.Conflicts, conflicts...)
		if len(conflicts) > 0 {
			continue
		}
		if changed {
			res.Written = append(res.Written, r.Dir)
		}
		if r.Record != "" {
			if err := writeRecord(o.Repo, r.Record, r.Source); err != nil {
				return res, err
			}
		}
	}
	if o.Prune {
		var stale []string
		for d := range m.Roots {
			if !listed[d] {
				stale = append(stale, d)
			}
		}
		sort.Strings(stale)
		for _, d := range stale {
			mr := m.Roots[d]
			_, conflicts, err := a.apply(Root{Dir: d, Label: mr.Label, Keep: mr.Keep}, map[string]want{})
			if err != nil {
				return res, err
			}
			res.Conflicts = append(res.Conflicts, conflicts...)
			if len(conflicts) > 0 {
				continue
			}
			delete(m.Roots, d)
			_ = os.Remove(filepath.Join(o.Repo, filepath.FromSlash(d)))
			removeEmptyParents(o.Repo, d)
			res.Written = append(res.Written, d)
		}
	}
	sort.Strings(res.Written)
	if after, _ := encode(m); !bytes.Equal(before, after) {
		if err := writeManifest(o.Repo, m); err != nil {
			return res, err
		}
	}
	return res, nil
}

// checkRoots refuses owned directories that are invalid, nested or shared (SPEC §03.6.6).
func checkRoots(roots []Root) error {
	var errs []error
	for i, r := range roots {
		if !validDir(r.Dir) {
			errs = append(errs, diag.New(1020, "label", r.Label, "option", "output directory",
				"reason", fmt.Sprintf("%s generates into %q, which is not a clean relative directory outside .git and .bob", r.Label, r.Dir)))
			continue
		}
		for _, o := range roots[:i] {
			switch {
			case o.Dir == r.Dir:
				errs = append(errs, diag.New(1020, "label", r.Label, "option", "output directory",
					"reason", fmt.Sprintf("%s and %s both generate into %s/ (give one of them another output directory)", o.Label, r.Label, r.Dir)))
			case strings.HasPrefix(r.Dir, o.Dir+"/"), strings.HasPrefix(o.Dir, r.Dir+"/"):
				inner, outer := r, o
				if strings.HasPrefix(o.Dir, r.Dir+"/") {
					inner, outer = o, r
				}
				errs = append(errs, diag.New(1020, "label", inner.Label, "option", "output directory",
					"reason", fmt.Sprintf("%s generates into %s/, which is inside %s/ owned by %s (generated directories may not be nested)", inner.Label, inner.Dir, outer.Dir, outer.Label)))
			}
		}
	}
	return errors.Join(errs...)
}

type applier struct {
	o       Options
	m       *Manifest
	tracked map[string]bool // repo-relative paths git tracks below the owned directories
	stamp   string          // backup directory name
}

// wanted is the file set of r: its tree plus the .gitignore. Store outputs never change, so
// when the manifest already records the same source its hashes are reused instead of reading
// every file again.
func (a *applier) wanted(r Root) (map[string]want, error) {
	prev, same := a.m.Roots[r.Dir]
	same = same && prev.Source == r.Source && r.Source != ""
	keep := map[string]bool{}
	for _, k := range r.Keep {
		keep[k] = true
	}
	out := map[string]want{}
	n := 0
	err := filepath.WalkDir(r.Tree, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(r.Tree, p)
		if err != nil || rel == "." {
			return err
		}
		rel = filepath.ToSlash(rel)
		if first, _, _ := strings.Cut(rel, "/"); keep[first] || rel == ".gitignore" {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if n++; n > maxTreeFiles {
			return fmt.Errorf("%s has more than %d files", r.Tree, maxTreeFiles)
		}
		switch {
		case d.Type()&fs.ModeSymlink != 0:
			target, err := os.Readlink(p)
			if err != nil {
				return err
			}
			target = mapLink(r, rel, target)
			out[rel] = want{ManifestFile: linkFile(target)}
		case d.Type().IsRegular():
			fi, err := d.Info()
			if err != nil {
				return err
			}
			w := want{ManifestFile: ManifestFile{Size: fi.Size(), Exec: fi.Mode()&0o111 != 0}, from: p}
			if f, ok := prev.Files[rel]; same && ok && f.Link == "" && f.Size == fi.Size() {
				w.SHA256 = f.SHA256
			} else if w.SHA256, err = hashFile(p); err != nil {
				return err
			}
			out[rel] = w
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("materialise: %s: %w", r.Label, err)
	}
	sum := sha256.Sum256([]byte(gitignore))
	out[".gitignore"] = want{ManifestFile: ManifestFile{SHA256: hex.EncodeToString(sum[:]), Size: int64(len(gitignore))}, content: []byte(gitignore)}
	return out, nil
}

// mapLink rewrites a symlink of the output: store targets go below LinkStore, and relative
// targets that leave the output become absolute (they pointed at a sibling store path).
func mapLink(r Root, rel, target string) string {
	if !path.IsAbs(target) {
		abs := path.Join(r.Source, path.Dir(rel), target)
		if r.Source != "" && (abs == r.Source || strings.HasPrefix(abs, r.Source+"/")) {
			return target
		}
		target = abs
	}
	if r.LinkStore != "" && strings.HasPrefix(target, "/nix/store/") {
		return filepath.Join(r.LinkStore, strings.TrimPrefix(target, "/nix/store/"))
	}
	return target
}

// sameStoreLink reports whether the symlink p on disk and the wanted symlink w point at the
// same store object, each through its own bob home ("<home>/nix/store/<hash>-<name>/…"). Such
// a link was made by bob from the same output before the state home changed (or before the
// manifest was lost); replacing it loses nothing, so it is rewritten instead of being a conflict.
func sameStoreLink(p string, fi fs.FileInfo, w want) bool {
	if fi.Mode()&fs.ModeSymlink == 0 || w.Link == "" {
		return false
	}
	target, err := os.Readlink(p)
	if err != nil {
		return false
	}
	obj := func(t string) string {
		if i := strings.LastIndex(t, "/nix/store/"); i >= 0 {
			return t[i:]
		}
		return ""
	}
	return obj(target) != "" && obj(target) == obj(w.Link)
}

func linkFile(target string) ManifestFile {
	sum := sha256.Sum256([]byte("symlink:" + target))
	return ManifestFile{SHA256: hex.EncodeToString(sum[:]), Size: int64(len(target)), Link: target}
}

// onDisk is one file or symlink found in an owned directory.
type onDisk struct {
	rel  string // relative to the owned directory
	info fs.FileInfo
}

// apply brings owned directory r.Dir to files (empty files: remove everything bob owns there).
// It returns whether anything changed and the conflicts; with conflicts nothing was written.
func (a *applier) apply(r Root, files map[string]want) (bool, []*diag.Error, error) {
	dir, label, source, keepNames := r.Dir, r.Label, r.Source, r.Keep
	abs := filepath.Join(a.o.Repo, filepath.FromSlash(dir))
	prev := a.m.Roots[dir]
	known := func(rel string) (ManifestFile, ManifestFile, bool, bool) {
		f, ok1 := prev.Files[rel]
		p, ok2 := prev.Pending[rel]
		return f, p, ok1, ok2
	}
	if fi, err := os.Lstat(abs); err == nil && !fi.IsDir() {
		// The owned directory itself is a file or a symlink bob did not make.
		return false, []*diag.Error{conflict(dir, label, "it is not a directory bob made")}, nil
	} else if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return false, nil, fmt.Errorf("materialise: %w", err)
	}
	disk, temps, err := scanDisk(abs, keepNames)
	if err != nil {
		return false, nil, err
	}
	for _, t := range temps { // interrupted writes
		_ = os.Remove(filepath.Join(abs, filepath.FromSlash(t)))
	}
	var (
		conflicts []*diag.Error
		backups   []string
		write     []string // to (re)write
		remove    []string // owned, no longer wanted
		changed   = len(temps) > 0
	)
	present := map[string]bool{}
	for _, f := range disk {
		present[f.rel] = true
		repoRel := path.Join(dir, f.rel)
		if a.tracked[repoRel] {
			conflicts = append(conflicts, conflict(repoRel, label, "it is tracked by git"))
			continue
		}
		w, isWanted := files[f.rel]
		mf, pf, inFiles, inPending := known(f.rel)
		sum, err := digest(filepath.Join(abs, filepath.FromSlash(f.rel)), f.info, mf, inFiles)
		if err != nil {
			return false, nil, err
		}
		switch {
		case isWanted && sum == w.SHA256:
			if f.info.Mode()&fs.ModeSymlink == 0 && f.info.Mode().Perm() != fileMode(w.Exec) {
				if err := os.Chmod(filepath.Join(abs, filepath.FromSlash(f.rel)), fileMode(w.Exec)); err != nil {
					return false, nil, fmt.Errorf("materialise: %w", err)
				}
			}
		case isWanted && sameStoreLink(filepath.Join(abs, filepath.FromSlash(f.rel)), f.info, w):
			write = append(write, f.rel) // the same store object seen through another bob home
		case inFiles && sum == mf.SHA256, inPending && sum == pf.SHA256:
			if isWanted {
				write = append(write, f.rel)
			} else {
				remove = append(remove, f.rel)
			}
		case inFiles || inPending:
			conflicts = append(conflicts, conflict(repoRel, label, "it was edited after bob wrote it"))
			backups = append(backups, f.rel)
		default:
			conflicts = append(conflicts, conflict(repoRel, label, "bob did not write it"))
			backups = append(backups, f.rel)
		}
	}
	if len(conflicts) > 0 {
		if !a.o.Force || len(backups) < len(conflicts) { // git-tracked files block even --force
			return false, conflicts, nil
		}
		for _, rel := range backups {
			if err := a.backup(dir, rel); err != nil {
				return false, nil, err
			}
			present[rel] = false
		}
		changed = true
	}
	for rel := range files {
		if !present[rel] {
			write = append(write, rel)
		}
	}
	sort.Strings(write)
	sort.Strings(remove)
	if len(write) == 0 && len(remove) == 0 && !changed && prev.Source == source && len(prev.Pending) == 0 {
		a.record(r, files, nil)
		return false, nil, nil
	}
	// Pending first: a crash from here on leaves files the next run recognises as bob's.
	pending := map[string]ManifestFile{}
	for rel, w := range files {
		pending[rel] = w.ManifestFile
	}
	if len(files) > 0 {
		mr := a.m.Roots[dir]
		mr.Label, mr.PendingSource, mr.Pending, mr.Keep = label, source, pending, keepNames
		if mr.Files == nil {
			mr.Files = map[string]ManifestFile{}
		}
		a.m.Roots[dir] = mr
		if err := writeManifest(a.o.Repo, a.m); err != nil {
			return false, nil, err
		}
	}
	// Stale entries go first, so that a path changing between file, symlink and directory
	// never meets its old self.
	for _, rel := range remove {
		if err := os.Remove(filepath.Join(abs, filepath.FromSlash(rel))); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return false, nil, fmt.Errorf("materialise: %w", err)
		}
	}
	removeEmptyDirs(abs, keepNames)
	written := map[string]ManifestFile{}
	synced := map[string]bool{}
	for _, rel := range write {
		mf, err := put(abs, rel, files[rel])
		if err != nil {
			return false, nil, err
		}
		written[rel] = mf
		synced[filepath.Dir(filepath.Join(abs, filepath.FromSlash(rel)))] = true
	}
	for d := range synced {
		if err := syncDir(d); err != nil {
			return false, nil, err
		}
	}
	a.record(r, files, written)
	return true, nil, nil
}

// record makes files the owned set of root.Dir in the manifest (written: the stat of files
// written now; the others keep their recorded mtime).
func (a *applier) record(root Root, files map[string]want, written map[string]ManifestFile) {
	if len(files) == 0 {
		return
	}
	dir := root.Dir
	prev := a.m.Roots[dir]
	r := ManifestRoot{Label: root.Label, Source: root.Source, Files: map[string]ManifestFile{}, Inputs: root.Inputs, Keep: root.Keep}
	for rel, w := range files {
		f := w.ManifestFile
		if x, ok := written[rel]; ok {
			f = x
		} else if old, ok := prev.Files[rel]; ok && old.SHA256 == f.SHA256 {
			f.MTime = old.MTime
		} else if fi, err := os.Lstat(filepath.Join(a.o.Repo, filepath.FromSlash(dir), filepath.FromSlash(rel))); err == nil {
			f.MTime = fi.ModTime().UnixNano()
		}
		r.Files[rel] = f
	}
	a.m.Roots[dir] = r
}

// backup moves a conflicting file to .bob/gen/backup/<UTC time>/<dir>/<rel> (bob gen --force).
func (a *applier) backup(dir, rel string) error {
	src := filepath.Join(a.o.Repo, filepath.FromSlash(dir), filepath.FromSlash(rel))
	dst := filepath.Join(a.o.Repo, ".bob", "gen", "backup", a.stamp, filepath.FromSlash(dir), filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return fmt.Errorf("materialise: %w", err)
	}
	if err := os.Rename(src, dst); err != nil {
		return fmt.Errorf("materialise: backup of %s: %w", path.Join(dir, rel), err)
	}
	return nil
}

func conflict(p, label, reason string) *diag.Error {
	return diag.New(1016, "path", p, "label", label, "reason", reason)
}

func fileMode(exec bool) fs.FileMode {
	if exec {
		return 0o555
	}
	return 0o444
}

// scanDisk lists the files and symlinks below abs (without following symlinks), skipping the
// top-level names in keep; temps are bob's temp files left by an interrupted write.
func scanDisk(abs string, keep []string) (files []onDisk, temps []string, err error) {
	skip := map[string]bool{}
	for _, k := range keep {
		skip[k] = true
	}
	err = filepath.WalkDir(abs, func(p string, d fs.DirEntry, err error) error {
		if errors.Is(err, fs.ErrNotExist) && p == abs {
			return filepath.SkipAll
		}
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(abs, p)
		if rel == "." {
			return nil
		}
		rel = filepath.ToSlash(rel)
		if first, _, _ := strings.Cut(rel, "/"); skip[first] {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasPrefix(d.Name(), tmpPrefix) {
			temps = append(temps, rel)
			return nil
		}
		if d.IsDir() {
			return nil
		}
		fi, err := d.Info()
		if err != nil {
			return err
		}
		if len(files) >= maxTreeFiles {
			return fmt.Errorf("more than %d files", maxTreeFiles)
		}
		files = append(files, onDisk{rel: rel, info: fi})
		return nil
	})
	if err != nil {
		return nil, nil, fmt.Errorf("materialise: %s: %w", abs, err)
	}
	return files, temps, nil
}

// digest is the sha256 of a file on disk (of "symlink:<target>" for a symlink). A regular
// file whose size and mtime equal its manifest entry is taken to have the recorded hash.
func digest(p string, fi fs.FileInfo, mf ManifestFile, known bool) (string, error) {
	if fi.Mode()&fs.ModeSymlink != 0 {
		target, err := os.Readlink(p)
		if err != nil {
			return "", fmt.Errorf("materialise: %w", err)
		}
		return linkFile(target).SHA256, nil
	}
	if !fi.Mode().IsRegular() {
		return "special", nil // never equal to a hash: a device or socket is never bob's
	}
	if known && mf.Link == "" && mf.Size == fi.Size() && mf.MTime != 0 && mf.MTime == fi.ModTime().UnixNano() {
		return mf.SHA256, nil
	}
	return hashFile(p)
}

func hashFile(p string) (string, error) {
	f, err := os.Open(p)
	if err != nil {
		return "", fmt.Errorf("materialise: %w", err)
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", fmt.Errorf("materialise: %w", err)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// put writes one file or symlink through a temp file in its directory and renames it into
// place. A regular file's content must hash to the expected sha256 (the store is read-only,
// so a difference is damage).
func put(abs, rel string, w want) (ManifestFile, error) {
	dst := filepath.Join(abs, filepath.FromSlash(rel))
	dir := filepath.Dir(dst)
	if err := mkdirs(abs, dir); err != nil {
		return ManifestFile{}, err
	}
	if fi, err := os.Lstat(dst); err == nil && fi.IsDir() {
		if err := os.Remove(dst); err != nil { // an empty directory left where a file goes
			return ManifestFile{}, fmt.Errorf("materialise: %w", err)
		}
	}
	tmp := filepath.Join(dir, tmpPrefix+randomSuffix())
	ok := false
	defer func() {
		if !ok {
			_ = os.Remove(tmp)
		}
	}()
	if w.Link != "" {
		if err := os.Symlink(w.Link, tmp); err != nil {
			return ManifestFile{}, fmt.Errorf("materialise: %w", err)
		}
	} else if err := writeContent(tmp, w); err != nil {
		return ManifestFile{}, err
	}
	if err := os.Rename(tmp, dst); err != nil {
		return ManifestFile{}, fmt.Errorf("materialise: %w", err)
	}
	ok = true
	mf := w.ManifestFile
	if fi, err := os.Lstat(dst); err == nil {
		mf.MTime = fi.ModTime().UnixNano()
	}
	return mf, nil
}

func writeContent(tmp string, w want) error {
	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return fmt.Errorf("materialise: %w", err)
	}
	h := sha256.New()
	var src io.Reader = bytes.NewReader(w.content)
	if w.from != "" {
		in, err := os.Open(w.from)
		if err != nil {
			f.Close()
			return fmt.Errorf("materialise: %w", err)
		}
		defer in.Close()
		src = in
	}
	if _, err := io.Copy(io.MultiWriter(f, h), src); err != nil {
		f.Close()
		return fmt.Errorf("materialise: %w", err)
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return fmt.Errorf("materialise: %w", err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("materialise: %w", err)
	}
	if got := hex.EncodeToString(h.Sum(nil)); got != w.SHA256 {
		return fmt.Errorf("materialise: %s changed while it was copied (sha256 %s, want %s)", w.from, got, w.SHA256)
	}
	if err := os.Chmod(tmp, fileMode(w.Exec)); err != nil {
		return fmt.Errorf("materialise: %w", err)
	}
	return nil
}

// mkdirs creates dir below base, refusing to pass through a symlink (a directory replaced by
// a link must not redirect bob's writes outside the owned directory).
func mkdirs(base, dir string) error {
	if err := os.MkdirAll(filepath.Dir(base), 0o755); err != nil {
		return fmt.Errorf("materialise: %w", err)
	}
	rel, err := filepath.Rel(filepath.Dir(base), dir)
	if err != nil || strings.HasPrefix(rel, "..") {
		return fmt.Errorf("materialise: %s is outside %s", dir, base)
	}
	cur := filepath.Dir(base)
	for _, part := range strings.Split(rel, string(filepath.Separator)) {
		cur = filepath.Join(cur, part)
		fi, err := os.Lstat(cur)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			if err := os.Mkdir(cur, 0o755); err != nil && !errors.Is(err, fs.ErrExist) {
				return fmt.Errorf("materialise: %w", err)
			}
		case err != nil:
			return fmt.Errorf("materialise: %w", err)
		case !fi.IsDir():
			return fmt.Errorf("materialise: %s is not a directory", cur)
		}
	}
	return nil
}

// removeEmptyDirs removes the empty directories below abs, deepest first (abs itself stays).
func removeEmptyDirs(abs string, keep []string) {
	skip := map[string]bool{}
	for _, k := range keep {
		skip[k] = true
	}
	var dirs []string
	_ = filepath.WalkDir(abs, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() && p != abs {
			rel, _ := filepath.Rel(abs, p)
			if first, _, _ := strings.Cut(filepath.ToSlash(rel), "/"); skip[first] {
				return filepath.SkipDir
			}
			dirs = append(dirs, p)
		}
		return nil
	})
	sort.Slice(dirs, func(i, j int) bool { return len(dirs[i]) > len(dirs[j]) })
	for _, d := range dirs {
		_ = os.Remove(d) // fails while not empty
	}
}

// removeEmptyParents removes the now empty parents of a pruned owned directory up to the repo.
func removeEmptyParents(repo, dir string) {
	for d := path.Dir(dir); d != "." && d != "/"; d = path.Dir(d) {
		if os.Remove(filepath.Join(repo, filepath.FromSlash(d))) != nil {
			return
		}
	}
}

// writeRecord writes source to the repo-relative file rel (atomic); a .bob directory it lands in
// gets bob's ignore-everything .gitignore.
func writeRecord(repo, rel, source string) error {
	if !validRel(rel) {
		return fmt.Errorf("materialise: invalid record path %q", rel)
	}
	p := filepath.Join(repo, filepath.FromSlash(rel))
	if b, err := os.ReadFile(p); err == nil && string(b) == source+"\n" {
		return nil
	}
	if filepath.Base(filepath.Dir(p)) == ".bob" {
		if err := ensureIgnoreAll(filepath.Dir(p)); err != nil {
			return err
		}
	}
	return writeAtomic(p, []byte(source+"\n"), 0o644)
}

// ensureIgnoreAll gives a .bob directory its .gitignore "*" (SPEC §03.6.6).
func ensureIgnoreAll(dir string) error {
	p := filepath.Join(dir, ".gitignore")
	if _, err := os.Lstat(p); err == nil {
		return nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("materialise: %w", err)
	}
	if err := os.WriteFile(p, []byte("*\n"), 0o644); err != nil {
		return fmt.Errorf("materialise: %w", err)
	}
	return nil
}

// gitTracked lists the files git tracks below dirs (repo-relative); empty when repo is not a git
// work tree or git is not installed (then nothing can be tracked).
func gitTracked(ctx context.Context, repo string, dirs []string) map[string]bool {
	out := map[string]bool{}
	if len(dirs) == 0 {
		return out
	}
	git, err := exec.LookPath("git")
	if err != nil {
		return out
	}
	args := append([]string{"-C", repo, "ls-files", "-z", "--cached", "--"}, dirs...)
	cmd := exec.CommandContext(ctx, git, args...)
	cmd.Env = append(os.Environ(), "GIT_OPTIONAL_LOCKS=0")
	b, err := cmd.Output()
	if err != nil {
		return out
	}
	for _, p := range strings.Split(string(b), "\x00") {
		if p != "" {
			out[p] = true
		}
	}
	return out
}

// lockDir takes an exclusive flock on p, waiting (and watching ctx) while another bob holds it.
func lockDir(ctx context.Context, p string) (func(), error) {
	f, err := os.OpenFile(p, os.O_RDWR|os.O_CREATE, 0o644)
	if err != nil {
		return nil, fmt.Errorf("materialise: %w", err)
	}
	for {
		err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			return func() { _ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN); f.Close() }, nil
		}
		if !errors.Is(err, syscall.EWOULDBLOCK) && !errors.Is(err, syscall.EINTR) {
			f.Close()
			return nil, fmt.Errorf("materialise: lock %s: %w", p, err)
		}
		select {
		case <-ctx.Done():
			f.Close()
			return nil, ctx.Err()
		case <-time.After(50 * time.Millisecond):
		}
	}
}

func randomSuffix() string {
	var b [8]byte
	_, _ = rand.Read(b[:])
	return hex.EncodeToString(b[:])
}
