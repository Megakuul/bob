func write(t *testing.T, p, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	_ = os.Chmod(p, 0o644)
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, p string) string {
	t.Helper()
	b, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// tree makes an output tree with files rel → content.
func tree(t *testing.T, files map[string]string) string {
	t.Helper()
	d := t.TempDir()
	for rel, c := range files {
		write(t, filepath.Join(d, rel), c)
	}
	return d
}

func apply(t *testing.T, o Options, roots ...Root) *Result {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	if o.Now == nil {
		o.Now = func() time.Time { return time.Date(2026, 10, 22, 12, 0, 0, 0, time.UTC) }
	}
	res, err := Apply(ctx, o, roots)
	if err != nil {
		t.Fatalf("Apply: %v", err)
	}
	return res
}

func conflictPaths(res *Result) []string {
	var out []string
	for _, c := range res.Conflicts {
		if c.Code != 1016 {
			out = append(out, "code "+c.Code.ID())
			continue
		}
		out = append(out, c.Args["path"]+": "+c.Args["reason"])
	}
	return out
}

// R-FW-066 (a), (b), (d), (e) and the write protocol on a plain directory.
func TestConflictsForceAdoptPrune(t *testing.T) {
	repo := t.TempDir()
	a := Root{Dir: "gen/a", Label: "//p:a", Source: "/nix/store/aaaa-gen-a", Tree: tree(t, map[string]string{"x.go": "package x\n", "sub/y.go": "package y\n"})}
	b := Root{Dir: "gen/b", Label: "//p:b", Source: "/nix/store/bbbb-gen-b", Tree: tree(t, map[string]string{"z.ts": "export {}\n"})}
	res := apply(t, Options{Repo: repo}, a, b)
	if len(res.Conflicts) != 0 || strings.Join(res.Written, ",") != "gen/a,gen/b" {
		t.Fatalf("first apply: written %v, conflicts %v", res.Written, conflictPaths(res))
	}
	x := filepath.Join(repo, "gen/a/x.go")
	if read(t, x) != "package x\n" || !strings.HasPrefix(read(t, filepath.Join(repo, "gen/a/.gitignore")), "# Generated by bob.") {
		t.Fatalf("files not written")
	}
	if fi, _ := os.Stat(x); fi.Mode().Perm() != 0o444 {
		t.Errorf("mode %v, want 0444", fi.Mode().Perm())
	}
	// no-op
	if res := apply(t, Options{Repo: repo}, a, b); len(res.Written) != 0 || len(res.Conflicts) != 0 {
		t.Errorf("second apply wrote %v, conflicts %v", res.Written, conflictPaths(res))
	}

	// (a) edit one file and add a foreign one in gen/a; gen/b gets new content.
	write(t, x, "package x // edited\n")
	write(t, filepath.Join(repo, "gen/a/mine.go"), "package x\n")
	b.Source, b.Tree = "/nix/store/bbbb-gen-b2", tree(t, map[string]string{"z.ts": "export const z = 1\n"})
	res = apply(t, Options{Repo: repo}, a, b)
	got := strings.Join(conflictPaths(res), "; ")
	if got != "gen/a/mine.go: bob did not write it; gen/a/x.go: it was edited after bob wrote it" &&
		got != "gen/a/x.go: it was edited after bob wrote it; gen/a/mine.go: bob did not write it" {
		t.Errorf("conflicts %q", got)
	}
	if read(t, x) != "package x // edited\n" || read(t, filepath.Join(repo, "gen/b/z.ts")) != "export const z = 1\n" {
		t.Errorf("the conflicting root must stay untouched and the other one be updated")
	}

	// (b) --force moves both to the backup and rewrites.
	res = apply(t, Options{Repo: repo, Force: true}, a, b)
	if len(res.Conflicts) != 0 {
		t.Fatalf("--force: conflicts %v", conflictPaths(res))
	}
	bk := filepath.Join(repo, ".bob/gen/backup/20261022T120000Z/gen/a")
	if read(t, filepath.Join(bk, "x.go")) != "package x // edited\n" || read(t, filepath.Join(bk, "mine.go")) != "package x\n" {
		t.Errorf("backup missing")
	}
	if read(t, x) != "package x\n" {
		t.Errorf("--force did not rewrite x.go")
	}
	if _, err := os.Stat(filepath.Join(repo, "gen/a/mine.go")); err == nil {
		t.Errorf("foreign file still in the owned directory after --force")
	}

	// (e) without the manifest identical files are adopted, nothing is written.
	if err := os.Remove(filepath.Join(repo, ManifestPath)); err != nil {
		t.Fatal(err)
	}
	fi1, _ := os.Stat(x)
	res = apply(t, Options{Repo: repo}, a, b)
	if len(res.Conflicts) != 0 {
		t.Fatalf("adopt: conflicts %v", conflictPaths(res))
	}
	if fi2, _ := os.Stat(x); !fi2.ModTime().Equal(fi1.ModTime()) {
		t.Errorf("adopting rewrote x.go")
	}

	// (d) a recipe removed: prune removes its files, .gitignore and empty parents.
	res = apply(t, Options{Repo: repo, Prune: true}, b)
	if len(res.Conflicts) != 0 {
		t.Fatalf("prune: conflicts %v", conflictPaths(res))
	}
	if _, err := os.Stat(filepath.Join(repo, "gen/a")); err == nil {
		t.Errorf("gen/a still exists after prune")
	}
	if _, err := os.Stat(filepath.Join(repo, "gen/b/z.ts")); err != nil {
		t.Errorf("gen/b pruned: %v", err)
	}
	m, _ := readManifest(repo)
	if _, ok := m.Roots["gen/a"]; ok || len(m.Roots) != 1 {
		t.Errorf("manifest roots %v", m.Roots)
	}
}

// (f) an interrupted write: temp files are removed, a pending manifest entry is honoured.
func TestInterruptedWrite(t *testing.T) {
	repo := t.TempDir()
	a := Root{Dir: "gen", Label: "//p:a", Source: "/nix/store/aaaa-gen", Tree: tree(t, map[string]string{"x": "1\n"})}
	apply(t, Options{Repo: repo}, a)
	// Simulate a crash during the next write: pending names the new content, x is already
	// new, a temp file is left.
	a2 := Root{Dir: "gen", Label: "//p:a", Source: "/nix/store/aaab-gen", Tree: tree(t, map[string]string{"x": "2\n", "y": "3\n"})}
	m, _ := readManifest(repo)
	r := m.Roots["gen"]
	ap := &applier{o: Options{Repo: repo}, m: m}
	files, err := ap.wanted(a2)
	if err != nil {
		t.Fatal(err)
	}
	r.PendingSource, r.Pending = a2.Source, map[string]ManifestFile{}
	for rel, w := range files {
		r.Pending[rel] = w.ManifestFile
	}
	m.Roots["gen"] = r
	if err := writeManifest(repo, m); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(repo, "gen/x"), "2\n")
	write(t, filepath.Join(repo, "gen/.bob-tmp-123"), "partial")
	res := apply(t, Options{Repo: repo}, a2)
	if len(res.Conflicts) != 0 {
		t.Fatalf("conflicts %v", conflictPaths(res))
	}
	if _, err := os.Stat(filepath.Join(repo, "gen/.bob-tmp-123")); err == nil {
		t.Errorf("temp file left")
	}
	if read(t, filepath.Join(repo, "gen/y")) != "3\n" {
		t.Errorf("y not written")
	}
	m, _ = readManifest(repo)
	if r := m.Roots["gen"]; r.Source != a2.Source || len(r.Pending) != 0 || len(r.Files) != 3 {
		t.Errorf("manifest root %+v", r)
	}
}

// node_modules: a directory of symlinks into the store (targets mapped to the store's host
// path), .vite kept, .bin wrappers executable, a record file with the store path; a foreign
// node_modules (npm install) is a conflict.
func TestSymlinkTreeKeepAndRecord(t *testing.T) {
	repo := t.TempDir()
	out := t.TempDir()
	if err := os.Symlink("/nix/store/1111-npm-react-19.0.0/node_modules/react", filepath.Join(out, "react")); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(out, "@types"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("/nix/store/2222-npm-@types+node/node_modules/@types/node", filepath.Join(out, "@types/node")); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(out, ".bin/tsc"), "#!/bin/sh\nexec node tsc\n")
	if err := os.Chmod(filepath.Join(out, ".bin/tsc"), 0o555); err != nil {
		t.Fatal(err)
	}
	r := Root{Dir: "web/node_modules", Label: "//web:web", Source: "/nix/store/3333-node_modules-web", Tree: out,
		LinkStore: "/home/u/.bob/nix/store", Keep: []string{".vite", ".cache"}, Record: "web/.bob/node_modules.path"}

	// A node_modules from npm install is foreign.
	write(t, filepath.Join(repo, "web/node_modules/react/index.js"), "npm's\n")
	if res := apply(t, Options{Repo: repo}, r); len(res.Conflicts) != 1 {
		t.Fatalf("conflicts %v, want web/node_modules/react/index.js", conflictPaths(res))
	}
	if err := os.RemoveAll(filepath.Join(repo, "web/node_modules")); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(repo, "web/node_modules/.vite/deps/x.js"), "cache\n")
	res := apply(t, Options{Repo: repo}, r)
	if len(res.Conflicts) != 0 {
		t.Fatalf("conflicts %v", conflictPaths(res))
	}
	nm := filepath.Join(repo, "web/node_modules")
	if got, _ := os.Readlink(filepath.Join(nm, "react")); got != "/home/u/.bob/nix/store/1111-npm-react-19.0.0/node_modules/react" {
		t.Errorf("react -> %q", got)
	}
	if got, _ := os.Readlink(filepath.Join(nm, "@types/node")); got != "/home/u/.bob/nix/store/2222-npm-@types+node/node_modules/@types/node" {
		t.Errorf("@types/node -> %q", got)
	}
	if fi, err := os.Stat(filepath.Join(nm, ".bin/tsc")); err != nil || fi.Mode().Perm() != 0o555 {
		t.Errorf(".bin/tsc: %v %v", fi, err)
	}
	if read(t, filepath.Join(nm, ".vite/deps/x.js")) != "cache\n" {
		t.Errorf(".vite was touched")
	}
	if read(t, filepath.Join(repo, "web/.bob/node_modules.path")) != r.Source+"\n" || read(t, filepath.Join(repo, "web/.bob/.gitignore")) != "*\n" {
		t.Errorf("record not written")
	}
	// A dependency removed and one replaced.
	if err := os.Remove(filepath.Join(out, "@types/node")); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(out, "react")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("/nix/store/4444-npm-react-19.1.0/node_modules/react", filepath.Join(out, "react")); err != nil {
		t.Fatal(err)
	}
	r.Source = "/nix/store/5555-node_modules-web"
	if res := apply(t, Options{Repo: repo}, r); len(res.Conflicts) != 0 {
		t.Fatalf("conflicts %v", conflictPaths(res))
	}
	if got, _ := os.Readlink(filepath.Join(nm, "react")); !strings.Contains(got, "4444-npm-react-19.1.0") {
		t.Errorf("react -> %q", got)
	}
	if _, err := os.Lstat(filepath.Join(nm, "@types")); err == nil {
		t.Errorf("@types left behind")
	}
}

// (c) a git-tracked file in an owned directory is refused, with and without --force.
func TestTrackedFileRefused(t *testing.T) {
	git, err := exec.LookPath("git")
	if err != nil {
		t.Skip("git not installed")
	}
	repo := t.TempDir()
	write(t, filepath.Join(repo, "gen/x"), "mine\n")
	for _, args := range [][]string{{"init", "-q"}, {"add", "gen/x"}} {
		cmd := exec.Command(git, append([]string{"-C", repo}, args...)...)
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v %s", args, err, out)
		}
	}
	r := Root{Dir: "gen", Label: "//p:a", Source: "/nix/store/aaaa-gen", Tree: tree(t, map[string]string{"x": "bob\n"})}
	for _, force := range []bool{false, true} {
		res := apply(t, Options{Repo: repo, Force: force}, r)
		if got := strings.Join(conflictPaths(res), ";"); got != "gen/x: it is tracked by git" {
			t.Errorf("force=%v: conflicts %q", force, got)
		}
		if read(t, filepath.Join(repo, "gen/x")) != "mine\n" {
			t.Errorf("force=%v: tracked file overwritten", force)
		}
	}
}

// Nested and shared owned directories are definition errors.
