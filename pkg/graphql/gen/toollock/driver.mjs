// bob's graphql-codegen driver (SPEC §03.6.5): calls the plugin API directly, without the CLI
// and without codegen.yml. Usage: node driver.mjs JOB.json, where JOB.json is
// {"out": file, "schema": [files], "documents": [files], "scalars": {name: type}}.
// Paths are relative to the working directory (the repository layout), so messages name
// repository files. Errors print the message only, never a Node stack trace into the store.
import fs from "node:fs";
import { codegen } from "@graphql-codegen/core";
import * as typescript from "@graphql-codegen/typescript";
import * as typescriptOperations from "@graphql-codegen/typescript-operations";
import { parse, concatAST, Source } from "graphql";

function fail(e) {
  const msg = (e && (e.message || String(e))) || "unknown error";
  const loc = e && e.locations && e.locations[0] ? `:${e.locations[0].line}:${e.locations[0].column}` : "";
  const src = e && e.source && e.source.name && e.source.name !== "GraphQL request" ? e.source.name : "";
  console.error(`${src}${loc}${src || loc ? ": " : ""}${msg}`);
  process.exit(1);
}
process.on("uncaughtException", fail);
process.on("unhandledRejection", fail);

const job = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const read = (f) => parse(new Source(fs.readFileSync(f, "utf8"), f));
const schema = concatAST(job.schema.map(read));
const documents = job.documents.map((f) => ({ location: f, document: read(f) }));
const text = await codegen({
  filename: job.out,
  schema,
  documents,
  config: { enumsAsTypes: true, useTypeImports: true, scalars: job.scalars },
  plugins: [{ typescript: {} }, { typescriptOperations: {} }],
  pluginMap: { typescript, typescriptOperations },
});
fs.writeFileSync(job.out, "// Code generated by bob (graphql-codegen). DO NOT EDIT.\n" + text);
