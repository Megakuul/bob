// keepRoots is the number of newest generations whose store paths keep a GC root (R-INST-005).
const keepRoots = 5

// shimHeader starts every shim bob install writes; a file in binDir without it is not bob's.
const shimHeader = "#!/bin/sh\n# Code generated by bob install ("

// genEntry is one installed release of a generation (SPEC §02.8 Files). BinDir is set only
// when the entry's shims live outside the default bin directory (--bin-dir).
type genEntry struct {
	Name       string            `json:"name"`
	Registry   string            `json:"registry"`
	Ref        string            `json:"ref"`
	Version    string            `json:"version"`
	Platform   string            `json:"platform"`
	StorePaths []string          `json:"storePaths"`
	Bins       map[string]string `json:"bins"`
	BinDir     string            `json:"binDir,omitempty"`
}

// generation is generations/<n>.json.
type generation struct {
	V       int        `json:"v"`
	N       int        `json:"n"`
	Created string     `json:"created"`
	Entries []genEntry `json:"entries"`
}

func (g *generation) entry(name string) *genEntry {
	for i := range g.Entries {
		if g.Entries[i].Name == name {
			return &g.Entries[i]
		}
	}
	return nil
}

// shimName is the file name of bin's shim: the bin itself, or "<as>-<bin>" for an entry
// installed under another name (--as).
func (en *genEntry) shimName(bin string) string {
	if en.Name == en.Ref {
		return bin
	}
	return en.Name + "-" + bin
}

func (en *genEntry) binNames() []string {
	out := make([]string, 0, len(en.Bins))
	for b := range en.Bins {
		out = append(out, b)
	}
	sort.Strings(out)
	return out
}

// profile is the install state of one user: <store home>/install (generations, current, lock)
// and the GC roots below <store home>/nix/var/nix/gcroots/bob-install.
type profile struct {
	home   string // bob's state home (the store)
	dir    string // <home>/install
	binDir string // default bin directory
}

func (e *env) profile() (*profile, error) {
	home, err := store.HomeDir("")
	if err != nil {
		return nil, err
	}
	return &profile{home: home, dir: filepath.Join(home, "install"), binDir: e.defaultBinDir()}, nil
}

func (p *profile) genDir() string   { return filepath.Join(p.dir, "generations") }
func (p *profile) rootsDir() string { return filepath.Join(p.home, "nix", "var", "nix", "gcroots", "bob-install") }

// hostPath is where a store path lies outside bob's namespace.
func (p *profile) hostPath(sp string) string { return filepath.Join(p.home, sp) }

// lock takes the profile's flock (every change of generations, current and shims holds it);
// a killed bob releases it with its process. Stale temporary files of a killed run are removed.
func (p *profile) lock() (func(), error) {
	if err := os.MkdirAll(p.genDir(), 0o755); err != nil {
		return nil, diag.New(7002, "reason", err.Error())
	}
	f, err := os.OpenFile(filepath.Join(p.dir, "lock"), os.O_RDWR|os.O_CREATE, 0o644)
	if err != nil {
		return nil, diag.New(7002, "reason", err.Error())
	}
	for {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX)
		if !errors.Is(err, syscall.EINTR) {
			break
		}
	}
	if err != nil {
		f.Close()
		return nil, fmt.Errorf("install lock: %w", err)
	}
	for _, d := range []string{p.dir, p.genDir(), p.rootsDir()} {
		ents, _ := os.ReadDir(d)
		for _, en := range ents {
			if strings.HasPrefix(en.Name(), ".tmp-") {
				_ = os.RemoveAll(filepath.Join(d, en.Name()))
			}
		}
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		f.Close()
	}, nil
}

// current returns the generation `current` points to; an empty generation 0 when none.
func (p *profile) current() (*generation, error) {
	l, err := os.Readlink(filepath.Join(p.dir, "current"))
	if errors.Is(err, fs.ErrNotExist) {
		return &generation{V: 1}, nil
	}
	if err != nil {
		return nil, diag.New(7002, "reason", err.Error())
	}
	n, ok := genNumber(filepath.Base(l))
	if !ok {
		return nil, diag.New(7002, "reason", "install/current points to "+l)
	}
	return p.read(n)
}

func (p *profile) read(n int) (*generation, error) {
	b, err := os.ReadFile(filepath.Join(p.genDir(), strconv.Itoa(n)+".json"))
	if err != nil {
		return nil, diag.New(7002, "reason", fmt.Sprintf("generation %d: %v", n, err))
	}
	g := &generation{}
	if err := json.Unmarshal(b, g); err != nil || g.N != n {
		return nil, diag.New(7002, "reason", fmt.Sprintf("generation %d is damaged", n))
	}
	return g, nil
}

// genNumber parses "<n>.json".
func genNumber(name string) (int, bool) {
	s, ok := strings.CutSuffix(name, ".json")
	n, err := strconv.Atoi(s)
	return n, ok && err == nil && n > 0 && strconv.Itoa(n) == s
}

// numbers lists the generation numbers on disk, ascending.
func (p *profile) numbers() []int {
	ents, _ := os.ReadDir(p.genDir())
	var out []int
	for _, en := range ents {
		if n, ok := genNumber(en.Name()); ok {
			out = append(out, n)
		}
	}
	sort.Ints(out)
	return out
}

// commit writes entries as a new generation and makes it current: GC roots first, then the
// generation file (create-only), then the atomic flip of `current`, then the old roots are
// pruned. A kill at any point leaves `current` on a complete generation.
func (p *profile) commit(entries []genEntry) (*generation, error) {
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name < entries[j].Name })
	n := 1
	if nums := p.numbers(); len(nums) > 0 {
		n = nums[len(nums)-1] + 1
	}
	g := &generation{V: 1, N: n, Created: time.Now().UTC().Format(time.RFC3339), Entries: entries}
	if g.Entries == nil {
		g.Entries = []genEntry{}
	}
	if err := p.writeRoots(g); err != nil {
		return nil, err
	}
	b, err := json.MarshalIndent(g, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("generation: %w", err)
	}
	if err := createOnly(filepath.Join(p.genDir(), strconv.Itoa(n)+".json"), append(b, '\n')); err != nil {
		return nil, err
	}
	if err := p.flip(n); err != nil {
		return nil, err
	}
	p.pruneRoots(n)
	return g, nil
}

// createOnly writes path through a synced temporary file and a hard link, which fails when
// path exists: a generation file is never replaced.
func createOnly(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-gen-*")
	if err != nil {
		return diag.New(7002, "reason", err.Error())
	}
	defer os.Remove(tmp.Name())
	_, err = tmp.Write(data)
	if err == nil {
		err = tmp.Chmod(0o644)
	}
	if err == nil {
		err = tmp.Sync()
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Link(tmp.Name(), path)
	}
	if err != nil {
		return diag.New(7002, "reason", err.Error())
	}
	syncDir(filepath.Dir(path))
	return nil
}

func syncDir(dir string) {
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		d.Close()
	}
}

// flip points `current` at generation n (symlink to a temporary name, then rename).
func (p *profile) flip(n int) error {
	tmp := filepath.Join(p.dir, ".tmp-current-"+strconv.Itoa(os.Getpid()))
	_ = os.Remove(tmp)
	if err := os.Symlink("generations/"+strconv.Itoa(n)+".json", tmp); err != nil {
		return diag.New(7002, "reason", err.Error())
	}
	if err := os.Rename(tmp, filepath.Join(p.dir, "current")); err != nil {
		_ = os.Remove(tmp)
		return diag.New(7002, "reason", err.Error())
	}
	syncDir(p.dir)
	return nil
}

// writeRoots makes gcroots/bob-install/<n>/ hold one symlink per store path of g (Nix follows
// them inside bob's namespace, where /nix/store is bob's store).
func (p *profile) writeRoots(g *generation) error {
	if err := os.MkdirAll(p.rootsDir(), 0o755); err != nil {
		return diag.New(7002, "reason", err.Error())
	}
	tmp, err := os.MkdirTemp(p.rootsDir(), ".tmp-")
	if err != nil {
		return diag.New(7002, "reason", err.Error())
	}
	for _, en := range g.Entries {
		for _, sp := range en.StorePaths {
			l := filepath.Join(tmp, filepath.Base(sp))
			if err := os.Symlink(sp, l); err != nil && !errors.Is(err, fs.ErrExist) {
				_ = os.RemoveAll(tmp)
				return diag.New(7002, "reason", err.Error())
			}
		}
	}
	dst := filepath.Join(p.rootsDir(), strconv.Itoa(g.N))
	_ = os.RemoveAll(dst) // roots of a generation number a killed run never committed
	if err := os.Rename(tmp, dst); err != nil {
		_ = os.RemoveAll(tmp)
		return diag.New(7002, "reason", err.Error())
	}
	return nil
}

// pruneRoots keeps the roots of the newest keepRoots generations and of cur; older
// generations lose theirs (their files stay; bob gc may collect their paths).
func (p *profile) pruneRoots(cur int) {
	nums := p.numbers()
	keep := map[string]bool{strconv.Itoa(cur): true}
	for i := len(nums) - 1; i >= 0 && i >= len(nums)-keepRoots; i-- {
		keep[strconv.Itoa(nums[i])] = true
	}
	ents, _ := os.ReadDir(p.rootsDir())
	for _, en := range ents {
		if !keep[en.Name()] && !strings.HasPrefix(en.Name(), ".tmp-") {
			_ = os.RemoveAll(filepath.Join(p.rootsDir(), en.Name()))
		}
	}
}

// rollbackTo makes the existing generation n current again; its store paths must still be
// in bob's store.
func (p *profile) rollbackTo(n int) (*generation, error) {
	g, err := p.read(n)
	if err != nil {
		return nil, err
	}
	for _, en := range g.Entries {
		for _, sp := range en.StorePaths {
			if _, err := os.Lstat(p.hostPath(sp)); err != nil {
				return nil, diag.New(4, "flag", "bob rollback", "what",
					fmt.Sprintf("a generation whose programs are still in bob's store (generation %d's %s was collected; install it again)", n, en.Name))
			}
		}
	}
	if _, err := os.Lstat(filepath.Join(p.rootsDir(), strconv.Itoa(n))); err != nil {
		if err := p.writeRoots(g); err != nil {
			return nil, err
		}
	}
	if err := p.flip(n); err != nil {
		return nil, err
	}
	p.pruneRoots(n)
	return g, nil
}

// entryBinDir is the bin directory of an entry's shims.
func (p *profile) entryBinDir(en *genEntry) string {
	if en.BinDir != "" {
		return en.BinDir
	}
	return p.binDir
}

// conflict reports the first shim of en that clashes with another entry of entries or with a
// file in its bin directory that bob did not create (BOB-E-0004, SPEC §02.8 step 6).
func (p *profile) conflict(en *genEntry, entries []genEntry) error {
	dir := p.entryBinDir(en)
	for _, b := range en.binNames() {
		shim := en.shimName(b)
		for i := range entries {
			o := &entries[i]
			if o.Name == en.Name || p.entryBinDir(o) != dir {
				continue
			}
			for ob := range o.Bins {
				if o.shimName(ob) == shim {
					return conflictDiag(shim + " is already provided by " + o.Name + "; use --as")
				}
			}
		}
		path := filepath.Join(dir, shim)
		if _, err := os.Lstat(path); err == nil && !isShim(path) {
			return conflictDiag(tildePath(path) + " exists and was not created by bob; remove it or use --as")
		}
	}
	return nil
}

func conflictDiag(cause string) error {
	d := diag.New(4, "flag", "bob install", "what", "a free command name")
	d.Cause = cause
	return d
}

// isShim reports whether path is a regular file that starts with bob install's shim header.
func isShim(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	if fi, err := f.Stat(); err != nil || !fi.Mode().IsRegular() || fi.Size() > 4096 {
		return false
	}
	b := make([]byte, len(shimHeader))
	n, _ := io.ReadFull(f, b)
	return string(b[:n]) == shimHeader
}

// shimText is the shim of SPEC §02.8 step 5.
func shimText(bob string, en *genEntry, bin string) string {
	return shimHeader + en.Ref + " " + en.Version + "). DO NOT EDIT.\n" +
		"exec \"${BOB:-" + shQuoteInDouble(bob) + "}\" exec --installed " + en.Name + " -- " + bin + " \"$@\"\n"
}

// shQuoteInDouble escapes s for the inside of a double-quoted sh word.
func shQuoteInDouble(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "$", `\$`, "`", "\\`")
	return r.Replace(s)
}

// syncShims makes the shims match generation g: every bin of every entry has its shim with
// the current text, and every shim bob wrote earlier for something g no longer provides is
// removed (from the default bin directory and every bin directory of g and prev). Running it
// again after a kill finishes the job.
func (p *profile) syncShims(bob string, g, prev *generation) error {
	want := map[string]string{}
	dirs := map[string]bool{p.binDir: true}
	for _, gen := range []*generation{g, prev} {
		if gen == nil {
			continue
		}
		for i := range gen.Entries {
			dirs[p.entryBinDir(&gen.Entries[i])] = true
		}
	}
	for i := range g.Entries {
		en := &g.Entries[i]
		dir := p.entryBinDir(en)
		for _, b := range en.binNames() {
			want[filepath.Join(dir, en.shimName(b))] = shimText(bob, en, b)
		}
	}
	for path, text := range want {
		if cur, err := os.ReadFile(path); err == nil && string(cur) == text {
			continue
		}
		if _, err := os.Lstat(path); err == nil && !isShim(path) {
			continue // a file the user created meanwhile; install refused it before
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return diag.New(7002, "reason", err.Error())
		}
		if err := writeAtomic(path, []byte(text), 0o755); err != nil {
			return err
		}
	}
	for dir := range dirs {
		ents, _ := os.ReadDir(dir)
		for _, en := range ents {
			path := filepath.Join(dir, en.Name())
			if _, ok := want[path]; !ok && en.Type().IsRegular() && isShim(path) {
				_ = os.Remove(path)
			}
		}
	}
	return nil
}

// tildePath writes a path below $HOME as ~/….
func tildePath(path string) string {
	home := os.Getenv("HOME")
	if home != "" && (path == home || strings.HasPrefix(path, home+"/")) {
		return "~" + strings.TrimPrefix(path, home)
	}
	return path
}

// listBins returns the programs of a store path's bin/ directory (executable regular files
// and symlinks with a name that is safe in a shim): name → store path of the program.
func (p *profile) listBins(sp string) map[string]string {
	out := map[string]string{}
	ents, err := os.ReadDir(filepath.Join(p.hostPath(sp), "bin"))
	if err != nil {
		return out
	}
	for _, en := range ents {
		name := en.Name()
		if !safeName(name) {
			continue
		}
		fi, err := os.Stat(filepath.Join(p.hostPath(sp), "bin", name))
		if err != nil {
			// a symlink to another store path (absolute /nix/store/…): it resolves inside
			// the namespace; keep it when it is a link.
			if en.Type()&fs.ModeSymlink == 0 {
				continue
			}
		} else if !fi.Mode().IsRegular() || fi.Mode().Perm()&0o111 == 0 {
			continue
		}
		out[name] = sp + "/bin/" + name
	}
	return out
}

// safeName accepts a program or entry name that needs no quoting in a shim.
func safeName(s string) bool {
	if s == "" || len(s) > 128 || s[0] == '.' || s[0] == '-' {
		return false
	}
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("._+-", r)) {
			return false
		}
	}
	return true
}
