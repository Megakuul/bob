package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/megakuul/bob/pkg/cli/devenv"
)

// toolWrapperDir is the directory of the dev session's wrappers of tools that need their own
// variables (gopls: GOFLAGS=-tags=bob, which makes it see bob.go): a language server that an
// editor starts from inside the session finds the wrapper first on PATH, where the shims of
// the hook are not used (A565). The tool env of the shim (devenv.Tool.Env) is the source.
func toolWrapperDir(root string) string { return filepath.Join(root, ".bob", "dev-bin") }

// writeToolWrappers writes one wrapper script per tool of f that has variables of its own and
// returns the directory, "" when there is none. Variables that hold flags (GOFLAGS) are
// appended to the caller's value so that the session's -mod=readonly stays.
func writeToolWrappers(f *devenv.File, root string) (string, error) {
	dir := toolWrapperDir(root)
	var names []string
	for n, t := range f.Tools {
		if len(t.Env) > 0 && t.Path != "" {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		return "", nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	for _, n := range names {
		t := f.Tools[n]
		var b strings.Builder
		b.WriteString("#!/bin/sh\n# Code generated by bob. DO NOT EDIT.\n")
		keys := make([]string, 0, len(t.Env))
		for k := range t.Env {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			v := shQuote(t.Env[k])
			if k == "GOFLAGS" {
				fmt.Fprintf(&b, "GOFLAGS=\"${GOFLAGS:+$GOFLAGS }\"%s; export GOFLAGS\n", v)
			} else {
				fmt.Fprintf(&b, "%s=%s; export %s\n", k, v, k)
			}
		}
		fmt.Fprintf(&b, "exec %s \"$@\"\n", shQuote(t.Path))
		p := filepath.Join(dir, n)
		tmp := p + ".tmp"
		if err := os.WriteFile(tmp, []byte(b.String()), 0o755); err != nil {
			return "", err
		}
		if err := os.Rename(tmp, p); err != nil {
			return "", err
		}
	}
	return dir, nil
}

func shQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// withPathFirst returns env with dir at the front of PATH.
func withPathFirst(env []string, dir string) []string {
	out := make([]string, 0, len(env))
	done := false
	for _, kv := range env {
		if v, ok := strings.CutPrefix(kv, "PATH="); ok && !done {
			kv, done = "PATH="+dir+":"+v, true
		}
		out = append(out, kv)
	}
	if !done {
		out = append(out, "PATH="+dir)
	}
	return out
}
