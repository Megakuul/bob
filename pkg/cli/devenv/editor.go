// Editors are the editors bob editor knows (SPEC §02.7.6).
var Editors = []string{"vscode", "nvim", "helix", "zed", "jetbrains"}

// Settings is what bob editor prints and writes for one editor.
type Settings struct {
	File   string         // project-relative settings file ("" = nothing to write)
	Values map[string]any // top-level keys merged into File
	Text   string         // instead of Values: the whole content of File, a file bob owns (A550)
	Note   string         // what to do instead / in addition (human output)
}

// EditorSettings returns the settings of editor for a project that uses the ecosystems ecos
// (bob.lock section names: "go", "rust", "cc", "npm", "ocaml"). Only keys of ecosystems in use
// are included (R-DEV-011).
func EditorSettings(editor string, ecos []string) (Settings, error) {
	uses := map[string]bool{}
	for _, e := range ecos {
		uses[e] = true
	}
	uses["go"] = true // bob.go is Go: every project needs gopls (with the bob build tag)
	shim := func(tool string) string { return "${workspaceFolder}/.bob/bin/" + tool }
	switch editor {
	case "vscode":
		v := map[string]any{"files.watcherExclude": map[string]any{"**/.bob/**": true}}
		if uses["go"] {
			v["go.alternateTools"] = map[string]any{"go": shim("go"), "gopls": shim("gopls")}
			v["go.toolsManagement.autoUpdate"] = false
			v["gopls"] = map[string]any{"build.buildFlags": []any{"-tags=bob"}, "build.directoryFilters": []any{"-.bob"}}
		}
		if uses["rust"] {
			v["rust-analyzer.server.path"] = shim("rust-analyzer")
		}
		if uses["cc"] {
			v["clangd.path"] = shim("clangd")
		}
		note := ""
		if uses["npm"] {
			note = "VS Code's built-in TypeScript reads node_modules itself: start it with bob dev -- code --new-window --user-data-dir .bob/vscode ."
		}
		return Settings{File: ".vscode/settings.json", Values: v, Note: note}, nil
	case "zed":
		lsp := map[string]any{}
		for _, s := range []struct{ eco, server, tool string }{
			{"go", "gopls", "gopls"}, {"rust", "rust-analyzer", "rust-analyzer"}, {"cc", "clangd", "clangd"},
			{"npm", "typescript-language-server", "typescript-language-server"}, {"ocaml", "ocamllsp", "ocamllsp"},
		} {
			if uses[s.eco] {
				lsp[s.server] = map[string]any{"binary": map[string]any{"path": ".bob/bin/" + s.tool}}
			}
		}
		return Settings{File: ".zed/settings.json", Values: map[string]any{"lsp": lsp},
			Note: "Zed finds the language servers on PATH with the shell hook; these entries are for Zed builds that ignore PATH."}, nil
	case "nvim":
		return Settings{File: ".nvim.lua", Text: nvimLua(uses),
			Note: "Neovim reads .nvim.lua with :set exrc (it asks once whether to trust it: :trust); without exrc, source it from your config. It starts the project's language servers from .bob/bin, so they see bob.go (build tag bob) and the framework module."}, nil
	case "helix":
		return Settings{File: ".helix/languages.toml", Text: helixToml(uses),
			Note: "Start hx in the project root: the language servers are .bob/bin shims, which see bob.go (build tag bob) and the framework module."}, nil
	case "jetbrains":
		return Settings{Note: "JetBrains IDEs read SDK and toolchain files themselves: start the IDE with bob dev -- <ide> ."}, nil
	}
	return Settings{}, diag.New(1, "kind", "editor", "name", editor, "suggest", strings.Join(Editors, ", "))
}

// ownedHeader starts every file bob editor writes whole (Settings.Text); --write replaces only
// files that start with it.
const ownedHeader = "generated by bob editor"

// servers are the language servers per ecosystem as the editors name them.
var servers = []struct {
	eco, tool, lspconfig, helix string
	args                        []string
}{
	{"go", "gopls", "gopls", "gopls", nil},
	{"rust", "rust-analyzer", "rust_analyzer", "rust-analyzer", nil},
	{"cc", "clangd", "clangd", "clangd", nil},
	{"npm", "typescript-language-server", "ts_ls", "typescript-language-server", []string{"--stdio"}},
	{"ocaml", "ocamllsp", "ocamllsp", "ocamllsp", nil},
}

// nvimLua is .nvim.lua: the language servers of the project's ecosystems, started from the
// project's .bob/bin (Neovim 0.11 vim.lsp.config, else nvim-lspconfig).
func nvimLua(uses map[string]bool) string {
	var b strings.Builder
	b.WriteString("-- " + ownedHeader + " nvim; do not edit (run bob editor nvim --write again).\n")
	b.WriteString("local root = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h')\n")
	b.WriteString("local function setup(name, cfg)\n")
	b.WriteString("  if vim.lsp.config then\n    vim.lsp.config(name, cfg)\n    vim.lsp.enable(name)\n")
	b.WriteString("  else\n    require('lspconfig')[name].setup(cfg)\n  end\nend\n")
	for _, sv := range servers {
		if !uses[sv.eco] {
			continue
		}
		cmd := "root .. '/.bob/bin/" + sv.tool + "'"
		for _, a := range sv.args {
			cmd += ", '" + a + "'"
		}
		b.WriteString("\nsetup('" + sv.lspconfig + "', {\n  cmd = { " + cmd + " },\n")
		if sv.eco == "go" {
			b.WriteString("  settings = { gopls = { buildFlags = { '-tags=bob' }, directoryFilters = { '-.bob' } } },\n")
		}
		b.WriteString("})\n")
	}
	return b.String()
}

// helixToml is .helix/languages.toml for the project's ecosystems.
func helixToml(uses map[string]bool) string {
	var b strings.Builder
	b.WriteString("# " + ownedHeader + " helix; do not edit (run bob editor helix --write again).\n")
	for _, sv := range servers {
		if !uses[sv.eco] {
			continue
		}
		b.WriteString("\n[language-server." + sv.helix + "]\ncommand = \".bob/bin/" + sv.tool + "\"\n")
		if len(sv.args) > 0 {
			b.WriteString("args = [\"" + strings.Join(sv.args, "\", \"") + "\"]\n")
		}
		if sv.eco == "go" {
			b.WriteString("config = { buildFlags = [\"-tags=bob\"], directoryFilters = [\"-.bob\"] }\n")
		}
	}
	return b.String()
}

// Snippet is the settings as indented JSON (what bob editor prints), or the file's text.
func (s Settings) Snippet() string {
	if s.Text != "" {
		return s.Text
	}
	b, _ := encodeJSON(s.Values)
	return string(b)
}

func encodeJSON(v any) ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// maxSettings bounds an editor settings file bob merges into.
const maxSettings = 8 << 20

// Merge merges s into root/s.File: top-level keys of s replace the file's, every other key is
// kept. A file that is not plain JSON (comments, trailing commas) is refused with BOB-E-0004;
// the caller shows the snippet to paste by hand. It reports whether the file changed.
func (s Settings) Merge(root string) (bool, error) {
	if s.File == "" {
		return false, nil
	}
	p := filepath.Join(root, filepath.FromSlash(s.File))
	if s.Text != "" {
		if old, err := os.ReadFile(p); err == nil && !strings.Contains(firstLine(old), ownedHeader) {
			return false, diag.New(4, "flag", s.File, "what", "a file written by bob editor for --write (it has another content); paste the snippet by hand")
		}
		return WriteFile(p, []byte(s.Text), 0o644)
	}
	cur := map[string]any{}
	b, err := readCapped(p, maxSettings)
	switch {
	case err == nil:
		dec := json.NewDecoder(bytes.NewReader(b))
		dec.UseNumber()
		if len(bytes.TrimSpace(b)) > 0 {
			if err := dec.Decode(&cur); err != nil || cur == nil {
				return false, diag.New(4, "flag", s.File, "what", "to be plain JSON without comments for --write; paste the settings by hand")
			}
		}
	case errors.Is(err, fs.ErrNotExist):
	default:
		return false, err
	}
	keys := make([]string, 0, len(s.Values))
	for k := range s.Values {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		cur[k] = s.Values[k]
	}
	out, err := encodeJSON(cur)
	if err != nil {
		return false, err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return false, err
	}
	mode := os.FileMode(0o644)
	if fi, err := os.Stat(p); err == nil {
		mode = fi.Mode().Perm()
	}
	return WriteFile(p, out, mode)
}

// firstLine is the first line of b.
func firstLine(b []byte) string {
	l, _, _ := strings.Cut(string(b), "\n")
	return l
}
