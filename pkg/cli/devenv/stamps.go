package devenv

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"syscall"
)

// Stamps are the eval-key index of the shell hook's fast path (SPEC §02.7.1 step 4, R-DEV-007):
// the size, mtime and inode of every input of the §01 eval key (bob.go files, go.mod, go.sum,
// bob.lock), of every directory a new bob.go could appear in, and of the trust list, as they
// were when env.json was last written. The fast path compares them with stat only: it opens
// no file besides env.json and this index, and runs no evaluator.
type Stamps struct {
	V       int     `json:"v"`
	Bob     string  `json:"bob"`     // the bob that wrote env.json
	EnvHash string  `json:"envHash"` // BOB_ENV_HASH of env.json then
	Files   []Stamp `json:"files"`
}

// Stamp is one stat result; Size -1 = the path did not exist.
type Stamp struct {
	Path  string `json:"p"`
	Size  int64  `json:"s"`
	MTime int64  `json:"m"`
	Ino   uint64 `json:"i"`
}

// maxStamped bounds the walk; a bigger tree gets no stamps (every prompt re-checks).
const maxStamped = 20000

// StampPath is where the stamps of root's shell live: below bob's state home, so the fast path
// never reads the working tree beyond env.json.
func StampPath(home, root, shell string) string {
	h := sha256.Sum256([]byte(root + "\x00" + shell))
	return filepath.Join(home, "devenv", "eval-"+hex.EncodeToString(h[:8])+".json")
}

// CollectStamps stats root's eval-key inputs, the directories they may appear in and the trust
// list at allowPath.
func CollectStamps(root, allowPath, bob, envHash string) (*Stamps, error) {
	s := &Stamps{V: 1, Bob: bob, EnvHash: envHash}
	paths := []string{allowPath}
	var walk func(dir string, depth int) error
	walk = func(dir string, depth int) error {
		if depth > 128 || len(paths) > maxStamped {
			return errors.New("tree too large for the hook's stamps")
		}
		ents, err := os.ReadDir(dir)
		if err != nil {
			return err
		}
		if dir != root {
			for _, e := range ents {
				// A nested project or a module of its own ends the walk (as the eval scan).
				if e.Name() == "bob.lock" || e.Name() == "go.mod" && !bobGoMod(filepath.Join(dir, "go.mod")) {
					paths = append(paths, filepath.Join(dir, e.Name()))
					return nil
				}
			}
		}
		paths = append(paths, dir)
		for _, e := range ents {
			name := e.Name()
			p := filepath.Join(dir, name)
			switch {
			case e.IsDir():
				if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") || name == "node_modules" || name == "testdata" {
					continue
				}
				if err := walk(p, depth+1); err != nil {
					return err
				}
			case name == "bob.go" || name == "go.mod" || name == "go.sum" || name == "bob.lock":
				paths = append(paths, p)
			}
		}
		return nil
	}
	if err := walk(root, 0); err != nil {
		return nil, err
	}
	// Inputs of the eval key outside that walk (replace targets are listed by the evaluator).
	if b, err := readCapped(filepath.Join(root, ".bob", "eval", "index.json"), 16<<20); err == nil {
		var idx map[string]json.RawMessage
		if json.Unmarshal(b, &idx) == nil {
			for rel := range idx {
				if !strings.HasPrefix(rel, "../") && filepath.IsLocal(rel) {
					paths = append(paths, filepath.Join(root, filepath.FromSlash(rel)))
				}
			}
		}
	}
	sort.Strings(paths)
	for i, p := range paths {
		if i > 0 && paths[i-1] == p {
			continue
		}
		s.Files = append(s.Files, stampOf(p))
	}
	return s, nil
}

// bobGoMod reports whether a go.mod is one bob generated (its first line is bob's header).
func bobGoMod(p string) bool {
	f, err := os.Open(p)
	if err != nil {
		return false
	}
	defer f.Close()
	line, _ := bufio.NewReader(f).ReadString('\n')
	return strings.HasPrefix(line, "// Code generated by bob")
}

func stampOf(p string) Stamp {
	var st syscall.Stat_t
	if err := syscall.Lstat(p, &st); err != nil {
		return Stamp{Path: p, Size: -1}
	}
	return Stamp{Path: p, Size: st.Size, MTime: st.Mtim.Nano(), Ino: st.Ino}
}

// Fresh reports whether nothing the stamps cover changed, for the env.json of hash envHash
// written by bob.
func (s *Stamps) Fresh(bob, envHash string) bool { return s.FreshIgnoring(bob, envHash, "") }

// FreshIgnoring is Fresh without the stamp of path ignore (the trust list, when the caller
// checked it itself).
func (s *Stamps) FreshIgnoring(bob, envHash, ignore string) bool {
	if s == nil || s.V != 1 || s.Bob != bob || s.EnvHash != envHash || len(s.Files) == 0 {
		return false
	}
	for _, f := range s.Files {
		if f.Path != ignore && stampOf(f.Path) != f {
			return false
		}
	}
	return true
}

// ReadStamps reads the stamps at p (nil when missing or damaged).
func ReadStamps(p string) *Stamps {
	b, err := readCapped(p, 64<<20)
	if err != nil {
		return nil
	}
	var s Stamps
	if json.Unmarshal(b, &s) != nil {
		return nil
	}
	return &s
}

// WriteStamps writes s to p.
func WriteStamps(p string, s *Stamps) error {
	b, err := json.Marshal(s)
	if err != nil {
		return err
	}
	_, err = WriteFile(p, b, 0o644)
	return err
}
