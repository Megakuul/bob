func TestParseRef(t *testing.T) {
	for in, want := range map[string]installRef{
		"acme/cli":                     {"", "acme", "cli", ""},
		"acme/cli@1.4.2":               {"", "acme", "cli", "1.4.2"},
		"acme/cli@latest":              {"", "acme", "cli", ""},
		"corp:infra/deploytool@1.4":    {"corp", "infra", "deploytool", "1.4"},
		"corp:infra/deploytool@latest": {"corp", "infra", "deploytool", ""},
	} {
		got, err := parseRef(in)
		if err != nil || got != want {
			t.Errorf("parseRef(%q) = %+v, %v; want %+v", in, got, err, want)
		}
	}
	for _, bad := range []string{"", "acme", "acme/", "/cli", "a:b:c/d", "acme/cli@", "acme/../x", "acme/cli@1 2", ":acme/cli"} {
		if _, err := parseRef(bad); err == nil {
			t.Errorf("parseRef(%q) accepted", bad)
		}
	}
}

func testProfile(t *testing.T) *profile {
	h := t.TempDir()
	return &profile{home: h, dir: filepath.Join(h, "install"), binDir: filepath.Join(h, "bin")}
}

func entry(name, version string, bins ...string) genEntry {
	sp := "/nix/store/" + strings.Repeat("a", 32) + "-" + strings.ReplaceAll(name, "/", "-") + "-" + version
	en := genEntry{Name: name, Registry: "default", Ref: name, Version: version, Platform: "linux-arm64", StorePaths: []string{sp}, Bins: map[string]string{}}
	for _, b := range bins {
		en.Bins[b] = sp + "/bin/" + b
	}
	return en
}

func TestProfileGenerations(t *testing.T) {
	p := testProfile(t)
	unlock, err := p.lock()
	if err != nil {
		t.Fatal(err)
	}
	defer unlock()
	cur, err := p.current()
	if err != nil || cur.N != 0 || len(cur.Entries) != 0 {
		t.Fatalf("empty profile: %+v %v", cur, err)
	}
	for i := 1; i <= 7; i++ {
		g, err := p.commit([]genEntry{entry(fmt.Sprintf("acme/t%d", i), "1.0.0", "t")})
		if err != nil || g.N != i {
			t.Fatalf("commit %d: %+v %v", i, g, err)
		}
	}
	if l, _ := os.Readlink(filepath.Join(p.dir, "current")); l != "generations/7.json" {
		t.Errorf("current -> %q", l)
	}
	ents, _ := os.ReadDir(p.rootsDir())
	var names []string
	for _, e := range ents {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	if fmt.Sprint(names) != "[3 4 5 6 7]" {
		t.Errorf("roots %v, want [3 4 5 6 7]", names)
	}
	// rollback to a rootless generation needs its paths in the store
	if _, err := p.rollbackTo(1); err == nil {
		t.Errorf("rollback to a generation whose paths are gone succeeded")
	}
	sp := entry("acme/t1", "1.0.0").StorePaths[0]
	if err := os.MkdirAll(p.hostPath(sp), 0o755); err != nil {
		t.Fatal(err)
	}
	g, err := p.rollbackTo(1)
	if err != nil || g.N != 1 {
		t.Fatalf("rollback: %+v %v", g, err)
	}
	if _, err := os.Lstat(filepath.Join(p.rootsDir(), "1", filepath.Base(sp))); err != nil {
		t.Errorf("rollback did not root generation 1: %v", err)
	}
	// a new generation after a rollback gets the next free number; generation files never change
	g, err = p.commit(nil)
	if err != nil || g.N != 8 {
		t.Errorf("commit after rollback: %+v %v", g, err)
	}
	if err := createOnly(filepath.Join(p.genDir(), "8.json"), []byte("{}")); err == nil {
		t.Errorf("createOnly replaced an existing generation")
	}
}

func TestShimsAndConflicts(t *testing.T) {
	p := testProfile(t)
	if err := os.MkdirAll(p.binDir, 0o755); err != nil {
		t.Fatal(err)
	}
	dt := entry("infra/dt", "0.9.0", "acme", "dt")
	cli := entry("acme/cli", "1.0.0", "acme")
	if err := p.conflict(&cli, []genEntry{dt, cli}); err == nil || !strings.Contains(errCause(err), "acme is already provided by infra/dt; use --as") {
		t.Errorf("clash between entries: %v", err)
	}
	cli.Name = "cli2"
	if err := p.conflict(&cli, []genEntry{dt, cli}); err != nil {
		t.Errorf("--as still clashes: %v", err)
	}
	if err := os.WriteFile(filepath.Join(p.binDir, "dt"), []byte("#!/bin/sh\necho mine\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := p.conflict(&dt, []genEntry{dt}); err == nil || !strings.Contains(errCause(err), "exists and was not created by bob") {
		t.Errorf("foreign file: %v", err)
	}
	if err := os.Remove(filepath.Join(p.binDir, "dt")); err != nil {
		t.Fatal(err)
	}

	g1 := &generation{V: 1, N: 1, Entries: []genEntry{dt, cli}}
	if err := p.syncShims("/usr/bin/bob", g1, nil); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(p.binDir, "cli2-acme"))
	want := "#!/bin/sh\n# Code generated by bob install (acme/cli 1.0.0). DO NOT EDIT.\nexec \"${BOB:-/usr/bin/bob}\" exec --installed cli2 -- acme \"$@\"\n"
	if err != nil || string(b) != want {
		t.Errorf("shim text %q, want %q (%v)", b, want, err)
	}
	if fi, err := os.Stat(filepath.Join(p.binDir, "acme")); err != nil || fi.Mode().Perm() != 0o755 {
		t.Errorf("shim mode: %v %v", fi, err)
	}
	foreign := filepath.Join(p.binDir, "other")
	if err := os.WriteFile(foreign, []byte("x"), 0o755); err != nil {
		t.Fatal(err)
	}
	g2 := &generation{V: 1, N: 2, Entries: []genEntry{cli}}
	if err := p.syncShims("/usr/bin/bob", g2, g1); err != nil {
		t.Fatal(err)
	}
	for _, gone := range []string{"acme", "dt"} {
		if _, err := os.Lstat(filepath.Join(p.binDir, gone)); err == nil {
			t.Errorf("shim %s of an uninstalled entry is still there", gone)
		}
	}
	if _, err := os.Stat(foreign); err != nil {
		t.Errorf("a file bob did not create was removed: %v", err)
	}
	if shQuoteInDouble(`/a b/$x"`) != `/a b/\$x\"` {
		t.Errorf("shQuoteInDouble: %s", shQuoteInDouble(`/a b/$x"`))
	}
}

func errCause(err error) string {
	for _, d := range diagErrors(err) {
		return d.Cause
	}
	return ""
}

func TestCacheURL(t *testing.T) {
	if got := cacheURL("https://bob.example.com", []string{"https://evil.example.org/nix", "https://bob.example.com/nix/"}); got != "https://bob.example.com/nix" {
		t.Errorf("cacheURL = %s", got)
	}
	if got := cacheURL("https://bob.example.com", []string{"https://evil.example.org/nix"}); got != "https://bob.example.com/nix" {
		t.Errorf("a substituter on another host was taken: %s", got)
	}
}
