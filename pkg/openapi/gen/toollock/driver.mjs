// bob's openapi-typescript driver (SPEC §03.6.5): calls the library API, not the CLI.
// Usage: node driver.mjs JOB.json, where JOB.json is {"out": file, "spec": file}; the spec path
// is relative to the working directory (the repository layout), so messages name repository
// files. Errors print the message only, never a Node stack trace into the store.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

// openapi-typescript logs each error itself before it throws; bob prints the thrown message
// once, prefixed with the document's path.
const log = console.error;
console.error = () => {};
let where = "";
function fail(e) {
  log(where + ((e && (e.message || String(e))) || "unknown error"));
  process.exit(1);
}
process.on("uncaughtException", fail);
process.on("unhandledRejection", fail);

const job = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
where = job.spec + ": ";
const ast = await openapiTS(pathToFileURL(path.resolve(job.spec)), { silent: true });
fs.writeFileSync(job.out, "// Code generated by bob (openapi-typescript). DO NOT EDIT.\n" + astToString(ast));
