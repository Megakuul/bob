func (s scenario) registry(t *testing.T) (MemRegistry, map[string][]byte) {
	t.Helper()
	reg := MemRegistry{}
	files := map[string][]byte{}
	names := map[string]bool{}
	for _, p := range s.index {
		names[p.name] = true
	}
	for n := range names {
		var lines []string
		for _, p := range s.index {
			if p.name != n {
				continue
			}
			// crates.io writes absent values as null or leaves them out, never as ""
			var deps []map[string]any
			for _, d := range p.deps {
				m := map[string]any{"name": d.Name, "req": d.Req, "features": orEmpty(d.Features), "optional": d.Optional,
					"default_features": d.DefaultFeatures == nil || *d.DefaultFeatures, "target": nil, "kind": d.Kind}
				if d.Target != "" {
					m["target"] = d.Target
				}
				if d.Package != "" {
					m["package"] = d.Package
				}
				deps = append(deps, m)
			}
			line := map[string]any{"name": p.name, "vers": p.vers, "deps": orEmptyMaps(deps), "cksum": s.cksum(p.name, p.vers),
				"features": orEmptyTable(p.features), "yanked": p.yanked, "v": 2}
			if p.links != "" {
				line["links"] = p.links
			}
			if p.rust != "" {
				line["rust_version"] = p.rust
			}
			b, err := json.Marshal(line)
			if err != nil {
				t.Fatal(err)
			}
			lines = append(lines, string(b))
		}
		body := []byte(strings.Join(lines, "\n") + "\n")
		files[IndexPath(n)] = body
		es, err := ParseIndexFile(n, body)
		if err != nil {
			t.Fatal(err)
		}
		reg[n] = es
	}
	return reg, files
}

// cksum is the made-up checksum of a synthetic version.
func (scenario) cksum(name, vers string) string {
	sum := sha256.Sum256([]byte(name + "@" + vers))
	return hex.EncodeToString(sum[:])
}

func (s scenario) member(t *testing.T) Member {
	t.Helper()
	m := Member{Name: "w0", Version: "0.1.0", Features: s.features}
	// Cargo builds a member's dependency list table by table, each sorted by name.
	ds := append([]IndexDep(nil), s.deps...)
	order := map[string]int{"normal": 0, "dev": 1, "build": 2}
	sort.SliceStable(ds, func(i, j int) bool {
		if (ds[i].Target == "") != (ds[j].Target == "") {
			return ds[i].Target == ""
		}
		if ds[i].Target != ds[j].Target {
			return ds[i].Target < ds[j].Target
		}
		if order[ds[i].Kind] != order[ds[j].Kind] {
			return order[ds[i].Kind] < order[ds[j].Kind]
		}
		return ds[i].Name < ds[j].Name
	})
	for _, d := range ds {
		rd, err := indexDep(d)
		if err != nil {
			t.Fatal(err)
		}
		m.Deps = append(m.Deps, rd)
	}
	return m
}

func (s scenario) write(t *testing.T, dir, resolver, url string) {
	t.Helper()
	tables := map[string][]string{}
	for _, d := range s.deps {
		sec := map[string]string{"normal": "dependencies", "dev": "dev-dependencies", "build": "build-dependencies"}[d.Kind]
		if d.Target != "" {
			sec = fmt.Sprintf("target.'%s'.%s", d.Target, sec)
		}
		var b strings.Builder
		fmt.Fprintf(&b, "%s = { version = %q", d.Name, d.Req)
		if d.Package != "" {
			fmt.Fprintf(&b, ", package = %q", d.Package)
		}
		if d.Optional {
			b.WriteString(", optional = true")
		}
		if d.DefaultFeatures != nil && !*d.DefaultFeatures {
			b.WriteString(", default-features = false")
		}
		if len(d.Features) > 0 {
			fmt.Fprintf(&b, `, features = ["%s"]`, strings.Join(d.Features, `", "`))
		}
		b.WriteString(" }")
		tables[sec] = append(tables[sec], b.String())
	}
	var toml strings.Builder
	toml.WriteString("[package]\nname = \"w0\"\nversion = \"0.1.0\"\nedition = \"2021\"\n")
	if len(s.features) > 0 {
		toml.WriteString("\n[features]\n")
		for _, k := range sortedKeys(s.features) {
			fmt.Fprintf(&toml, "%s = [", k)
			for i, v := range s.features[k] {
				if i > 0 {
					toml.WriteString(", ")
				}
				fmt.Fprintf(&toml, "%q", v)
			}
			toml.WriteString("]\n")
		}
	}
	for _, sec := range sortedKeys(tables) {
		fmt.Fprintf(&toml, "\n[%s]\n%s\n", sec, strings.Join(tables[sec], "\n"))
	}
	files := map[string]string{
		"Cargo.toml":         "[workspace]\nresolver = \"" + resolver + "\"\nmembers = [\"w0\"]\n",
		"w0/Cargo.toml":      toml.String(),
		"w0/src/lib.rs":      "",
		".cargo/config.toml": "[source.crates-io]\nreplace-with = \"mirror\"\n[source.mirror]\nregistry = \"sparse+" + url + "/\"\n",
	}
	for rel, body := range files {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// TestScenariosEqualCargo resolves synthetic indexes that exercise one Cargo rule each and
// compares with the Cargo.lock cargo 1.95.0 wrote for them (recorded with BOB_TEST_CARGO and
// BOB_TEST_RUSTC set and BOB_TEST_RECORD=1; with BOB_TEST_CARGO set, cargo is rerun and must
// still agree).
func TestScenariosEqualCargo(t *testing.T) {
	cargo := os.Getenv("BOB_TEST_CARGO")
	for _, s := range scenarios {
		for _, rn := range []cargoRun{{"2", ""}, {"3", "1.95.0"}} {
			t.Run(s.name+"/resolver"+rn.resolver, func(t *testing.T) {
				reg, files := s.registry(t)
				golden := filepath.Join("testdata", "scenarios", s.name+".resolver"+rn.resolver+".Cargo.lock")
				if cargo != "" {
					url := serveIndex(t, func(_ context.Context, rel string) ([]byte, error) {
						if b, ok := files[rel]; ok {
							return b, nil
						}
						return nil, ErrNoCrate
					})
					dir := t.TempDir()
					s.write(t, dir, rn.resolver, url)
					cmd := exec.Command(cargo, "generate-lockfile")
					cmd.Dir = dir
					path := "/usr/bin:/bin"
					if rc := os.Getenv("BOB_TEST_RUSTC"); rc != "" {
						path = rc + ":" + path
					}
					cmd.Env = []string{"PATH=" + path, "HOME=" + t.TempDir(), "CARGO_HOME=" + t.TempDir()}
					out, err := cmd.CombinedOutput()
					got := "error\n"
					if err == nil {
						b, rerr := os.ReadFile(filepath.Join(dir, "Cargo.lock"))
						if rerr != nil {
							t.Fatal(rerr)
						}
						got = string(b)
					} else {
						t.Logf("cargo: %s", out)
					}
					if os.Getenv("BOB_TEST_RECORD") == "1" {
						if err := os.MkdirAll(filepath.Dir(golden), 0o755); err != nil {
							t.Fatal(err)
						}
						if err := os.WriteFile(golden, []byte(got), 0o644); err != nil {
							t.Fatal(err)
						}
					}
				}
				want, err := os.ReadFile(golden)
				if err != nil {
					t.Fatal(err)
				}
				res, err := Resolve(context.Background(), reg, []Member{s.member(t)}, Options{RustVersion: rn.rustVersion})
				if string(want) == "error\n" {
					if !errors.Is(err, ErrUnresolvable) {
						t.Fatalf("cargo fails to resolve; bob: %v", err)
					}
					return
				}
				if err != nil {
					t.Fatalf("resolve: %v", err)
				}
				ours, err := res.CargoLock()
				if err != nil {
					t.Fatal(err)
				}
				if ours != string(want) {
					t.Errorf("Cargo.lock differs from %s\n%s", golden, diffLines(ours, string(want)))
				}
			})
		}
	}
}

func orEmpty(xs []string) []string {
	if xs == nil {
		return []string{}
	}
	return xs
}

func orEmptyMaps(xs []map[string]any) []map[string]any {
	if xs == nil {
		return []map[string]any{}
	}
	return xs
}

func orEmptyTable(m map[string][]string) map[string][]string {
	if m == nil {
		return map[string][]string{}
	}
	return m
}
