// pub is one published version of a synthetic index.
type pub struct {
	name, vers string
	deps       []IndexDep
	features   map[string][]string
	yanked     bool
	links      string
	rust       string
}

func dep(name, req string, mods ...func(*IndexDep)) IndexDep {
	t := true
	d := IndexDep{Name: name, Req: req, Kind: "normal", DefaultFeatures: &t}
	for _, m := range mods {
		m(&d)
	}
	return d
}

func optional(d *IndexDep)            { d.Optional = true }
func noDefault(d *IndexDep)           { f := false; d.DefaultFeatures = &f }
func kind(k string) func(*IndexDep)   { return func(d *IndexDep) { d.Kind = k } }
func target(t string) func(*IndexDep) { return func(d *IndexDep) { d.Target = t } }
func pkg(p string) func(*IndexDep)    { return func(d *IndexDep) { d.Package = p } }
func feats(fs ...string) func(*IndexDep) {
	return func(d *IndexDep) { d.Features = fs }
}

