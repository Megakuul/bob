func TestParseTOML(t *testing.T) {
	src := `# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO
[package]
edition = "2021"
name = "zstd-sys"
version = "2.1.2+zstd.1.5.7"
build = 'build.rs'
description = """
Low-level bindings \
  for "zstd"."""
keywords = [
    "zstd",   # comment
    'zstandard',
]
authors = []
"quoted.key" = 1_000
pi = 3.5
when = 1979-05-27T07:32:00Z
day = 1979-05-27 07:32:00
lit = '''a 'quoted' line'''
esc = "tab\there \u00e9"

[package.metadata.docs.rs]
features = ["a"]

[lib]
name = "zstd_sys"
path = "src/lib.rs"
proc-macro = false
inline = { a = 1, b.c = "x", d = [1, [2, 3]] }

[[bench]]
name = "one"

[[bench]]
name = "two"

[target.'cfg(unix)'.dependencies.libc]
version = "0.2"
`
	doc, err := parseTOML(src)
	if err != nil {
		t.Fatal(err)
	}
	pkg := doc["package"].(map[string]any)
	checks := map[string]any{
		"edition": "2021", "build": "build.rs", "description": "Low-level bindings for \"zstd\".",
		"quoted.key": int64(1000), "pi": 3.5, "when": "1979-05-27T07:32:00Z", "day": "1979-05-27 07:32:00",
		"lit": "a 'quoted' line", "esc": "tab\there é",
	}
	for k, want := range checks {
		if got := pkg[k]; !reflect.DeepEqual(got, want) {
			t.Errorf("package.%s = %#v, want %#v", k, got, want)
		}
	}
	if kw := pkg["keywords"].([]any); len(kw) != 2 || kw[1] != "zstandard" {
		t.Errorf("keywords = %v", kw)
	}
	lib := doc["lib"].(map[string]any)
	inl := lib["inline"].(map[string]any)
	if inl["b"].(map[string]any)["c"] != "x" || len(inl["d"].([]any)) != 2 {
		t.Errorf("inline table = %v", inl)
	}
	if b := doc["bench"].([]any); len(b) != 2 || b[1].(map[string]any)["name"] != "two" {
		t.Errorf("bench = %v", b)
	}
	tg := doc["target"].(map[string]any)["cfg(unix)"].(map[string]any)
	if tg["dependencies"].(map[string]any)["libc"].(map[string]any)["version"] != "0.2" {
		t.Errorf("target table = %v", tg)
	}
	for _, bad := range []string{
		"a = 1\na = 2", "[x]\n[x]", "a = \"open", "a = [1, 2", "a = {b = 1", "a = nope", "[a\n", "a = 1 b",
		"a = \"\\q\"", strings.Repeat("[", 200),
		"a = " + strings.Repeat("[", 100) + strings.Repeat("]", 100),
	} {
		if _, err := parseTOML(bad); err == nil {
			t.Errorf("parseTOML(%q) accepted", bad)
		}
	}
}

func TestMetaFromManifest(t *testing.T) {
	has := func(files ...string) func(string) bool {
		return func(p string) bool {
			for _, f := range files {
				if f == p {
					return true
				}
			}
			return false
		}
	}
	tests := []struct {
		name, toml string
		files      func(string) bool
		want       CrateMeta
		err        string
	}{
		{"plain", "[package]\nname = \"plain\"\nedition = \"2021\"\n", has("src/lib.rs"), CrateMeta{Edition: "2021"}, ""},
		{"old", "[project]\nname = \"old\"\n", has("src/lib.rs", "build.rs"), CrateMeta{Edition: "2015", Build: "build.rs"}, ""},
		{"no-build", "[package]\nedition = \"2018\"\nbuild = false\n", has("src/lib.rs", "build.rs"), CrateMeta{Edition: "2018"}, ""},
		{"build-path", "[package]\nedition = \"2018\"\nbuild = \"src/build.rs\"\n", has("src/lib.rs"), CrateMeta{Edition: "2018", Build: "src/build.rs"}, ""},
		{"serde_derive", "[package]\nedition = \"2021\"\n[lib]\nproc-macro = true\nname = \"serde_derive\"\n", has("src/lib.rs"), CrateMeta{Edition: "2021", ProcMacro: true}, ""},
		{"lib-name", "[package]\nedition = \"2021\"\n[lib]\nname = \"other\"\npath = \"lib.rs\"\n", has("lib.rs"), CrateMeta{Edition: "2021", LibName: "other", LibPath: "lib.rs"}, ""},
		{"lib-edition", "[package]\nedition = \"2018\"\n[lib]\nedition = \"2021\"\n", has("src/lib.rs"), CrateMeta{Edition: "2021"}, ""},
		{"no-lib", "[package]\nedition = \"2021\"\n", has("src/main.rs"), CrateMeta{}, "no library target"},
		{"autolib-off", "[package]\nautolib = false\n", has("src/lib.rs"), CrateMeta{}, "no library target"},
		{"escape", "[package]\nbuild = \"../../etc/x\"\n", has("src/lib.rs"), CrateMeta{}, "leaves the crate"},
		{"abs-lib", "[package]\n[lib]\npath = \"/etc/passwd\"\n", has("/etc/passwd"), CrateMeta{}, "leaves the crate"},
		{"edition", "[package]\nedition = \"2077\"\n", has("src/lib.rs"), CrateMeta{}, "unknown edition"},
		{"no-package", "[lib]\n", has("src/lib.rs"), CrateMeta{}, "no [package]"},
	}
	for _, tt := range tests {
		got, err := MetaFromManifest(tt.name, []byte(tt.toml), tt.files)
		switch {
		case tt.err != "":
			if err == nil || !strings.Contains(err.Error(), tt.err) {
				t.Errorf("%s: err = %v, want %q", tt.name, err, tt.err)
			}
		case err != nil:
			t.Errorf("%s: %v", tt.name, err)
		case got != tt.want:
			t.Errorf("%s: got %+v, want %+v", tt.name, got, tt.want)
		}
	}
}

func crateArchive(t *testing.T, files map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for name, body := range files {
		if err := tw.WriteHeader(&tar.Header{Name: name, Mode: 0o644, Size: int64(len(body)), Typeflag: tar.TypeReg}); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write([]byte(body)); err != nil {
			t.Fatal(err)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := gz.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func TestMetaFromCrate(t *testing.T) {
	data := crateArchive(t, map[string]string{
		"zstd-sys-2.1.2+zstd.1.5.7/Cargo.toml":      "[package]\nname = \"zstd-sys\"\nedition = \"2018\"\nbuild = \"build.rs\"\nlinks = \"zstd\"\n",
		"zstd-sys-2.1.2+zstd.1.5.7/Cargo.toml.orig": "garbage [[[",
		"zstd-sys-2.1.2+zstd.1.5.7/src/lib.rs":      "",
		"zstd-sys-2.1.2+zstd.1.5.7/build.rs":        "",
	})
	m, err := MetaFromCrate("zstd-sys", "2.1.2+zstd.1.5.7", bytes.NewReader(data))
	if err != nil || m != (CrateMeta{Edition: "2018", Build: "build.rs"}) {
		t.Errorf("MetaFromCrate = %+v, %v", m, err)
	}
	if _, err := MetaFromCrate("other", "1.0.0", bytes.NewReader(data)); err == nil {
		t.Error("a crate without its own top directory was accepted")
	}
	if _, err := MetaFromCrate("x", "1.0.0", strings.NewReader("not gzip")); err == nil {
		t.Error("garbage accepted")
	}
}
