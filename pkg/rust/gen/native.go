// tomlHeader starts every generated TOML file (§03.0.2).
const tomlHeader = "# generated by bob from bob.go — do not edit\n"

// nativeFiles returns the Cargo files of the repository's crates (§03.3.4): the workspace
// Cargo.toml, one Cargo.toml per local crate, Cargo.lock (from bob.lock alone) and the
// .cargo/config.toml that points cargo at bob's vendor directory.
func nativeFiles(ws *workspace, sec *lock.RustSection) ([]engine.GeneratedFile, error) {
	var local []*member
	for _, name := range ws.names {
		m := ws.members[name]
		if strings.HasPrefix(m.node.Label, "//") {
			local = append(local, m)
		}
	}
	if len(local) == 0 {
		return nil, nil
	}
	records := []resolve.Crate{}
	if sec != nil {
		var err error
		if records, err = fromLockCrates(sec.Crates); err != nil {
			return nil, err
		}
	}
	byName := map[string][]*resolve.Crate{}
	for i := range records {
		byName[records[i].Name] = append(byName[records[i].Name], &records[i])
	}
	owner := local[0].node.Label
	var out []engine.GeneratedFile
	var dirs []string
	rootMember := (*member)(nil)
	for _, m := range local {
		toml, err := crateToml(ws, m, byName)
		if err != nil {
			return nil, err
		}
		if m.dir == "" {
			rootMember = m
			dirs = append(dirs, ".")
			owner = m.node.Label
			continue
		}
		dirs = append(dirs, m.dir)
		out = append(out, engine.GeneratedFile{Path: m.dir + "/Cargo.toml", Content: []byte(tomlHeader + toml), Mode: 0o444, Owner: m.node.Label})
	}
	sort.Strings(dirs)
	var root strings.Builder
	root.WriteString(tomlHeader)
	if rootMember != nil {
		toml, err := crateToml(ws, rootMember, byName)
		if err != nil {
			return nil, err
		}
		root.WriteString(toml + "\n")
	}
	root.WriteString("[workspace]\nresolver = \"3\"\nmembers = [\n")
	for _, d := range dirs {
		fmt.Fprintf(&root, "    %s,\n", quote(d))
	}
	root.WriteString("]\n")
	out = append(out, engine.GeneratedFile{Path: "Cargo.toml", Content: []byte(root.String()), Mode: 0o444, Owner: owner})

	members, err := ws.resolveMembers()
	if err != nil {
		return nil, err
	}
	cl, err := resolve.CargoLockFromRecords(members, records)
	if err != nil {
		return nil, err
	}
	out = append(out, engine.GeneratedFile{Path: "Cargo.lock", Content: []byte(cl), Mode: 0o444, Owner: owner})
	out = append(out, engine.GeneratedFile{Path: ".cargo/config.toml", Content: []byte(tomlHeader +
		"[source.crates-io]\nreplace-with = \"bob-vendor\"\n\n[source.bob-vendor]\ndirectory = \".bob/vendor\"\n"), Mode: 0o444, Owner: owner})
	vendor, err := vendorFiles(records, owner)
	if err != nil {
		return nil, err
	}
	out = append(out, vendor...)
	return out, nil
}

// crateToml is the manifest of one local crate (without the header).
func crateToml(ws *workspace, m *member, byName map[string][]*resolve.Crate) (string, error) {
	s := m.spec
	var b strings.Builder
	fmt.Fprintf(&b, "[package]\nname = %s\nversion = \"0.0.0\"\nedition = %s\npublish = false\n", quote(s.Name), quote(s.Edition))
	if s.BuildScript != "" {
		fmt.Fprintf(&b, "build = %s\n", quote(s.BuildScript))
	} else {
		b.WriteString("build = false\n")
	}
	b.WriteString("autobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n")
	switch s.Type {
	case rsspec.TypeBin:
		fmt.Fprintf(&b, "\n[[bin]]\nname = %s\npath = %s\n", quote(s.Name), quote(s.Root))
	case rsspec.TypeProcMacro:
		fmt.Fprintf(&b, "\n[lib]\npath = %s\nproc-macro = true\n", quote(s.Root))
	case rsspec.TypeStaticLib, rsspec.TypeCDylib:
		fmt.Fprintf(&b, "\n[lib]\npath = %s\ncrate-type = [%s]\n", quote(s.Root), quote(s.Type))
	default:
		fmt.Fprintf(&b, "\n[lib]\npath = %s\n", quote(s.Root))
	}
	ft := featureTable(s)
	if len(ft) > 0 {
		b.WriteString("\n[features]\n")
		for _, k := range sortedKeys(ft) {
			fmt.Fprintf(&b, "%s = %s\n", key(k), list(ft[k]))
		}
	}
	for _, sec := range []struct {
		table string
		deps  []rsspec.Dep
	}{{"dependencies", s.Deps}, {"dev-dependencies", s.DevDeps}, {"build-dependencies", s.BuildDeps}} {
		if len(sec.deps) == 0 {
			continue
		}
		deps := append([]rsspec.Dep(nil), sec.deps...)
		sort.SliceStable(deps, func(i, j int) bool { return deps[i].Name < deps[j].Name })
		fmt.Fprintf(&b, "\n[%s]\n", sec.table)
		for _, d := range deps {
			var fields []string
			if d.Local >= 0 {
				dep := ws.members[m.local[d.Local]]
				if dep == nil {
					return "", fmt.Errorf("%s: unknown local crate %s", m.node.Label, m.local[d.Local])
				}
				fields = append(fields, "path = "+quote(relPath(m.dir, dep.dir)))
				if dep.spec.Name != d.Name {
					fields = append(fields, "package = "+quote(dep.spec.Name))
				}
			} else {
				req, err := resolve.ParseReq(d.Req)
				if err != nil {
					return "", fmt.Errorf("%s: rust.Crate(%q, %q): %w", m.node.Label, d.Crate, d.Req, err)
				}
				c := resolve.MatchLocked(byName[d.Crate], req)
				v := d.Req
				if c != nil {
					v = "=" + c.Version
				}
				fields = append(fields, "version = "+quote(v))
				if d.Crate != d.Name {
					fields = append(fields, "package = "+quote(d.Crate))
				}
			}
			if d.NoDefault {
				fields = append(fields, "default-features = false")
			}
			if len(d.Features) > 0 {
				fields = append(fields, "features = "+list(d.Features))
			}
			fmt.Fprintf(&b, "%s = { %s }\n", key(d.Name), strings.Join(fields, ", "))
		}
	}
	return b.String(), nil
}

// relPath is the path from crate directory from to directory to.
func relPath(from, to string) string {
	f, t := splitDir(from), splitDir(to)
	i := 0
	for i < len(f) && i < len(t) && f[i] == t[i] {
		i++
	}
	var parts []string
	for range f[i:] {
		parts = append(parts, "..")
	}
	parts = append(parts, t[i:]...)
	if len(parts) == 0 {
		return "."
	}
	return path.Join(parts...)
}

func splitDir(d string) []string {
	if d == "" || d == "." {
		return nil
	}
	return strings.Split(d, "/")
}

// vendorFiles are the stand-ins cargo reads from .bob/vendor/<name>-<version> (a directory
// source): a manifest written from bob.lock's facts and .cargo-checksum.json. They let cargo
// metadata --offline --locked load the whole graph without crate sources.
func vendorFiles(records []resolve.Crate, owner string) ([]engine.GeneratedFile, error) {
	var out []engine.GeneratedFile
	for _, c := range records {
		dir := ".bob/vendor/" + c.Name + "-" + c.Version
		sum, err := resolve.HexOfSRI(c.Checksum)
		if err != nil {
			return nil, fmt.Errorf("bob.lock crate %s@%s: %w", c.Name, c.Version, err)
		}
		out = append(out, engine.GeneratedFile{Path: dir + "/Cargo.toml", Content: []byte(vendorToml(c)), Mode: 0o444, Owner: owner},
			engine.GeneratedFile{Path: dir + "/.cargo-checksum.json", Content: []byte(`{"files":{},"package":"` + sum + `"}` + "\n"), Mode: 0o444, Owner: owner})
	}
	return out, nil
}

// vendorToml writes a registry crate's manifest from its bob.lock entry.
func vendorToml(c resolve.Crate) string {
	var b strings.Builder
	b.WriteString(tomlHeader)
	ed := c.Meta.Edition
	if ed == "" {
		ed = "2015"
	}
	fmt.Fprintf(&b, "[package]\nname = %s\nversion = %s\nedition = %s\n", quote(c.Name), quote(c.Version), quote(ed))
	if c.Links != "" {
		fmt.Fprintf(&b, "links = %s\n", quote(c.Links))
	}
	if c.Meta.Build != "" {
		fmt.Fprintf(&b, "build = %s\n", quote(c.Meta.Build))
	} else {
		b.WriteString("build = false\n")
	}
	b.WriteString("autobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n")
	libPath := c.Meta.LibPath
	if libPath == "" {
		libPath = "src/lib.rs"
	}
	fmt.Fprintf(&b, "\n[lib]\npath = %s\n", quote(libPath))
	if c.Meta.LibName != "" {
		fmt.Fprintf(&b, "name = %s\n", quote(c.Meta.LibName))
	}
	if c.Meta.ProcMacro {
		b.WriteString("proc-macro = true\n")
	}
	deps := map[string]bool{}
	optional := map[string]bool{}
	for _, d := range c.Deps {
		deps[d.Name] = true
		if d.Optional {
			optional[d.Name] = true
		}
	}
	if len(c.Features) > 0 {
		b.WriteString("\n[features]\n")
		for _, k := range sortedKeys(c.Features) {
			var vs []string
			for _, v := range c.Features[k] {
				if featureRefKnown(v, c.Features, deps, optional) {
					vs = append(vs, v)
				}
			}
			fmt.Fprintf(&b, "%s = %s\n", key(k), list(vs))
		}
	}
	type table struct{ name, kind, target string }
	tables := map[table][]resolve.CrateDep{}
	for _, d := range c.Deps {
		t := table{kind: d.Kind, target: d.Target}
		tables[t] = append(tables[t], d)
	}
	keys := make([]table, 0, len(tables))
	for t := range tables {
		keys = append(keys, t)
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].target != keys[j].target {
			return keys[i].target < keys[j].target
		}
		return keys[i].kind < keys[j].kind
	})
	for _, t := range keys {
		name := map[string]string{"": "dependencies", "build": "build-dependencies", "dev": "dev-dependencies"}[t.kind]
		if t.target != "" {
			fmt.Fprintf(&b, "\n[target.%s.%s]\n", quote(t.target), name)
		} else {
			fmt.Fprintf(&b, "\n[%s]\n", name)
		}
		ds := tables[t]
		sort.SliceStable(ds, func(i, j int) bool { return ds[i].Name < ds[j].Name })
		for _, d := range ds {
			n, v, _ := strings.Cut(d.Crate, "@")
			fields := []string{"version = " + quote("="+v)}
			if n != d.Name {
				fields = append(fields, "package = "+quote(n))
			}
			if d.Optional {
				fields = append(fields, "optional = true")
			}
			if d.NoDefault {
				fields = append(fields, "default-features = false")
			}
			if len(d.Features) > 0 {
				fields = append(fields, "features = "+list(d.Features))
			}
			fmt.Fprintf(&b, "%s = { %s }\n", key(d.Name), strings.Join(fields, ", "))
		}
	}
	return b.String()
}

// featureRefKnown reports whether a feature value names something the manifest has (bob.lock
// leaves out optional dependencies no workspace feature can enable; their references go too).
func featureRefKnown(v string, table map[string][]string, deps, optional map[string]bool) bool {
	if d, ok := strings.CutPrefix(v, "dep:"); ok {
		return optional[d]
	}
	if d, _, ok := strings.Cut(v, "/"); ok {
		return deps[strings.TrimSuffix(d, "?")]
	}
	_, isFeature := table[v]
	return isFeature || optional[v]
}

func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, "\\u%04X", r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// key writes a TOML key: bare when possible.
func key(k string) string {
	for _, r := range k {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' || r == '-') {
			return quote(k)
		}
	}
	if k == "" {
		return `""`
	}
	return k
}

func list(vs []string) string {
	q := make([]string, len(vs))
	for i, v := range vs {
		q[i] = quote(v)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
