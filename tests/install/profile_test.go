// TestRINST005Layout: golden generations/1.json and shim text (SPEC §02.8); the shim is a 0755
// POSIX sh file; `current` is a symlink to generations/<n>.json.
func TestRINST005Layout(t *testing.T) {
	parity.Covers(t, "R-INST-005")
	e, srv := setup(t)
	if r := e.addRegistry(t, "default", srv); harness.Red(t, r) {
		return
	}
	if r := e.bob(t, "", "install", "acme/cli@1.0.0"); r.Exit != 0 {
		t.Fatalf("install: exit %d\n%s", r.Exit, r.Combined())
	}
	gen := filepath.Join(e.installDir(), "generations", "1.json")
	norm := golden.Normalize(func(b []byte) []byte {
		b = regexp.MustCompile(`"created": *"[^"]*"`).ReplaceAll(b, []byte(`"created": "<t>"`))
		return regexp.MustCompile(`linux-(arm64|amd64)`).ReplaceAll(b, []byte("<platform>"))
	})
	golden.Assert(t, "tests/goldens/install/generations-1.json", []byte(readFile(t, gen)), norm, golden.Reqs("R-INST-005"))

	bobPath := harness.Bin(t, "bob")
	wantShim := "#!/bin/sh\n# Code generated by bob install (acme/cli 1.0.0). DO NOT EDIT.\nexec \"${BOB:-" + bobPath + "}\" exec --installed acme/cli -- acme \"$@\"\n"
	got := readFile(t, e.shim("acme"))
	if got != wantShim {
		t.Errorf("shim text differs\n got: %q\nwant: %q", got, wantShim)
	}
	golden.Assert(t, "tests/goldens/install/shim-acme.sh", []byte(strings.ReplaceAll(got, bobPath, "<bob>")), golden.Reqs("R-INST-005"))
	if st, err := os.Stat(e.shim("acme")); err != nil || st.Mode().Perm() != 0o755 {
		t.Errorf("shim mode: %v %v, want 0755", st, err)
	}
	l, err := os.Readlink(filepath.Join(e.installDir(), "current"))
	if err != nil || l != "generations/1.json" {
		t.Errorf("current -> %q (%v), want a symlink to generations/1.json", l, err)
	}
	g := e.readGeneration(t, 1)
	if g.V != 1 || g.N != 1 || len(g.Entries) != 1 || g.Entries[0].Registry != "default" || g.Entries[0].Ref != "acme/cli" ||
		g.Entries[0].Version != "1.0.0" || g.Entries[0].Platform != fakeserver.Platform() || len(g.Entries[0].StorePaths) == 0 ||
		!strings.HasPrefix(g.Entries[0].Bins["acme"], g.Entries[0].StorePaths[0]+"/bin/acme") {
		t.Errorf("generation 1: %+v", g)
	}
}

// TestRINST005Conflicts: an existing non-bob file at the shim path gives BOB-E-0004 (`… exists and
// was not created by bob; remove it or use --as`) and nothing changes; a binary provided by
// another entry gives BOB-E-0004 `acme is already provided by infra/dt; use --as`; `--as` installs
// under another name and prefixes the shims.
func TestRINST005Conflicts(t *testing.T) {
	parity.Covers(t, "R-INST-005")
	e, srv := setup(t)
	publish(t, srv, "infra", "dt", false, []string{"acme"}, "0.9.0") // dt also ships a binary named acme
	if r := e.addRegistry(t, "default", srv); harness.Red(t, r) {
		return
	}
	if err := os.MkdirAll(e.binDir(), 0o755); err != nil {
		t.Fatal(err)
	}
	foreign := "#!/bin/sh\necho mine\n"
	if err := os.WriteFile(e.shim("acme"), []byte(foreign), 0o755); err != nil {
		t.Fatal(err)
	}
	r := e.bob(t, "", "install", "acme/cli")
	if r.Exit != 2 || !strings.Contains(r.Combined(), "BOB-E-0004") || !strings.Contains(r.Combined(), "~/.local/bin/acme exists and was not created by bob; remove it or use --as") {
		t.Errorf("foreign file: exit %d, want 2 with BOB-E-0004 `~/.local/bin/acme exists and was not created by bob; remove it or use --as`\n%s", r.Exit, r.Combined())
	}
	if readFile(t, e.shim("acme")) != foreign || e.current(t) != 0 {
		t.Errorf("a failed install changed something (shim or current=%d)", e.current(t))
	}
	if _, err := os.Stat(filepath.Join(e.installDir(), "generations")); err == nil {
		ents, _ := os.ReadDir(filepath.Join(e.installDir(), "generations"))
		if len(ents) != 0 {
			t.Errorf("a failed install left %d files in generations/", len(ents))
		}
	}
	if err := os.Remove(e.shim("acme")); err != nil {
		t.Fatal(err)
	}
	if r := e.bob(t, "", "install", "infra/dt"); r.Exit != 0 {
		t.Fatalf("install infra/dt: exit %d\n%s", r.Exit, r.Combined())
	}
	before := readFile(t, e.shim("acme"))
	r = e.bob(t, "", "install", "acme/cli")
	if r.Exit != 2 || !strings.Contains(r.Combined(), "BOB-E-0004") || !strings.Contains(r.Combined(), "acme is already provided by infra/dt; use --as") {
		t.Errorf("provided by another entry: exit %d, want 2 with BOB-E-0004 `acme is already provided by infra/dt; use --as`\n%s", r.Exit, r.Combined())
	}
	if e.current(t) != 1 || readFile(t, e.shim("acme")) != before {
		t.Errorf("a failed install changed something (current=%d)", e.current(t))
	}
	r = e.bob(t, "", "install", "acme/cli", "--as", "cli2")
	if r.Exit != 0 {
		t.Fatalf("install --as cli2: exit %d\n%s", r.Exit, r.Combined())
	}
	if _, err := os.Stat(e.shim("cli2-acme")); err != nil {
		t.Errorf("--as cli2 must create the shim cli2-acme: %v", err)
	}
	if !strings.Contains(readFile(t, e.shim("cli2-acme")), "exec --installed cli2 -- acme") {
		t.Errorf("shim of --as does not name the entry cli2:\n%s", readFile(t, e.shim("cli2-acme")))
	}
}

// TestRINST005GCRoots: after 7 installs exactly generations 3–7 have GC roots; older generations
// lose theirs.
func TestRINST005GCRoots(t *testing.T) {
	parity.Covers(t, "R-INST-005")
	srv := fakeserver.New(t, fakeserver.Options{Name: "default"})
	e := newEnv(t)
	for i := 1; i <= 7; i++ {
		publish(t, srv, "acme", fmt.Sprintf("tool%d", i), false, []string{fmt.Sprintf("tool%d", i)}, "1.0.0")
	}
	if r := e.addRegistry(t, "default", srv); harness.Red(t, r) {
		return
	}
	for i := 1; i <= 7; i++ {
		if r := e.bob(t, "", "install", fmt.Sprintf("acme/tool%d", i)); r.Exit != 0 {
			t.Fatalf("install %d: exit %d\n%s", i, r.Exit, r.Combined())
		}
	}
	roots, err := os.ReadDir(filepath.Join(e.home, ".local", "share", "bob", "nix", "var", "nix", "gcroots", "bob-install"))
	if err != nil {
		t.Fatalf("no GC roots directory: %v", err)
	}
	var names []string
	for _, r := range roots {
		names = append(names, r.Name())
	}
	sort.Strings(names)
	if fmt.Sprint(names) != "[3 4 5 6 7]" {
		t.Errorf("GC roots of generations %v, want exactly [3 4 5 6 7]", names)
	}
	// every store path of generation 7 (all seven programs) is reachable from a root.
	g := e.readGeneration(t, 7)
	if len(g.Entries) != 7 {
		t.Errorf("generation 7 has %d entries, want 7", len(g.Entries))
	}
	for _, n := range []int{1, 2} { // the generation files stay; only the roots go
		if _, err := os.Stat(filepath.Join(e.installDir(), "generations", fmt.Sprintf("%d.json", n))); err != nil {
			t.Errorf("generation %d file removed: %v", n, err)
		}
	}
}
