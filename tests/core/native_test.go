// R-FW-066 (e): deleting the manifest and rerunning adopts identical files without writing.
func TestRFW066ManifestLossAdoptsFiles(t *testing.T) {
	parity.Covers(t, "R-FW-066")
	dir, ok := codegenGenerated(t)
	if !ok {
		return
	}
	protoRoot, _ := genRoots(dir)
	file := firstFile(t, protoRoot)
	before, err := os.Stat(file)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(dir, ".bob", "gen", "manifest.json")); err != nil {
		t.Fatal(err)
	}
	tree := treeHash(t, protoRoot)
	if r := bobRun(t, dir, "gen"); !exitIs(t, r, 0) {
		return
	}
	after, err := os.Stat(file)
	if err != nil || !after.ModTime().Equal(before.ModTime()) {
		t.Errorf("bob gen rewrote an identical file after the manifest was deleted (mtime %v → %v)", before.ModTime(), after.ModTime())
	}
	if treeHash(t, protoRoot) != tree {
		t.Errorf("the root changed although all files were identical")
	}
	var m struct {
		Version int `json:"version"`
		Roots   map[string]struct {
			Files map[string]struct {
				SHA256 string `json:"sha256"`
			} `json:"files"`
		} `json:"roots"`
	}
	if err := json.Unmarshal([]byte(readFile(t, filepath.Join(dir, ".bob", "gen", "manifest.json"))), &m); err != nil || m.Version != 1 || len(m.Roots) == 0 {
		t.Errorf("the manifest was not recreated: %v %+v", err, m)
	}
}

// R-FW-066 (f): SIGKILL at each step of the write protocol leaves no temp file and a consistent
// manifest after the rerun. SPEC names no injection hook, so the kill points are a sweep over
// the run time of bob gen (decision: 40 kill points, 0 … 110 % of the measured duration).
func TestRFW066KillDuringWrite(t *testing.T) {
	parity.Covers(t, "R-FW-066")
	ref := harness.Fixture(t, "codegen")
	start := time.Now()
	if r := bobRun(t, ref, "gen"); harness.Red(t, r) || !exitIs(t, r, 0) {
		return
	}
	dur := time.Since(start)
	want := treeHashExcept(t, ref)
	for i := 0; i < 40; i++ {
		dir := harness.Fixture(t, "codegen")
		cmd := exec.Command(harness.Bin(t, "bob"), "gen")
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "TZ=UTC", "LC_ALL=C")
		cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
		if err := cmd.Start(); err != nil {
			t.Fatalf("harness: %v", err)
		}
		time.AfterFunc(dur*time.Duration(i*110/40)/100, func() { _ = syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL) })
		_ = cmd.Wait()
		if r := bobRun(t, dir, "gen"); !exitIs(t, r, 0) {
			t.Errorf("kill point %d: the rerun of bob gen failed", i)
			continue
		}
		var temps []string
		_ = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
			if err == nil && strings.Contains(d.Name(), ".bob-tmp-") {
				temps = append(temps, p)
			}
			return nil
		})
		if len(temps) != 0 {
			t.Errorf("kill point %d: temp files left: %v", i, temps)
		}
		if got := treeHashExcept(t, dir); got != want {
			t.Errorf("kill point %d: the tree after the rerun differs from an uninterrupted run", i)
		}
		if r := bobRun(t, dir, "status", "--json"); r.Exit != 0 || strings.Contains(r.Stdout, `"edited"`) || strings.Contains(r.Stdout, `"orphan"`) {
			t.Errorf("kill point %d: bob status after the rerun reports problems:\n%s", i, r.Stdout)
		}
	}
}

// treeHashExcept is treeHash without the files that legitimately differ between two runs: the
// manifest (mtimes), the eval cache and bob's state.
func treeHashExcept(t *testing.T, dir string) string {
	t.Helper()
	return treeHashSkip(t, dir, ".bob/gen/manifest.json", ".bob/eval", ".bob/state", ".bob/gen/backup")
}

// R-FW-067 (a): after bob gen, gopls (through the shim, -tags=bob) resolves the import of
// example.com/svc/gen/proto/greet/v1 with 0 diagnostics.
func TestRFW067GoplsResolvesGeneratedCode(t *testing.T) {
	parity.Covers(t, "R-FW-067")
	dir, ok := codegenGenerated(t)
	if !ok {
		return
	}
	if r := bobRun(t, dir, "env", "--format", "json"); !exitIs(t, r, 0) {
		return
	}
	cmd := execShim(t, filepath.Join(dir, "svc"), nil)
	cmd.Dir = filepath.Join(dir, "svc")
	c, err := startLSP(cmd, filepath.Join(dir, "svc"), map[string]any{"build.buildFlags": []string{"-tags=bob"}})
	if err != nil {
		t.Fatalf("start gopls: %v", err)
	}
	defer c.close()
	if err := c.open("cmd/server/main.go"); err != nil {
		t.Fatal(err)
	}
	var errs []string
	for _, d := range c.diagnostics("cmd/server/main.go") {
		if d.Severity == 1 {
			errs = append(errs, d.Message)
		}
	}
	if len(errs) != 0 {
		t.Errorf("gopls reports %d error(s) in cmd/server/main.go: %v", len(errs), errs)
	}
	res, err := c.at("textDocument/definition", "cmd/server/main.go", "greetv1.GreetRequest", 3)
	if err != nil || !strings.Contains(string(res), "svc/gen/proto/greet/v1") && !strings.Contains(string(res), "gen/proto/greet/v1") {
		t.Errorf("gopls does not resolve greetv1.GreetRequest into gen/proto/greet/v1: %v %.300s", err, res)
	}
}

