// R-FW-061: an edit of a generated file is drift: bob build exits 3 with BOB-E-1011 before any
// Nix call (no package.start event), prints the template (golden) and leaves the files alone;
// bob gen --force restores the files byte-identical and moves the edited copies to
// .bob/gen/backup/<UTC time>/.
func TestRFW061DriftIsRejected(t *testing.T) {
	parity.Covers(t, "R-FW-061")
	for _, c := range driftCases() {
		t.Run(c.name, func(t *testing.T) {
			dir := harness.Fixture(t, c.fixture)
			if r := bobRun(t, dir, "gen"); harness.Red(t, r) || !exitIs(t, r, 0) {
				return
			}
			path := filepath.Join(dir, filepath.FromSlash(c.file))
			generated := readFile(t, path)
			edited := c.edit(generated)
			if edited == generated {
				t.Fatalf("harness: the edit of %s changed nothing", c.file)
			}
			writeFile(t, path, edited)
			// bob's own state under .bob/ (evaluator cache, logs) may change; every other file,
			// the drifted one included, must not.
			before := treeHashSkip(t, dir, ".bob/")
			r := bobRun(t, dir, "build", "//...", "--json")
			if !exitIs(t, r, 3) {
				return
			}
			e, ok := errorWithCode(t, r, "BOB-E-1011")
			if ok && !strings.Contains(strings.Join(append([]string{e.Message}, e.Excerpt...), "\n"), filepath.Base(c.file)) {
				t.Errorf("the drift error does not name %s: %+v", c.file, e)
			}
			for _, ev := range eventsNamed(events(t, r), "package.start") {
				t.Errorf("a package started (%v) although drift must stop bob before any Nix call", ev)
			}
			if treeHashSkip(t, dir, ".bob/") != before {
				t.Errorf("bob build changed files although it must leave drifted files unchanged")
			}
			human := bobRun(t, dir, "build", "//...")
			if c.name == "go" {
				// The template of SPEC R-FW-061, as far as it does not depend on the fixture's own
				// go.mod (module dir, versions).
				for _, want := range []string{
					"✗ api/go.mod or go.sum was changed outside bob (they are generated from bob.go)",
					"+ golang.org/x/text v0.20.0  (not declared in bob.go)",
					"hint: declare Go modules in bob.go (golang.Require(\"golang.org/x/text\", \"v0.20.0\")) and run `bob lock`;",
					"`go get` and `go mod tidy` are not used with bob. To discard the edit: bob gen --force",
				} {
					if !strings.Contains(human.Stderr, want) {
						t.Errorf("the drift message lacks %q:\n%s", want, human.Stderr)
					}
				}
			}
			golden.Assert(t, "tests/goldens/native/drift/"+c.name+".txt", []byte(human.Stderr), golden.Human(), golden.Reqs("R-FW-061"))
			if r := bobRun(t, dir, "gen", "--force"); !exitIs(t, r, 0) {
				return
			}
			if got := readFile(t, path); got != generated {
				t.Errorf("bob gen --force did not restore %s byte-identical", c.file)
			}
			backups, _ := filepath.Glob(filepath.Join(dir, ".bob", "gen", "backup", "*", filepath.FromSlash(c.file)))
			if len(backups) != 1 {
				t.Fatalf("want one backup copy of %s under .bob/gen/backup/<time>/, got %v", c.file, backups)
			}
			if readFile(t, backups[0]) != edited {
				t.Errorf("the backup is not the edited copy")
			}
			if !regexp.MustCompile(`/backup/\d{8}T\d{6}Z?`).MatchString(backups[0]) && !regexp.MustCompile(`/backup/20\d\d`).MatchString(backups[0]) {
				t.Errorf("backup directory %s is not named by the UTC time", backups[0])
			}
		})
	}
}

