// R-FW-067 (c): in bob dev, a .proto edit reaches the tree within the budget of §03.8 (≤ 2.5 s;
// budget row "codegen bob dev proto edit").
func TestRFW067DevProtoEditReachesTree(t *testing.T) {
	parity.Covers(t, "R-FW-067")
	dir, ok := codegenGenerated(t)
	if !ok {
		return
	}
	cmd := exec.Command(harness.Bin(t, "bob"), "dev", "--servers-only", "--no-servers")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "TZ=UTC", "LC_ALL=C")
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	if err := cmd.Start(); err != nil {
		t.Fatalf("harness: %v", err)
	}
	defer func() { _ = syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL); _ = cmd.Wait() }()
	time.Sleep(3 * time.Second)
	proto := filepath.Join(dir, "proto", "greet", "v1", "greet.proto")
	generated := filepath.Join(dir, "svc", "gen", "proto", "greet", "v1", "greet.pb.go")
	before := readFile(t, generated)
	if strings.Contains(before, "FieldAddedInDev") {
		t.Fatal("harness: generated code already has the field")
	}
	replaceIn(t, proto, "message GreetRequest {", "message GreetRequest {\n  string field_added_in_dev = 99;")
	editedAt := time.Now()
	for time.Since(editedAt) < 10*time.Second {
		if b, err := os.ReadFile(generated); err == nil && strings.Contains(string(b), "FieldAddedInDev") {
			if d := time.Since(editedAt); d > 2500*time.Millisecond {
				t.Errorf("the .proto edit reached svc/gen after %s, want ≤ 2.5 s", d.Round(time.Millisecond))
			}
			return
		}
		time.Sleep(50 * time.Millisecond)
	}
	t.Errorf("a .proto edit never reached svc/gen/proto/greet/v1/greet.pb.go within 10 s")
}
