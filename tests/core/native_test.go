// R-FW-066 helpers.
func genRoots(dir string) (proto, rest string) {
	return filepath.Join(dir, "svc", "gen", "proto"), filepath.Join(dir, "svc", "gen", "rest")
}

func firstFile(t *testing.T, dir string) string {
	t.Helper()
	var files []string
	_ = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err == nil && d.Type().IsRegular() && d.Name() != ".gitignore" {
			files = append(files, p)
		}
		return nil
	})
	sort.Strings(files)
	if len(files) == 0 {
		t.Fatalf("harness: no generated file under %s", dir)
	}
	return files[0]
}

// codegenGenerated returns the fixture after a successful bob gen.
func codegenGenerated(t *testing.T) (string, bool) {
	t.Helper()
	dir := harness.Fixture(t, "codegen")
	if r := bobRun(t, dir, "gen"); harness.Red(t, r) || !exitIs(t, r, 0) {
		return dir, false
	}
	return dir, true
}

// R-FW-066 (a)+(b): an edited generated file plus a foreign file in one root make bob gen exit
// 3 with BOB-E-1016, leave that root untouched and update other roots; --force moves both to
// the backup dir and rewrites.
func TestRFW066ConflictAndForce(t *testing.T) {
	parity.Covers(t, "R-FW-066")
	dir, ok := codegenGenerated(t)
	if !ok {
		return
	}
	protoRoot, _ := genRoots(dir)
	gen := firstFile(t, protoRoot)
	original := readFile(t, gen)
	writeFile(t, gen, original+"\n// edited by hand\n")
	foreign := filepath.Join(protoRoot, "foreign.txt")
	writeFile(t, foreign, "mine\n")
	protoBefore := treeHash(t, protoRoot)
	r := bobRun(t, dir, "gen", "--json")
	if !exitIs(t, r, 3) {
		return
	}
	e, ok := errorWithCode(t, r, "BOB-E-1016")
	if ok && !strings.Contains(e.Message, "svc/gen/proto") {
		t.Errorf("the conflict error does not name svc/gen/proto: %q", e.Message)
	}
	if treeHash(t, protoRoot) != protoBefore {
		t.Errorf("the conflicting root svc/gen/proto was touched")
	}
	human := bobRun(t, dir, "gen")
	golden.Assert(t, "tests/goldens/native/codegen/conflict.txt", []byte(human.Stderr), golden.Human(), golden.Reqs("R-FW-066"))
	if r := bobRun(t, dir, "gen", "--force"); !exitIs(t, r, 0) {
		return
	}
	if got := readFile(t, gen); got != original {
		t.Errorf("--force did not rewrite the edited generated file")
	}
	if _, err := os.Stat(foreign); err == nil {
		t.Errorf("--force left the foreign file in the root")
	}
	backups, _ := filepath.Glob(filepath.Join(dir, ".bob", "gen", "backup", "*", "svc", "gen", "proto", "*"))
	if len(backups) < 2 {
		t.Errorf("--force did not move both the edited and the foreign file to the backup dir: %v", backups)
	}
	for _, b := range backups {
		if strings.HasSuffix(b, "foreign.txt") && readFile(t, b) != "mine\n" {
			t.Errorf("the backup of the foreign file lost its content")
		}
	}
}

