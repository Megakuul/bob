// envJSON is .bob/env.json (SPEC §02.7.2).
type envJSON struct {
	V       int    `json:"v"`
	Root    string `json:"root"`
	Shell   string `json:"shell"`
	EvalKey string `json:"evalKey"`
	Inside  map[string]string
	Outside struct {
		Set map[string]string `json:"set"`
	} `json:"outside"`
	InsideOnly []string `json:"insideOnly"`
	Tools      map[string]struct {
		Path string            `json:"path"`
		LSP  bool              `json:"lsp"`
		Env  map[string]string `json:"env"`
	} `json:"tools"`
	Closure []string `json:"closure"`
	Hooks   []string `json:"hooks"`
	Servers []struct {
		Name  string   `json:"name"`
		Cmd   []string `json:"cmd"`
		Cwd   string   `json:"cwd"`
		Ready string   `json:"ready"`
	} `json:"servers"`
}

// prepare runs bob env in dir (writes .bob/env.json and the shims) and returns the parsed file.
// ok is false when the feature is a stub (t is failed as red) or bob env failed.
func prepare(t testing.TB, w *world, dir string) (envJSON, bool) {
	t.Helper()
	r := w.bob(dir, "env")
	if harness.Red(t, r) || !exitIs(t, r, 0) {
		return envJSON{}, false
	}
	noLeak(t, r)
	var e envJSON
	if err := json.Unmarshal([]byte(readFile(t, filepath.Join(dir, ".bob", "env.json"))), &e); err != nil {
		t.Fatalf(".bob/env.json is not JSON: %v", err)
	}
	return e, true
}

// shimEnv is the environment a shim runs in: the shim honours $BOB for moved binaries.
func shimEnv(t testing.TB) []string { return []string{"BOB=" + bobBin(t)} }

var goVersion = regexp.MustCompile(`/nix/store/[0-9a-z]{32}-go-([0-9][0-9.]*)/bin/go$`)

// TestRDEV008ShimFiles: after bob env, env.json has the documented fields and .bob/bin holds
// exactly the SPEC §02.7.3 shims (mode 0755, LSP servers with --lsp, only shims).
func TestRDEV008ShimFiles(t *testing.T) {
	parity.Covers(t, "R-DEV-008")
	w := newWorld(t)
	dir := w.fixture("acme")
	e, ok := prepare(t, w, dir)
	if !ok {
		return
	}
	if e.V != 1 || e.Root != dir || e.Shell != "default" || !strings.HasPrefix(e.EvalKey, "sha256:") {
		t.Errorf("env.json header: v=%d root=%q shell=%q evalKey=%q", e.V, e.Root, e.Shell, e.EvalKey)
	}
	gopls, hasGopls := e.Tools["gopls"]
	if !hasGopls || !gopls.LSP || gopls.Env["GOFLAGS"] != "-tags=bob" {
		t.Errorf("tools.gopls = %+v, want lsp:true and env GOFLAGS=-tags=bob (S1-7)", gopls)
	}
	if g, has := e.Tools["go"]; !has || g.LSP || !goVersion.MatchString(g.Path) {
		t.Errorf("tools.go = %+v, want a /nix/store/…-go-<version>/bin/go path, lsp:false", g)
	}
	if _, has := e.Tools["jq"]; !has {
		t.Errorf("tools has no jq although the dev shell lists it")
	}
	if e.Outside.Set["ACME_ENV"] != "dev" {
		t.Errorf("outside.set = %v, want ACME_ENV=dev", e.Outside.Set)
	}
	for k, v := range e.Outside.Set {
		if strings.Contains(v, "/nix/store") {
			t.Errorf("outside.set[%s] = %q references the store", k, v)
		}
	}
	bin := filepath.Join(dir, ".bob", "bin")
	ents, err := os.ReadDir(bin)
	if err != nil {
		t.Fatalf(".bob/bin: %v", err)
	}
	var names []string
	for _, ent := range ents {
		names = append(names, ent.Name())
	}
	var tools []string
	for n := range e.Tools {
		tools = append(tools, n)
	}
	sort.Strings(names)
	sort.Strings(tools)
	if strings.Join(names, " ") != strings.Join(tools, " ") {
		t.Errorf(".bob/bin = %v, want exactly the tools of env.json %v", names, tools)
	}
	bobPath := bobBin(t)
	for _, n := range names {
		p := filepath.Join(bin, n)
		st, err := os.Lstat(p)
		if err != nil || !st.Mode().IsRegular() || st.Mode().Perm() != 0o755 {
			t.Errorf("shim %s: %v %v, want a regular file with mode 0755", n, st, err)
		}
		flag := ""
		if e.Tools[n].LSP {
			flag = "--lsp "
		}
		want := fmt.Sprintf("#!/bin/sh\n# Code generated by bob. DO NOT EDIT.\nexec \"${BOB:-%s}\" exec %s--project '%s' -- %s \"$@\"\n", bobPath, flag, dir, n)
		if got := readFile(t, p); got != want {
			t.Errorf("shim %s:\n%s\nwant:\n%s", n, got, want)
		}
	}
	// A tool that left the dev shell loses its shim at the next write.
	stale := filepath.Join(bin, "stale-tool")
	writeFile(t, stale, "#!/bin/sh\n")
	w.acc.chownTree(t, bin)
	if _, ok := prepare(t, w, dir); ok && exists(stale) {
		t.Errorf("the shim of a tool that is not in the dev shell survived bob env")
	}
}

// TestRDEV008NoEnv: a shim whose root has no .bob/env.json exits 7 with BOB-E-7006.
func TestRDEV008NoEnv(t *testing.T) {
	parity.Covers(t, "R-DEV-008")
	w := newWorld(t)
	dir := w.fixture("acme")
	shim := filepath.Join(dir, ".bob", "bin", "gopls")
	writeFile(t, shim, fmt.Sprintf("#!/bin/sh\n# Code generated by bob. DO NOT EDIT.\nexec \"${BOB:-%s}\" exec --lsp --project '%s' -- gopls \"$@\"\n", bobBin(t), dir))
	if err := os.Chmod(shim, 0o755); err != nil {
		t.Fatal(err)
	}
	w.acc.chownTree(t, filepath.Join(dir, ".bob"))
	r := w.run(runOpts{dir: dir, env: shimEnv(t)}, shim, "version")
	if harness.Red(t, r) {
		return
	}
	noLeak(t, r)
	if r.Exit != 7 || !strings.Contains(r.Stderr, "BOB-E-7006") {
		t.Errorf("shim without env.json: exit %d, stderr %q, want exit 7 with BOB-E-7006", r.Exit, r.Stderr)
	}
	if r.Stdout != "" {
		t.Errorf("--lsp mode wrote to stdout: %q", r.Stdout)
	}
}

const nsProgram = `package main

import (
	"fmt"
	"os"
	"strings"
)

func main() {
	wd, _ := os.Getwd()
	um, _ := os.ReadFile("/proc/self/uid_map")
	ns, _ := os.Readlink("/proc/self/ns/mnt")
	fmt.Printf("wd=%s\nuidmap=%s\nmnt=%s\n", wd, strings.Join(strings.Fields(string(um)), " "), ns)
}
`

const exit5Program = `package main

import "os"

func main() { os.Exit(5) }
`

// TestRDEV008ExecAndShims: shims in a root without /nix run the pinned tools inside bob's
// namespace; exit status, stdin, cwd and SIGTERM are the tool's.
func TestRDEV008ExecAndShims(t *testing.T) {
	parity.Covers(t, "R-DEV-008")
	w := newWorld(t)
	dir := w.fixture("acme")
	writeFile(t, filepath.Join(dir, "ns", "main.go"), nsProgram)
	writeFile(t, filepath.Join(dir, "x", "main.go"), exit5Program)
	w.acc.chownTree(t, dir)
	e, ok := prepare(t, w, dir)
	if !ok {
		return
	}
	shimDir := filepath.Join(dir, ".bob", "bin")
	shim := func(name string) string { return filepath.Join(shimDir, name) }
	run := func(o runOpts, argv ...string) harness.Result {
		o.hide = true
		if o.dir == "" {
			o.dir = dir
		}
		o.env = append(o.env, shimEnv(t)...)
		r := w.run(o, argv...)
		noLeak(t, r)
		return r
	}

	// Pinned Go in a root without /nix.
	m := goVersion.FindStringSubmatch(e.Tools["go"].Path)
	r := run(runOpts{}, shim("go"), "version")
	if exitIs(t, r, 0) && (m == nil || !strings.HasPrefix(r.Stdout, "go version go"+m[1]+" ")) {
		t.Errorf(".bob/bin/go version = %q, want the pinned go %v", r.Stdout, m)
	}

	// Subprocesses run in bob's mount namespace: uid_map "0 <uid> 1", mntns differs from the host.
	hostNS, _ := os.Readlink("/proc/self/ns/mnt")
	r = run(runOpts{}, shim("go"), "run", "./ns")
	if exitIs(t, r, 0) {
		kv := map[string]string{}
		for _, l := range strings.Split(r.Stdout, "\n") {
			if k, v, ok := strings.Cut(l, "="); ok {
				kv[k] = v
			}
		}
		if want := fmt.Sprintf("0 %d 1", w.acc.uid); kv["uidmap"] != want {
			t.Errorf("uid_map inside the namespace = %q, want %q", kv["uidmap"], want)
		}
		if kv["mnt"] == "" || kv["mnt"] == hostNS {
			t.Errorf("mount namespace inside = %q, host = %q: not entered", kv["mnt"], hostNS)
		}
		if kv["wd"] != dir {
			t.Errorf("working directory inside = %q, want %q", kv["wd"], dir)
		}
	}

	// Exit status passes through a shell. `go run` itself reports a failing program as "exit
	// status 5" and exits 1 (cmd/go, pinned go 1.26.8; test correction 33), so the shim's status
	// must be go's 1; jq's halt_error(5) checks a status other than 1 unchanged.
	r = run(runOpts{}, "/bin/sh", "-c", ".bob/bin/go run ./x; echo $?")
	if exitIs(t, r, 0) && (strings.TrimSpace(r.Stdout) != "1" || !strings.Contains(r.Stderr, "exit status 5")) {
		t.Errorf("go run ./x through the shim: status %q, stderr %q, want 1 and \"exit status 5\"", strings.TrimSpace(r.Stdout), r.Stderr)
	}
	r = run(runOpts{}, "/bin/sh", "-c", `.bob/bin/jq -n '"" | halt_error(5)'; echo $?`)
	if exitIs(t, r, 0) && strings.TrimSpace(r.Stdout) != "5" {
		t.Errorf("exit status through the shim = %q, want 5", strings.TrimSpace(r.Stdout))
	}
	// A failing tool's status is the shim's own status.
	if r = run(runOpts{}, shim("go"), "run", "./x"); r.Exit != 1 {
		t.Errorf("go run ./x through the shim exited %d, want go's own 1", r.Exit)
	}
	if r = run(runOpts{}, shim("jq"), "-n", `"" | halt_error(5)`); r.Exit != 5 {
		t.Errorf("jq halt_error(5) through the shim exited %d, want 5", r.Exit)
	}

	// stdin and stdout are the tool's.
	r = run(runOpts{stdin: "hello\n"}, shim("jq"), "-R", ".")
	if exitIs(t, r, 0) && r.Stdout != "\"hello\"\n" {
		t.Errorf("jq through the shim printed %q for stdin hello", r.Stdout)
	}
	// cwd is the caller's.
	r = run(runOpts{dir: filepath.Join(dir, "libs", "foo")}, shim("go"), "env", "GOMOD")
	if exitIs(t, r, 0) && strings.TrimSpace(r.Stdout) != filepath.Join(dir, "go.mod") {
		t.Errorf("go env GOMOD from libs/foo = %q, want %q", strings.TrimSpace(r.Stdout), filepath.Join(dir, "go.mod"))
	}
	// stderr stays stderr.
	if r = run(runOpts{}, shim("go"), "build", "./nosuchpackage"); r.Exit == 0 || r.Stdout != "" || r.Stderr == "" {
		t.Errorf("failed go build through the shim: exit %d stdout %q stderr %q, want status != 0, text on stderr only", r.Exit, r.Stdout, r.Stderr)
	}
}

// TestRDEV008Signal: SIGTERM sent to the shim reaches the tool (a language server that waits for
// input), and the tool is gone afterwards.
func TestRDEV008Signal(t *testing.T) {
	parity.Covers(t, "R-DEV-008")
	w := newWorld(t)
	dir := w.fixture("acme")
	if _, ok := prepare(t, w, dir); !ok {
		return
	}
	shim := filepath.Join(dir, ".bob", "bin", "gopls")
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	argv := w.acc.hideNix([]string{shim})
	cmd := exec.CommandContext(ctx, argv[0], argv[1:]...)
	cmd.Dir = dir
	cmd.Env = append([]string{"PATH=/usr/bin:/bin", "TZ=UTC", "LC_ALL=C"}, append(w.env, shimEnv(t)...)...)
	w.acc.cred(cmd)
	in, err := cmd.StdinPipe() // stays open: gopls serves until EOF
	if err != nil {
		t.Fatal(err)
	}
	defer in.Close()
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Start(); err != nil {
		t.Fatalf("harness error: start shim: %v", err)
	}
	waitc := make(chan error, 1)
	go func() { waitc <- cmd.Wait() }()
	var tool int
	deadline := time.Now().Add(2 * time.Minute)
	for tool == 0 && time.Now().Before(deadline) {
		select {
		case err := <-waitc:
			t.Fatalf("the shim exited before it could be signalled: %v\n%s", err, stderr.String())
		case <-time.After(100 * time.Millisecond):
		}
		tool = findTool("/gopls", cmd.Process.Pid)
	}
	if tool == 0 {
		t.Fatalf("no gopls process started below the shim\n%s", stderr.String())
	}
	time.Sleep(500 * time.Millisecond)
	if err := syscall.Kill(cmd.Process.Pid, syscall.SIGTERM); err != nil {
		t.Fatal(err)
	}
	select {
	case err := <-waitc:
		ws, ok := cmd.ProcessState.Sys().(syscall.WaitStatus)
		if !ok || !((ws.Signaled() && ws.Signal() == syscall.SIGTERM) || ws.ExitStatus() == 128+int(syscall.SIGTERM)) {
			t.Errorf("after SIGTERM the shim ended with %v, want death by SIGTERM or exit 143", err)
		}
	case <-time.After(10 * time.Second):
		t.Fatalf("the shim did not end within 10 s of SIGTERM")
	}
	for range 50 {
		if !pidAlive(tool) {
			return
		}
		time.Sleep(100 * time.Millisecond)
	}
	t.Errorf("gopls (pid %d) is still running after SIGTERM to the shim", tool)
}

// findTool returns the pid of a descendant of root whose command line contains needle.
func findTool(needle string, root int) int {
	ents, _ := os.ReadDir("/proc")
	parent := map[int]int{}
	cmdline := map[int]string{}
	for _, e := range ents {
		pid, err := strconv.Atoi(e.Name())
		if err != nil {
			continue
		}
		st, err := os.ReadFile(fmt.Sprintf("/proc/%d/stat", pid))
		if err != nil {
			continue
		}
		s := string(st)
		f := strings.Fields(s[strings.LastIndexByte(s, ')')+2:])
		if len(f) < 2 {
			continue
		}
		pp, _ := strconv.Atoi(f[1])
		parent[pid] = pp
		b, _ := os.ReadFile(fmt.Sprintf("/proc/%d/cmdline", pid))
		cmdline[pid] = strings.ReplaceAll(string(b), "\x00", " ")
	}
	for pid, c := range cmdline {
		// Kernel threads and zombies have an empty command line.
		if f := strings.Fields(c); len(f) == 0 || !strings.Contains(f[0], needle) {
			continue
		}
		for p := pid; p > 1; p = parent[p] {
			if p == root {
				return pid
			}
		}
	}
	return 0
}

func pidAlive(pid int) bool {
	b, err := os.ReadFile(fmt.Sprintf("/proc/%d/stat", pid))
	if err != nil {
		return false
	}
	s := string(b)
	return !strings.HasPrefix(s[strings.LastIndexByte(s, ')')+2:], "Z")
}

// TestRDEV008ShimOverhead: starting /bin/true through bob exec (what a shim does) costs at most
// 15 ms p95 [8c/15G] / 20 ms [2c/4G] (budget B-080).
func TestRDEV008ShimOverhead(t *testing.T) {
	parity.Covers(t, "R-DEV-008")
	w := newWorld(t)
	dir := w.fixture("acme")
	if _, ok := prepare(t, w, dir); !ok {
		return
	}
	argv := []string{bobBin(t), "exec", "--project", dir, "--", "/bin/true"}
	if r := w.run(runOpts{dir: dir}, argv...); harness.Red(t, r) || !exitIs(t, r, 0) {
		return // the first run may realise the closure
	}
	const runs = 100
	ds := make([]time.Duration, 0, runs)
	for range runs {
		t0 := time.Now()
		r := w.run(runOpts{dir: dir}, argv...)
		ds = append(ds, time.Since(t0))
		if r.Exit != 0 {
			t.Fatalf("bob exec -- /bin/true: exit %d: %s", r.Exit, r.Stderr)
		}
	}
	limit := time.Duration(profile(15, 20) * float64(time.Millisecond))
	if got := p95(ds); got > limit {
		t.Errorf("shim start p95 = %s, budget (B-080) %s", got, limit)
	}
}
