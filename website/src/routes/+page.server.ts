import { highlight } from '$lib/server/highlight';
import { treeHTML, treeText } from '$lib/server/tree';
import type { PageServerLoad } from './$types';

// The front page's samples. The API calls are the ones of the pkg/golang and pkg/output/oci
// examples (example_test.go), so the sample stays honest; imports are left out for brevity.
const sample = `// Module is your go.mod, declared once.
var API = bob.Define(func(p *bob.P) *golang.Binary {
	return Module(p).Binary("./api", golang.BinaryOpts{})
})

var Image = bob.Define(func(p *bob.P) *oci.Image {
	return oci.NewImage(p, "api", oci.ImageOpts{Program: API(p)})
})
`;

const tree = `📁 shop/
  📄 bob.go          # the whole build
  🔒 bob.lock        # pins every input
  📁 api/
    🐹 main.go
  📁 engine/
    🦀 lib.rs
  📁 web/
    📦 package.json  # generated by bob
    📁 src/
`;

export const load: PageServerLoad = () => ({
	sample: { code: sample, html: highlight(sample, 'go') },
	tree: { html: treeHTML(tree), text: treeText(tree) }
});
