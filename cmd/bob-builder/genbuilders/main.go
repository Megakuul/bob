// Command genbuilders builds cmd/bob-builder for both systems the way R-NIX-015 prescribes and
// writes pkg/engine/store/builders.go (the {system → store path} table) and the embedded
// binaries pkg/engine/store/builderbin/<goarch>/bob-builder.gz. It runs through
// `go generate ./pkg/engine/store`.
//
// With -check it writes nothing: it fails when the committed table is stale, and (with -base,
// the table of the last commit) when the builder changed without a bspec.BuilderVersion bump
// (R-NIX-015; the CI command runs it).
package main

import (
	"bytes"
	"compress/gzip"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/megakuul/bob/pkg/builder/bspec"
	"github.com/megakuul/bob/pkg/engine/drv"
	"github.com/megakuul/bob/pkg/engine/nar"
)

var systems = []struct{ system, goarch string }{{"aarch64-linux", "arm64"}, {"x86_64-linux", "amd64"}}

func main() {
	check := flag.Bool("check", false, "write nothing; fail if builders.go is stale or the builder changed without a BuilderVersion bump")
	base := flag.String("base", "", "with -check: a copy of builders.go of the last commit (missing file = none)")
	flag.Parse()
	if err := run(*check, *base); err != nil {
		fmt.Fprintln(os.Stderr, "genbuilders:", err)
		os.Exit(1)
	}
}

// moduleRoot walks up from the working directory to the directory holding cmd/bob-builder.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "cmd", "bob-builder", "main.go")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("cmd/bob-builder not found above the working directory")
		}
		dir = parent
	}
}

func run(check bool, base string) error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	tmp, err := os.MkdirTemp("", "genbuilders-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	var table bytes.Buffer
	for _, s := range systems {
		tree := filepath.Join(tmp, s.goarch)
		bin := filepath.Join(tree, "bin", "bob-builder")
		cmd := exec.Command("go", "build", "-trimpath", "-buildvcs=false", "-ldflags=-s -w -buildid=", "-o", bin, "./cmd/bob-builder")
		cmd.Dir = root
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS=linux", "GOARCH="+s.goarch)
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("go build bob-builder (%s): %w: %s", s.goarch, err, out)
		}
		if err := os.Chmod(bin, 0o755); err != nil {
			return err
		}
		// The source path of the tree (as srcs.Path; pkg/engine/store must not be needed to
		// regenerate its own table).
		sum, _, err := nar.Hash(tree, []string{"bin/bob-builder"})
		if err != nil {
			return err
		}
		path, err := drv.MakeStorePath("source", sum, fmt.Sprintf("bob-builder-%d", bspec.BuilderVersion))
		if err != nil {
			return err
		}
		entry, err := tableCase(s.system, path)
		if err != nil {
			return err
		}
		table.WriteString(entry)
		if check {
			continue
		}
		if err := writeGzip(filepath.Join(root, "pkg", "engine", "store", "builderbin", s.goarch, "bob-builder.gz"), bin); err != nil {
			return err
		}
	}
	formatted, err := tableSource(table.String())
	if err != nil {
		return err
	}
	dst := filepath.Join(root, "pkg", "engine", "store", "builders.go")
	if !check {
		return os.WriteFile(dst, formatted, 0o644)
	}
	working, err := os.ReadFile(dst)
	if err != nil {
		return err
	}
	var committed []byte
	if base != "" {
		if committed, err = os.ReadFile(base); err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
	}
	return checkTables(string(formatted), string(working), string(committed))
}

// tableCase is the switch case of one system. The store hash is written with a "." after its
// first half, which storePath removes at run time (two separate literals are not enough: the
// linker may place them next to each other): bob's own binary, built by bob (R-ARCH-005), must not contain
// the store path of the bob-builder that built it, which the reference check forbids
// (R-NIX-019: "bob-builder" is in every output's forbidden set, BOB-E-9003, A453).
func tableCase(system, path string) (string, error) {
	base, ok := strings.CutPrefix(path, "/nix/store/")
	if !ok || len(base) < 34 || base[32] != '-' {
		return "", fmt.Errorf("builder store path %q has no store hash", path)
	}
	return fmt.Sprintf("\tcase %q:\n\t\treturn storePath(%q)\n", system, base[:16]+"."+base[16:]), nil
}

// tableSource is the formatted builders.go around the switch cases.
func tableSource(cases string) ([]byte, error) {
	return format.Source([]byte(fmt.Sprintf(`// Code generated by cmd/bob-builder/genbuilders (go generate ./pkg/engine/store). DO NOT EDIT.

package store

// builderTable is the store path of bob-builder per Nix system (R-NIX-015).
func builderTable(system string) string {
	switch system {
%s	}
	return ""
}

// storePath is "/nix/store/" + base without the "." after the hash's first half: a bob built
// by bob must not contain the builder's store hash (it would refer to the builder, BOB-E-9003).
func storePath(base string) string {
	return "/nix/store/" + base[:16] + base[17:]
}
`, cases)))
}

// tableEntry matches a case of builders.go: the split form tableCase writes, or the single
// string of builders.go files written before A453 (the last commit's table of -base).
var tableEntry = regexp.MustCompile(`case "([a-z0-9_]+-linux)":\s*return (?:"/nix/store/([0-9a-z]{32})-(bob-builder-\d+)"|storePath\("([0-9a-z]{16})\.([0-9a-z]{16})-(bob-builder-\d+)"\))`)

// tableOf parses a builders.go into system → store path.
func tableOf(src string) map[string]string {
	out := map[string]string{}
	for _, m := range tableEntry.FindAllStringSubmatch(src, -1) {
		if m[2] != "" {
			out[m[1]] = "/nix/store/" + m[2] + "-" + m[3]
		} else {
			out[m[1]] = "/nix/store/" + m[4] + m[5] + "-" + m[6]
		}
	}
	return out
}

// checkTables compares the table computed from the current builder sources with the committed
// one (working) and with the last commit's (base, "" if none): a different working table is
// stale; a builder whose store path changed while its version (the "-bob-builder-<n>" name)
// stayed the same is a builder change without a BuilderVersion bump (R-NIX-015).
func checkTables(computed, working, base string) error {
	now := tableOf(computed)
	if len(now) == 0 {
		return fmt.Errorf("no builder table computed")
	}
	if computed != working {
		return fmt.Errorf("pkg/engine/store/builders.go is stale: the builder sources changed; bump bspec.BuilderVersion if its behaviour changed, then run go generate ./pkg/engine/store")
	}
	var bad []string
	for system, old := range tableOf(base) {
		cur, ok := now[system]
		if ok && cur != old && version(cur) == version(old) {
			bad = append(bad, system)
		}
	}
	if len(bad) > 0 {
		slices.Sort(bad)
		return fmt.Errorf("bob-builder changed (%s) but bspec.BuilderVersion is still %s: bump it (R-NIX-015) and run go generate ./pkg/engine/store",
			strings.Join(bad, ", "), version(now[bad[0]]))
	}
	return nil
}

// version is the builder version in a store path ".../<hash>-bob-builder-<n>".
func version(path string) string { return path[strings.LastIndex(path, "-")+1:] }

// writeGzip writes a reproducible gzip of the file bin to dst.
func writeGzip(dst, bin string) error {
	b, err := os.ReadFile(bin)
	if err != nil {
		return err
	}
	var out bytes.Buffer
	zw, err := gzip.NewWriterLevel(&out, gzip.BestCompression)
	if err != nil {
		return err
	}
	if _, err := zw.Write(b); err != nil {
		return err
	}
	if err := zw.Close(); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	return os.WriteFile(dst, out.Bytes(), 0o644)
}
