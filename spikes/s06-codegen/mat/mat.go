// Package mat materialises codegen outputs (store directories) into the working tree.
//
// Rules (spike S6, proposal for SPEC):
//   - Each codegen package owns exactly one directory in the tree (a "root"). bob writes only
//     there; roots never overlap and never contain hand-written files.
//   - .bob/gen/manifest.json records, per root, the producing label, the store path and the
//     sha256 of every file bob wrote. A file is bob's if its hash matches the manifest (or the
//     write-ahead "pending" set, or the new desired content). Anything else is a conflict.
//   - Conflicts are never overwritten silently: the root is skipped and reported. With Force,
//     the conflicting files are moved to .bob/gen/backup/<time>/ first (never deleted).
//   - Every file is replaced atomically (temp file in the same directory, fsync, rename).
//     The manifest is written ahead (pending) and after (final), both atomically.
//   - Each root gets a .gitignore containing "*", so git ignores the whole directory.
//   - Files are made read-only (0444) so editors warn before a hand edit.
package mat

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"syscall"
	"time"
)

const (
	ManifestRel = ".bob/gen/manifest.json"
	LockRel     = ".bob/gen/lock"
	BackupRel   = ".bob/gen/backup"
	IgnoreName  = ".gitignore"
	IgnoreBody  = "# Generated by bob. Do not edit files in this directory: change the inputs and run `bob gen`.\n*\n"
	tmpMarker   = ".bob-tmp-"
)

type File struct {
	SHA256 string `json:"sha256"`
	Size   int64  `json:"size"`
	Exec   bool   `json:"exec,omitempty"`
	MTime  int64  `json:"mtime,omitempty"` // unix nanos of the file bob wrote (fast path only)
}

type Root struct {
	Label         string          `json:"label"`
	Source        string          `json:"source"` // store path the files came from
	Files         map[string]File `json:"files"`
	PendingSource string          `json:"pendingSource,omitempty"`
	Pending       map[string]File `json:"pending,omitempty"` // write-ahead: files being written
}

func (r *Root) fileOK(f string) (File, bool) {
	if r == nil || r.Pending != nil {
		return File{}, false
	}
	k, ok := r.Files[f]
	return k, ok
}

type Manifest struct {
	Version int              `json:"version"`
	Roots   map[string]*Root `json:"roots"`
}

// Want is one codegen output that should be in the tree.
type Want struct {
	Dir    string // repo-relative, slash separated
	Label  string
	Source string // directory whose tree is copied (a store path)
}

type Conflict struct {
	Root  string
	Path  string // repo-relative
	Kind  string // edited | foreign | tracked
	Label string
}

func (c Conflict) String() string {
	switch c.Kind {
	case "edited":
		return fmt.Sprintf("%s was edited by hand (generated by %s)", c.Path, c.Label)
	case "foreign":
		return fmt.Sprintf("%s is not a file bob generated, but it is inside %s, which bob owns for %s", c.Path, c.Root+"/", c.Label)
	case "tracked":
		return fmt.Sprintf("%s is tracked by git, but %s is generated by %s", c.Path, c.Root+"/", c.Label)
	}
	return c.Path + ": " + c.Kind
}

type Options struct {
	Force bool // back up conflicting files, then overwrite
	Prune bool // remove roots that are in the manifest but no longer wanted
	Check bool // dry run: report only
	Git   bool // check that roots contain no git-tracked files
	// Keep lists roots that are still defined in the graph but not written by this run
	// (e.g. `bob build` of one target); Prune never removes them.
	Keep []string
}

type RootState struct {
	Dir, Label, State string // fresh | written | stale | missing | conflict | orphan | removed
	Writes, Removes  []string
}

type Result struct {
	Written, Removed, Unchanged, Hashed int
	Roots                               []RootState
	Conflicts                           []Conflict
	Backups                             []string
}

// ConflictError is returned when at least one root was skipped because of conflicts.
type ConflictError struct{ Conflicts []Conflict }

func (e *ConflictError) Error() string {
	var b strings.Builder
	fmt.Fprintf(&b, "✗ bob gen: %d file(s) in generated directories are not bob's to overwrite; those directories were left untouched\n", len(e.Conflicts))
	for _, c := range e.Conflicts {
		fmt.Fprintf(&b, "  • %s\n", c)
	}
	b.WriteString("  hint: generated code is rebuilt from its inputs (.proto, .graphqls, OpenAPI spec, bob.go).\n" +
		"        Change the input instead. To discard the edits run `bob gen --force`\n" +
		"        (bob moves the edited files to " + BackupRel + "/<time>/ first).")
	return b.String()
}

var ErrBadPath = errors.New("invalid materialisation path")

func cleanRel(p string) (string, error) {
	if p == "" || strings.HasPrefix(p, "/") || strings.Contains(p, "\\") {
		return "", fmt.Errorf("%w: %q", ErrBadPath, p)
	}
	c := path.Clean(p)
	if c == "." || c == ".." || strings.HasPrefix(c, "../") || c != p {
		return "", fmt.Errorf("%w: %q", ErrBadPath, p)
	}
	for _, seg := range strings.Split(c, "/") {
		if seg == ".git" || seg == ".bob" {
			return "", fmt.Errorf("%w: %q (inside %s)", ErrBadPath, p, seg)
		}
	}
	return c, nil
}

func hashFile(p string) (string, int64, error) {
	f, err := os.Open(p)
	if err != nil {
		return "", 0, err
	}
	defer f.Close()
	h := sha256.New()
	n, err := io.Copy(h, f)
	if err != nil {
		return "", 0, err
	}
	return hex.EncodeToString(h.Sum(nil)), n, nil
}

// desired lists the files of a source tree. Hashes of an unchanged source are reused from the
// manifest (store paths are immutable), so a no-op never reads the store.
func desired(src string, old *Root, res *Result) (map[string]File, error) {
	if old != nil && old.Source == src && old.Files != nil {
		return old.Files, nil
	}
	out := map[string]File{}
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(src, p)
		rel = filepath.ToSlash(rel)
		if !d.Type().IsRegular() {
			return fmt.Errorf("codegen output %s contains a non-regular file %s", src, rel)
		}
		if rel == IgnoreName {
			return fmt.Errorf("codegen output %s contains its own %s", src, IgnoreName)
		}
		fi, err := d.Info()
		if err != nil {
			return err
		}
		h, n, err := hashFile(p)
		if err != nil {
			return err
		}
		res.Hashed++
		out[rel] = File{SHA256: h, Size: n, Exec: fi.Mode()&0o111 != 0}
		return nil
	})
	return out, err
}

func load(repo string) (*Manifest, error) {
	m := &Manifest{Version: 1, Roots: map[string]*Root{}}
	b, err := os.ReadFile(filepath.Join(repo, ManifestRel))
	if errors.Is(err, fs.ErrNotExist) {
		return m, nil
	}
	if err != nil {
		return nil, err
	}
	if len(b) > 64<<20 {
		return nil, fmt.Errorf("%s is larger than 64 MiB", ManifestRel)
	}
	if err := json.Unmarshal(b, m); err != nil {
		return nil, fmt.Errorf("%s is corrupt (%v); delete it and run `bob gen --force`", ManifestRel, err)
	}
	if m.Version != 1 {
		return nil, fmt.Errorf("%s has unknown version %d", ManifestRel, m.Version)
	}
	if m.Roots == nil {
		m.Roots = map[string]*Root{}
	}
	for dir, r := range m.Roots { // hostile-input check: the manifest is a file in the tree
		if _, err := cleanRel(dir); err != nil {
			return nil, fmt.Errorf("%s: %w", ManifestRel, err)
		}
		for _, files := range []map[string]File{r.Files, r.Pending} {
			for f := range files {
				if _, err := cleanRel(f); err != nil {
					return nil, fmt.Errorf("%s: root %s: %w", ManifestRel, dir, err)
				}
			}
		}
	}
	return m, nil
}

func writeAtomic(p string, data []byte, mode os.FileMode) error {
	dir := filepath.Dir(p)
	f, err := os.CreateTemp(dir, "."+filepath.Base(p)+tmpMarker+"*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	ok := false
	defer func() {
		if !ok {
			f.Close()
			os.Remove(tmp)
		}
	}()
	if _, err := f.Write(data); err != nil {
		return err
	}
	if err := f.Sync(); err != nil {
		return err
	}
	if err := f.Chmod(mode); err != nil {
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmp, p); err != nil {
		return err
	}
	ok = true
	return syncDir(dir)
}

func syncDir(dir string) error {
	d, err := os.Open(dir)
	if err != nil {
		return err
	}
	defer d.Close()
	return d.Sync()
}

func save(repo string, m *Manifest) error {
	b, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	p := filepath.Join(repo, ManifestRel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	ig := filepath.Join(repo, ".bob", IgnoreName) // bob's state directory is never committed
	if _, err := os.Stat(ig); errors.Is(err, fs.ErrNotExist) {
		if err := writeAtomic(ig, []byte("# bob state, never committed\n*\n"), 0o644); err != nil {
			return err
		}
	}
	b = append(b, '\n')
	if old, err := os.ReadFile(p); err == nil && bytes.Equal(old, b) {
		return nil // no-op runs never touch the disk
	}
	return writeAtomic(p, b, 0o644)
}

func lock(repo string) (func(), error) {
	p := filepath.Join(repo, LockRel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(p, os.O_CREATE|os.O_RDWR, 0o644)
	if err != nil {
		return nil, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		f.Close()
		return nil, err
	}
	return func() { _ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN); f.Close() }, nil
}

type plan struct {
	dir       string
	label     string
	src       string
	want      map[string]File
	writes    []string
	removes   []string
	tmps      []string
	ignore    bool // .gitignore must be (re)written
	conflicts []Conflict
}

// scan compares the tree under dir with old (manifest) and want (nil for an orphan).
func scan(repo string, dir, label, src string, old *Root, want map[string]File, res *Result) (*plan, error) {
	pl := &plan{dir: dir, label: label, src: src, want: want}
	// known returns the manifest entry for f; a hash in the write-ahead set also counts.
	known := func(f, h string) (File, bool) {
		if old == nil {
			return File{}, false
		}
		k, ok := old.Files[f]
		if pk, pok := old.Pending[f]; pok && (!ok || h == pk.SHA256) {
			return pk, true
		}
		return k, ok
	}
	seen := map[string]bool{}
	abs := filepath.Join(repo, dir)
	err := filepath.WalkDir(abs, func(p string, d fs.DirEntry, err error) error {
		if errors.Is(err, fs.ErrNotExist) && p == abs {
			return fs.SkipAll
		}
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(abs, p)
		rel = filepath.ToSlash(rel)
		repoRel := dir + "/" + rel
		if strings.Contains(path.Base(rel), tmpMarker) {
			pl.tmps = append(pl.tmps, rel) // left over from an interrupted write
			return nil
		}
		if rel == IgnoreName {
			b, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			if string(b) != IgnoreBody {
				pl.conflicts = append(pl.conflicts, Conflict{dir, repoRel, "foreign", label})
			}
			seen[rel] = true
			return nil
		}
		seen[rel] = true
		if !d.Type().IsRegular() {
			pl.conflicts = append(pl.conflicts, Conflict{dir, repoRel, "foreign", label})
			return nil
		}
		w, isWanted := want[rel]
		fi, err := d.Info()
		if err != nil {
			return err
		}
		var h string
		if k, ok := old.fileOK(rel); ok && k.MTime != 0 && fi.ModTime().UnixNano() == k.MTime && fi.Size() == k.Size {
			h = k.SHA256 // fast path: unchanged since bob wrote it
		} else {
			if h, _, err = hashFile(p); err != nil {
				return err
			}
			res.Hashed++
		}
		k, isKnown := known(rel, h)
		switch {
		case isWanted && h == w.SHA256:
			if (fi.Mode()&0o111 != 0) != w.Exec || fi.Mode()&0o222 != 0 {
				pl.writes = append(pl.writes, rel) // right content, wrong mode
			}
		case isKnown && h == k.SHA256:
			if isWanted {
				pl.writes = append(pl.writes, rel)
			} else {
				pl.removes = append(pl.removes, rel)
			}
		case isKnown:
			pl.conflicts = append(pl.conflicts, Conflict{dir, repoRel, "edited", label})
		default:
			pl.conflicts = append(pl.conflicts, Conflict{dir, repoRel, "foreign", label})
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	for f := range want {
		if !seen[f] {
			pl.writes = append(pl.writes, f)
		}
	}
	pl.ignore = want != nil && !seen[IgnoreName]
	sort.Strings(pl.writes)
	sort.Strings(pl.removes)
	return pl, nil
}

func gitTracked(repo string, dirs []string) (map[string][]string, error) {
	out := map[string][]string{}
	if len(dirs) == 0 {
		return out, nil
	}
	if _, err := exec.LookPath("git"); err != nil {
		return out, nil
	}
	cmd := exec.Command("git", append([]string{"-C", repo, "ls-files", "-z", "--"}, dirs...)...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	b, err := cmd.Output()
	if err != nil {
		if strings.Contains(stderr.String(), "not a git repository") {
			return out, nil
		}
		return nil, fmt.Errorf("git ls-files: %v: %s", err, stderr.String())
	}
	for _, f := range strings.Split(string(b), "\x00") {
		if f == "" {
			continue
		}
		for _, d := range dirs {
			if strings.HasPrefix(f, d+"/") {
				out[d] = append(out[d], f)
			}
		}
	}
	return out, nil
}

// Apply brings the tree in line with wants.
func Apply(repo string, wants []Want, opt Options) (*Result, error) {
	res := &Result{}
	unlock, err := lock(repo)
	if err != nil {
		return nil, err
	}
	defer unlock()
	m, err := load(repo)
	if err != nil {
		return nil, err
	}
	// validate wants: clean, unique, non-overlapping
	byDir := map[string]Want{}
	var dirs []string
	for _, w := range wants {
		d, err := cleanRel(w.Dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", w.Label, err)
		}
		if o, dup := byDir[d]; dup {
			return nil, fmt.Errorf("✗ %s and %s both generate into %s/\n  hint: give one of them another output directory", o.Label, w.Label, d)
		}
		w.Dir = d
		byDir[d] = w
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	for i := 1; i < len(dirs); i++ {
		if strings.HasPrefix(dirs[i], dirs[i-1]+"/") {
			return nil, fmt.Errorf("✗ %s generates into %s/, which is inside %s/ owned by %s\n  hint: generated directories may not be nested", byDir[dirs[i]].Label, dirs[i], dirs[i-1], byDir[dirs[i-1]].Label)
		}
	}
	tracked := map[string][]string{}
	if opt.Git {
		if tracked, err = gitTracked(repo, dirs); err != nil {
			return nil, err
		}
	}
	var plans []*plan
	for _, d := range dirs {
		w := byDir[d]
		old := m.Roots[d]
		want, err := desired(w.Source, old, res)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", w.Label, err)
		}
		pl, err := scan(repo, d, w.Label, w.Source, old, want, res)
		if err != nil {
			return nil, err
		}
		for _, f := range tracked[d] {
			pl.conflicts = append(pl.conflicts, Conflict{d, f, "tracked", w.Label})
		}
		plans = append(plans, pl)
	}
	if opt.Prune {
		keep := map[string]bool{}
		for _, k := range opt.Keep {
			keep[k] = true
		}
		var orphans []string
		for d := range m.Roots {
			if _, ok := byDir[d]; !ok && !keep[d] {
				orphans = append(orphans, d)
			}
		}
		sort.Strings(orphans)
		for _, d := range orphans {
			old := m.Roots[d]
			pl, err := scan(repo, d, old.Label, "", old, nil, res)
			if err != nil {
				return nil, err
			}
			plans = append(plans, pl)
		}
	}

	backupDir := filepath.Join(BackupRel, time.Now().UTC().Format("20060102T150405.000000000Z"))
	for _, pl := range plans {
		st := RootState{Dir: pl.dir, Label: pl.label, Writes: pl.writes, Removes: pl.removes}
		old := m.Roots[pl.dir]
		switch {
		case len(pl.conflicts) > 0 && !opt.Force:
			st.State = "conflict"
			res.Conflicts = append(res.Conflicts, pl.conflicts...)
		case pl.want == nil:
			st.State = "orphan"
		case old == nil || len(old.Files) == 0 && len(pl.writes) > 0:
			st.State = "missing"
		case len(pl.writes)+len(pl.removes)+len(pl.tmps)+len(pl.conflicts) == 0 && !pl.ignore:
			st.State = "fresh"
		default:
			st.State = "stale"
		}
		if opt.Check || st.State == "conflict" || st.State == "fresh" {
			if st.State == "fresh" {
				res.Unchanged += len(pl.want)
				if old.Source != pl.src { // same content from a new store path
					old.Source = pl.src
				}
			}
			res.Roots = append(res.Roots, st)
			continue
		}
		if len(pl.conflicts) > 0 { // Force: move conflicting files away, never delete them
			for _, c := range pl.conflicts {
				if c.Kind == "tracked" {
					return nil, fmt.Errorf("✗ %s\n  hint: run `git rm -r --cached %s` and commit; generated code must not be committed", c, pl.dir)
				}
				dst := filepath.Join(repo, backupDir, c.Path)
				if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
					return nil, err
				}
				if err := os.Rename(filepath.Join(repo, c.Path), dst); err != nil {
					return nil, err
				}
				res.Backups = append(res.Backups, filepath.Join(backupDir, c.Path))
				rel := strings.TrimPrefix(c.Path, pl.dir+"/")
				if _, ok := pl.want[rel]; ok {
					pl.writes = append(pl.writes, rel)
				}
				if rel == IgnoreName {
					pl.ignore = true
				}
			}
		}
		if err := applyPlan(repo, m, pl, res); err != nil {
			return nil, err
		}
		switch {
		case pl.want == nil:
			st.State = "removed"
		case len(pl.writes) == 0 && len(pl.removes) == 0:
			st.State = "adopted" // files already right (e.g. manifest lost); now recorded
		default:
			st.State = "written"
		}
		res.Roots = append(res.Roots, st)
	}
	if !opt.Check {
		if err := save(repo, m); err != nil {
			return nil, err
		}
	}
	if len(res.Conflicts) > 0 {
		return res, &ConflictError{res.Conflicts}
	}
	return res, nil
}

func applyPlan(repo string, m *Manifest, pl *plan, res *Result) error {
	abs := filepath.Join(repo, pl.dir)
	old := m.Roots[pl.dir]
	if old == nil {
		old = &Root{Label: pl.label, Files: map[string]File{}}
		m.Roots[pl.dir] = old
	}
	// write-ahead: whatever happens next, files with these hashes are bob's
	if pl.want != nil {
		old.Pending, old.PendingSource = pl.want, pl.src
		if err := save(repo, m); err != nil {
			return err
		}
	}
	for _, t := range pl.tmps {
		_ = os.Remove(filepath.Join(abs, t))
	}
	newFiles := map[string]File{}
	for f, w := range pl.want {
		newFiles[f] = w
	}
	for _, f := range pl.writes {
		w := pl.want[f]
		b, err := os.ReadFile(filepath.Join(pl.src, f))
		if err != nil {
			return err
		}
		dst := filepath.Join(abs, f)
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return err
		}
		mode := os.FileMode(0o444)
		if w.Exec {
			mode = 0o555
		}
		if err := writeAtomic(dst, b, mode); err != nil {
			return err
		}
		res.Written++
	}
	for _, f := range pl.removes {
		if err := os.Remove(filepath.Join(abs, f)); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		res.Removed++
	}
	if pl.want == nil {
		if err := os.Remove(filepath.Join(abs, IgnoreName)); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
	} else if pl.ignore {
		if err := os.MkdirAll(abs, 0o755); err != nil {
			return err
		}
		if err := writeAtomic(filepath.Join(abs, IgnoreName), []byte(IgnoreBody), 0o444); err != nil {
			return err
		}
	}
	removeEmptyDirs(abs, pl.want == nil)
	if pl.want == nil {
		// also drop parents that are now empty (svc/gen/proto/billing after billing/v1)
		for d := filepath.Dir(abs); d != repo && strings.HasPrefix(d, repo+string(filepath.Separator)); d = filepath.Dir(d) {
			if os.Remove(d) != nil {
				break
			}
		}
		delete(m.Roots, pl.dir)
		return nil
	}
	for f, w := range newFiles { // record stat for the fast path
		if fi, err := os.Stat(filepath.Join(abs, f)); err == nil {
			w.MTime = fi.ModTime().UnixNano()
			newFiles[f] = w
		}
	}
	old.Label, old.Source, old.Files, old.Pending, old.PendingSource = pl.label, pl.src, newFiles, nil, ""
	return nil
}

func removeEmptyDirs(root string, includeRoot bool) {
	var dirs []string
	_ = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err == nil && d.IsDir() {
			dirs = append(dirs, p)
		}
		return nil
	})
	for i := len(dirs) - 1; i >= 0; i-- {
		if dirs[i] == root && !includeRoot {
			continue
		}
		_ = os.Remove(dirs[i]) // fails (and is ignored) unless empty
	}
}

// Owned returns the materialised roots recorded in the manifest (used to exclude them from
// source hashing, R-FW-021).
func Owned(repo string) ([]string, error) {
	m, err := load(repo)
	if err != nil {
		return nil, err
	}
	var out []string
	for d := range m.Roots {
		out = append(out, d)
	}
	sort.Strings(out)
	return out, nil
}

// Status reports, without building or writing, how each defined root compares with the tree.
// outs maps root dir -> label + the store path the current graph would produce.
type StatusEntry struct {
	Dir, Label, State string // fresh | stale | missing | edited | orphan
	Detail            []string
}

func Status(repo string, outs map[string][2]string) ([]StatusEntry, error) {
	m, err := load(repo)
	if err != nil {
		return nil, err
	}
	var dirs []string
	for d := range outs {
		dirs = append(dirs, d)
	}
	for d := range m.Roots {
		if _, ok := outs[d]; !ok {
			dirs = append(dirs, d)
		}
	}
	sort.Strings(dirs)
	var res []StatusEntry
	for _, d := range dirs {
		o, defined := outs[d]
		r := m.Roots[d]
		st := StatusEntry{Dir: d, Label: o[0]}
		switch {
		case !defined:
			st.State, st.Label = "orphan", r.Label
		case r == nil:
			st.State = "missing"
		case r.Source != o[1] || r.Pending != nil:
			st.State = "stale"
		default:
			st.State = "fresh"
		}
		if r != nil {
			pl, err := scan(repo, d, st.Label, r.Source, r, r.Files, &Result{})
			if err != nil {
				return nil, err
			}
			for _, c := range pl.conflicts {
				st.Detail = append(st.Detail, c.String())
			}
			if len(pl.conflicts) > 0 {
				st.State = "edited"
			} else if st.State == "fresh" && len(pl.writes)+len(pl.removes) > 0 {
				st.State = "stale"
				st.Detail = append(st.Detail, "files missing or with wrong mode: "+strings.Join(pl.writes, ", "))
			}
		}
		res = append(res, st)
	}
	return res, nil
}

// SourceOf returns the store path recorded for a root ("" if none).
func SourceOf(repo, dir string) string {
	m, err := load(repo)
	if err != nil || m.Roots[dir] == nil {
		return ""
	}
	return m.Roots[dir].Source
}
