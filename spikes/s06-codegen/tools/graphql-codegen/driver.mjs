// bob-owned driver for graphql-codegen: calls the plugin API directly (no CLI, no codegen.yml).
// usage: node driver.mjs OUT.ts SCHEMA.graphqls [SCHEMA...] -- DOC.graphql [DOC...]
import fs from "node:fs";
import { codegen } from "@graphql-codegen/core";
import * as typescript from "@graphql-codegen/typescript";
import * as typescriptOperations from "@graphql-codegen/typescript-operations";
import { parse, concatAST, Source } from "graphql";

const args = process.argv.slice(2);
const out = args[0];
const sep = args.indexOf("--");
const schemas = args.slice(1, sep < 0 ? undefined : sep);
const docs = sep < 0 ? [] : args.slice(sep + 1);
process.on("uncaughtException", (e) => fail(e));
process.on("unhandledRejection", (e) => fail(e));
function fail(e) {
  // bob shows the message, not a Node stack trace into the store
  const msg = (e && (e.message || String(e))) || "unknown error";
  const loc = e && e.locations && e.locations[0] ? `:${e.locations[0].line}:${e.locations[0].column}` : "";
  const src = e && e.source && e.source.name && e.source.name !== "GraphQL request" ? e.source.name : "";
  console.error(`${src}${loc}${src || loc ? ": " : ""}${msg}`);
  process.exit(1);
}
const schema = concatAST(schemas.map((f) => parse(new Source(fs.readFileSync(f, "utf8"), f))));
const documents = docs.map((f) => ({ location: f, document: parse(new Source(fs.readFileSync(f, "utf8"), f)) }));
const text = await codegen({
  filename: out,
  schema,
  documents,
  config: { enumsAsTypes: true, useTypeImports: true },
  plugins: [{ typescript: {} }, { typescriptOperations: {} }],
  pluginMap: { typescript, typescriptOperations },
});
fs.writeFileSync(out, "// Code generated by bob (graphql-codegen). DO NOT EDIT.\n" + text);
