// Package reg is the S11 proof of concept for zero-setup worker registration:
// a worker writes a self-signed registration record into the fleet bucket, an
// orchestrator reconciles it and writes back a token sealed (HPKE) to the
// worker's public key, and the worker proves key possession on every call.
package reg

import (
	"bytes"
	"crypto/ecdh"
	"crypto/ed25519"
	"crypto/hpke"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base32"
	"encoding/binary"
	"errors"
	"fmt"
	"strconv"
)

// Suite selects the HPKE KEM. KDF is HKDF-SHA256, AEAD is ChaCha20-Poly1305.
type Suite uint16

const (
	SuiteX25519         Suite = 0x0020 // DHKEM(X25519, HKDF-SHA256), RFC 9180
	SuiteMLKEM768X25519 Suite = 0x647a // hybrid ML-KEM-768 + X25519 (X-Wing style), Go 1.26 crypto/hpke
)

func (s Suite) kem() (hpke.KEM, error) {
	switch s {
	case SuiteX25519:
		return hpke.DHKEM(ecdh.X25519()), nil
	case SuiteMLKEM768X25519:
		return hpke.MLKEM768X25519(), nil
	}
	return nil, fmt.Errorf("unsupported KEM suite 0x%04x", uint16(s))
}

var (
	kdf  = hpke.HKDFSHA256()
	aead = hpke.ChaCha20Poly1305()
)

// Domain separation strings. Every signature and every HPKE info carries one.
const (
	dsWorkerID = "bob-worker-id-v1"
	dsReg      = "bob-wreg-v1"
	dsToken    = "bob-wtok-v1"
	dsSeal     = "bob-wseal-v1"
	dsPoP      = "bob-pop-v1"
)

// WorkerKeys are generated by the worker at start and never leave its memory.
type WorkerKeys struct {
	Suite  Suite
	Sig    ed25519.PrivateKey
	KEM    hpke.PrivateKey
	KEMPub []byte
}

// NewWorkerKeys creates a fresh signing key and KEM key.
func NewWorkerKeys(s Suite) (*WorkerKeys, error) {
	_, sk, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return nil, err
	}
	kem, err := s.kem()
	if err != nil {
		return nil, err
	}
	dk, err := kem.GenerateKey()
	if err != nil {
		return nil, err
	}
	return &WorkerKeys{Suite: s, Sig: sk, KEM: dk, KEMPub: dk.PublicKey().Bytes()}, nil
}

// SigPub returns the Ed25519 public key.
func (k *WorkerKeys) SigPub() ed25519.PublicKey { return k.Sig.Public().(ed25519.PublicKey) }

// ID returns the worker id derived from the public keys.
func (k *WorkerKeys) ID() string { return WorkerID(k.SigPub(), k.Suite, k.KEMPub) }

var b32 = base32.NewEncoding("abcdefghijklmnopqrstuvwxyz234567").WithPadding(base32.NoPadding)

// WorkerID = "w" + base32(SHA-256(ds || len||sigpub || suite || len||kempub))[:26] (130 bits).
// Because the id is a hash of the keys, a record cannot be re-pointed at other keys.
func WorkerID(sigPub []byte, s Suite, kemPub []byte) string {
	h := sha256.New()
	h.Write([]byte(dsWorkerID))
	writeLV(h, sigPub)
	binary.Write(h, binary.BigEndian, uint16(s))
	writeLV(h, kemPub)
	return "w" + b32.EncodeToString(h.Sum(nil))[:26]
}

func writeLV(w interface{ Write([]byte) (int, error) }, b []byte) {
	var l [4]byte
	binary.BigEndian.PutUint32(l[:], uint32(len(b)))
	w.Write(l[:])
	w.Write(b)
}

func msg(ds string, parts ...[]byte) []byte {
	var b bytes.Buffer
	b.WriteString(ds)
	b.WriteByte(0)
	for _, p := range parts {
		writeLV(&b, p)
	}
	return b.Bytes()
}

// sealInfo binds a sealed token to the worker id, generation and serial, so a
// ciphertext moved to another worker record (or replayed at another serial) fails to open.
func sealInfo(workerID string, gen, serial int) []byte {
	return msg(dsSeal, []byte(workerID), []byte(strconv.Itoa(gen)), []byte(strconv.Itoa(serial)))
}

// Seal encrypts plaintext to a worker KEM public key.
func Seal(s Suite, kemPub []byte, workerID string, gen, serial int, plaintext []byte) ([]byte, error) {
	kem, err := s.kem()
	if err != nil {
		return nil, err
	}
	pk, err := kem.NewPublicKey(kemPub)
	if err != nil {
		return nil, err
	}
	return hpke.Seal(pk, kdf, aead, sealInfo(workerID, gen, serial), plaintext)
}

// Open decrypts a sealed token with the worker's KEM private key.
func (k *WorkerKeys) Open(workerID string, gen, serial int, ct []byte) ([]byte, error) {
	return hpke.Open(k.KEM, kdf, aead, sealInfo(workerID, gen, serial), ct)
}

// ErrBadSignature is returned for any signature that does not verify.
var ErrBadSignature = errors.New("bad signature")
