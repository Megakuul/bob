package ocamlgen

import (
	"fmt"
	"sort"
	"strings"

	"bobspike/s05/drv"
)

// MLLib is a local OCaml library (ocaml.Library in bob.go).
type MLLib struct {
	Name  string   `json:"name"`
	Src   string   `json:"src"`
	Libs  []string `json:"libs"`  // findlib names: opam libraries (fmt, lwt.unix) or local libraries
	Stubs []string `json:"stubs"` // C stub files without .c
	CLibs []string `json:"clibs"` // bob C libraries to link
}

// MLExe is a local native executable (ocaml.Executable).
type MLExe struct {
	Name string   `json:"name"`
	Src  string   `json:"src"`
	Main string   `json:"main"`
	Libs []string `json:"libs"`
}

// Mode selects how bob's own OCaml code is compiled.
type Mode string

const (
	Direct Mode = "direct" // ocamldep -sort + ocamlfind ocamlopt, no dune
	Dune   Mode = "dune"   // generated dune files, `dune build` inside the derivation
)

// Local holds what the generator needs about local targets.
type Local struct {
	Libs  map[string]*MLLib
	CLibs map[string]bool
	Mode  Mode
	built map[string]*drv.Derivation
}

func (g *Gen) CLib(name string) (*drv.Derivation, error) {
	if d := g.pkgs["c:"+name]; d != nil {
		return d, nil
	}
	e, err := g.toolEnv()
	if err != nil {
		return nil, err
	}
	src := g.Srcs["c:"+name]
	e.srcs = append(e.srcs, src)
	s := fmt.Sprintf(`mkdir -p $out/lib $out/include && cd $TMPDIR
for f in %[1]s/*.c; do cc -O2 -fPIC -I%[1]s/include -c "$f" -o "$(basename "$f" .c).o"; done
ar rcs $out/lib/lib%[2]s.a *.o
cp %[1]s/include/*.h $out/include/
`, src, name)
	d, err := g.finish("c", "c-"+name, "//"+name+":"+name, e, s, nil)
	if err == nil {
		g.pkgs["c:"+name] = d
	}
	return d, err
}

// opamPkgOf maps a findlib library name to its opam package (prefix before the first dot).
func opamPkgOf(lib string) string { p, _, _ := strings.Cut(lib, "."); return p }

// deps collects inputs for a local target: opam closure, local libs, C libs.
func (g *Gen) localDeps(l *Local, e *env, libs []string, clibs []string) (ocamlpath []string, cflags, ldflags []string, err error) {
	var opamRoots []string
	for _, lb := range libs {
		p := opamPkgOf(lb)
		if ll := l.Libs[p]; ll != nil {
			d, err := g.LocalLib(l, ll)
			if err != nil {
				return nil, nil, nil, err
			}
			e.inputs[d.DrvPath] = []string{"out"}
			ocamlpath = append(ocamlpath, d.OutPath+"/lib")
			sub, c2, l2, err := g.localDeps(l, e, ll.Libs, ll.CLibs)
			if err != nil {
				return nil, nil, nil, err
			}
			ocamlpath = append(ocamlpath, sub...)
			cflags, ldflags = append(cflags, c2...), append(ldflags, l2...)
			continue
		}
		if g.Lock.Packages[p] == nil && p != "unix" && p != "threads" && p != "str" {
			return nil, nil, nil, fmt.Errorf("library %s: opam package %s is not declared (add it to opam deps and run bob lock)", lb, p)
		}
		if g.Lock.Packages[p] != nil {
			opamRoots = append(opamRoots, p)
		}
	}
	clo, err := g.Closure(opamRoots)
	if err != nil {
		return nil, nil, nil, err
	}
	for _, n := range clo {
		d, err := g.Package(n)
		if err != nil {
			return nil, nil, nil, err
		}
		e.inputs[d.DrvPath] = []string{"out"}
		ocamlpath = append(ocamlpath, d.OutPath+"/lib")
	}
	for _, c := range clibs {
		d, err := g.CLib(c)
		if err != nil {
			return nil, nil, nil, err
		}
		e.inputs[d.DrvPath] = []string{"out"}
		cflags = append(cflags, "-I"+d.OutPath+"/include")
		ldflags = append(ldflags, "-L"+d.OutPath+"/lib", "-l"+c)
	}
	sort.Strings(ocamlpath)
	return uniq(ocamlpath), cflags, ldflags, nil
}

func capital(s string) string { return strings.ToUpper(s[:1]) + s[1:] }

// DuneLib renders the dune stanza bob generates for a library (also written to the tree).
func DuneLib(ll *MLLib, cflags, ldflags []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "; generated by bob from bob.go — do not edit\n(library\n (name %s)\n (public_name %s)", ll.Name, ll.Name)
	if len(ll.Libs) > 0 {
		fmt.Fprintf(&b, "\n (libraries %s)", strings.Join(ll.Libs, " "))
	}
	if len(ll.Stubs) > 0 {
		fmt.Fprintf(&b, "\n (foreign_stubs (language c) (names %s) (flags :standard %s))", strings.Join(ll.Stubs, " "), strings.Join(cflags, " "))
	}
	if len(ldflags) > 0 {
		fmt.Fprintf(&b, "\n (c_library_flags %s)", strings.Join(ldflags, " "))
	}
	b.WriteString(")\n")
	return b.String()
}

func DuneExe(x *MLExe) string {
	return fmt.Sprintf("; generated by bob from bob.go — do not edit\n(executable\n (name %s)\n (libraries %s))\n", x.Main, strings.Join(x.Libs, " "))
}

const DuneProject = "(lang dune 3.21)\n"

func (g *Gen) commonEnv(ocamlpath []string) string {
	ocaml := g.Tool("ocamlPackages.ocaml")
	ocamlpath = append(ocamlpath, fmt.Sprintf("%s/lib/ocaml/%s/site-lib", g.Tool("ocamlPackages.findlib"), g.Ix.Attrs["ocamlPackages.ocaml"].Version))
	return fmt.Sprintf("export OCAMLPATH=%s\nexport OCAMLFIND_DESTDIR=$out/lib OCAMLFIND_LDCONF=ignore CAML_LD_LIBRARY_PATH=%s/lib/ocaml/stublibs\ncd $TMPDIR\n",
		strings.Join(ocamlpath, ":"), ocaml)
}

// LocalLib compiles one local library.
func (g *Gen) LocalLib(l *Local, ll *MLLib) (*drv.Derivation, error) {
	if d := l.built[ll.Name]; d != nil {
		return d, nil
	}
	e, err := g.toolEnv()
	if err != nil {
		return nil, err
	}
	src := g.Srcs["ml:"+ll.Name]
	e.srcs = append(e.srcs, src)
	op, cflags, ldflags, err := g.localDeps(l, e, ll.Libs, ll.CLibs)
	if err != nil {
		return nil, fmt.Errorf("//%s: %v", ll.Name, err)
	}
	var s strings.Builder
	s.WriteString(g.commonEnv(op))
	fmt.Fprintf(&s, "cp -r %s/. src && chmod -R u+w src && cd src\n", src)
	M := capital(ll.Name)
	switch l.Mode {
	case Dune:
		fmt.Fprintf(&s, "printf '%%s' %s > dune-project\nprintf '%%s' %s > dune\ntouch %s.opam\n", shq(DuneProject), shq(DuneLib(ll, cflags, ldflags)), ll.Name)
		fmt.Fprintf(&s, "dune build -p %[1]s -j $NIX_BUILD_CORES @install 2>&1\nopam-installer --prefix=$out --libdir=$out/lib --stubsdir=$out/lib/stublibs %[1]s.install\n", ll.Name)
	default:
		pk := ""
		if len(ll.Libs) > 0 {
			pk = "-package " + strings.Join(ll.Libs, ",")
		}
		// dune-compatible wrapping: modules become <Lib>__<Mod>, the alias module <lib>__
		// re-exports them; <lib>.ml (if present) is the library interface.
		fmt.Fprintf(&s, `L=%[1]s; M=%[2]s; PK=%[3]s
files=$(ocamlfind ocamldep -sort *.mli *.ml 2>/dev/null || ocamlfind ocamldep -sort *.ml)
: > ${L}__.ml
for f in *.ml; do b=${f%%.ml}; [ "$b" = "$L" ] && continue; B=${b^}; echo "module $B = ${M}__$B" >> ${L}__.ml; done
if [ ! -f $L.ml ]; then cp ${L}__.ml $L.ml; files="$files $L.ml"; fi
ocamlfind ocamlopt -c -w -49 -no-alias-deps -bin-annot ${L}__.ml
cmx="${L}__.cmx"
for f in $files; do
  b=${f%%.*}
  if [ "$b" = "$L" ]; then o=$L; else o=${L}__${b^}; fi
  ocamlfind ocamlopt $PK -c -g -bin-annot -open ${M}__ -o $o $f
  case $f in *.ml) cmx="$cmx $o.cmx";; esac
done
`, ll.Name, M, shq(pk))
		lflags := ""
		if len(ll.Stubs) > 0 {
			for _, st := range ll.Stubs {
				fmt.Fprintf(&s, "ocamlfind ocamlopt -c -ccopt -fPIC %s %s.c\n", prefixEach("-ccopt ", cflags), st)
			}
			fmt.Fprintf(&s, "ar rcs lib%s_stubs.a *.o\n", ll.Name)
			lflags = fmt.Sprintf("-cclib -l%s_stubs", ll.Name)
		}
		for _, f := range ldflags {
			if strings.HasPrefix(f, "-l") {
				lflags += " -cclib " + f
			} else {
				lflags += " -ccopt " + f
			}
		}
		fmt.Fprintf(&s, `ocamlfind ocamlopt -a -o $L.cmxa $cmx %s
D=$out/lib/$L; mkdir -p $D
cp *.cmi *.cmx *.cmt* $L.cmxa $L.a $D/; cp lib*_stubs.a $D/ 2>/dev/null || true
printf 'version = "dev"\nrequires = "%s"\narchive(native) = "%s.cmxa"\n' > $D/META
`, lflags, strings.Join(ll.Libs, " "), ll.Name)
	}
	d, err := g.finish("local", "ml-"+ll.Name, "//"+ll.Name+":"+ll.Name, e, s.String(), nil)
	if err != nil {
		return nil, err
	}
	l.built[ll.Name] = d
	return d, nil
}

// Exe links a native executable.
func (g *Gen) Exe(l *Local, x *MLExe) (*drv.Derivation, error) {
	e, err := g.toolEnv()
	if err != nil {
		return nil, err
	}
	src := g.Srcs["ml:"+x.Name]
	e.srcs = append(e.srcs, src)
	op, _, _, err := g.localDeps(l, e, x.Libs, nil)
	if err != nil {
		return nil, fmt.Errorf("//%s: %v", x.Name, err)
	}
	var s strings.Builder
	s.WriteString(g.commonEnv(op))
	fmt.Fprintf(&s, "cp -r %s/. src && chmod -R u+w src && cd src\nmkdir -p $out/bin\n", src)
	switch l.Mode {
	case Dune:
		fmt.Fprintf(&s, "printf '%%s' %s > dune-project\nprintf '%%s' %s > dune\ndune build --release -j $NIX_BUILD_CORES ./%s.exe 2>&1\ncp _build/default/%s.exe $out/bin/%s\n",
			shq(DuneProject), shq(DuneExe(x)), x.Main, x.Main, x.Name)
	default:
		fmt.Fprintf(&s, "files=$(ocamlfind ocamldep -sort *.ml)\nocamlfind ocamlopt -package %s -linkpkg -g $files -o $out/bin/%s\n", strings.Join(x.Libs, ","), x.Name)
	}
	// Drop build-time-only references from the runtime closure (the OCaml stdlib path baked
	// into every native exe, gcc and glibc-dev from the cc-wrapper's -L/RUNPATH).
	s.WriteString(`for r in $(grep -aoE '/nix/store/[a-z0-9]{32}-[^/"]*' $out/bin/* | cut -d: -f2 | sort -u); do
  case ${r#/nix/store/????????????????????????????????-} in
    ocaml-[0-9]*|gcc-[0-9.]*|glibc-*-dev|binutils-*) h=${r:11:32}; sed -i "s|$h|eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee|g" $out/bin/*;;
  esac
done
`)
	return g.finish("local", "ml-"+x.Name, "//"+x.Name+":"+x.Name, e, s.String(), nil)
}

func prefixEach(p string, xs []string) string {
	var out []string
	for _, x := range xs {
		out = append(out, p+x)
	}
	return strings.Join(out, " ")
}

func NewLocal(mode Mode, libs []*MLLib) *Local {
	l := &Local{Libs: map[string]*MLLib{}, Mode: mode, built: map[string]*drv.Derivation{}}
	for _, x := range libs {
		l.Libs[x.Name] = x
	}
	return l
}
