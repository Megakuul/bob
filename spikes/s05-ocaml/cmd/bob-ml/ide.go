package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"bobspike/s05/drv"
	"bobspike/s05/ocamlgen"
	"bobspike/s05/run"
)

var ideTools = []string{"ocamlPackages.ocaml-lsp", "ocamlPackages.merlin", "ocamlPackages.dot-merlin-reader"}

// ideCmd: what `bob dev` would materialise for OCaml editors.
//   -style dune   : dune-project + dune files (merlin asks `dune ocaml-merlin`, needs `dune build @check`)
//   -style merlin : .merlin files only (dot-merlin-reader; own libraries from bob's store outputs)
func ideCmd(args []string) error {
	fs := flag.NewFlagSet("ide", flag.ExitOnError)
	style := fs.String("style", "dune", "dune|merlin")
	fs.Parse(args)
	if fs.NArg() != 2 {
		return fmt.Errorf("usage: bob-ml ide [-style dune|merlin] ws.json bob.lock")
	}
	t0 := time.Now()
	t := &timer{last: t0}
	w, g, l, err := setup(fs.Arg(0), fs.Arg(1), ocamlgen.Direct, t)
	if err != nil {
		return err
	}
	if err := g.Ix.Resolve(ideTools); err != nil {
		return err
	}
	// opam closure of everything the workspace uses
	var roots []string
	for _, lb := range w.Libs {
		roots = append(roots, lb.Libs...)
	}
	for _, x := range w.Exes {
		roots = append(roots, x.Libs...)
	}
	local := map[string]bool{}
	for _, lb := range w.Libs {
		local[lb.Name] = true
	}
	var opamRoots []string
	for _, r := range roots {
		p, _, _ := strings.Cut(r, ".")
		if !local[p] && g.Lock.Packages[p] != nil {
			opamRoots = append(opamRoots, p)
		}
	}
	clo, err := g.Closure(opamRoots)
	if err != nil {
		return err
	}
	var want []*drv.Derivation
	var ocamlpath []string
	for _, n := range clo {
		d, err := g.Package(n)
		if err != nil {
			return err
		}
		want = append(want, d)
		ocamlpath = append(ocamlpath, d.OutPath+"/lib")
	}
	ocamlV := g.Ix.Attrs["ocamlPackages.ocaml"].Version
	ocamlpath = append(ocamlpath, fmt.Sprintf("%s/lib/ocaml/%s/site-lib", g.Tool("ocamlPackages.findlib"), ocamlV))
	libOut := map[string]string{}
	cflags := map[string][]string{}
	ldflags := map[string][]string{}
	for _, lb := range w.Libs {
		for _, c := range lb.CLibs {
			d, err := g.CLib(c)
			if err != nil {
				return err
			}
			want = append(want, d)
			cflags[lb.Name] = append(cflags[lb.Name], "-I"+d.OutPath+"/include")
			ldflags[lb.Name] = append(ldflags[lb.Name], "-L"+d.OutPath+"/lib", "-l"+c)
		}
		if *style == "merlin" {
			d, err := g.LocalLib(l, lb)
			if err != nil {
				return err
			}
			want = append(want, d)
			libOut[lb.Name] = d.OutPath + "/lib/" + lb.Name
		}
	}
	if _, err := run.AddDerivations(g.Order, "import"); err != nil {
		return err
	}
	var paths []string
	for _, d := range want {
		paths = append(paths, d.DrvPath)
	}
	res, err := run.Build(paths)
	if err != nil {
		return err
	}
	if !res.OK {
		return translate(g, res)
	}
	var written []string
	write := func(rel, content string, mode os.FileMode) error {
		p := filepath.Join(w.Root, rel)
		os.MkdirAll(filepath.Dir(p), 0o755)
		written = append(written, rel)
		return os.WriteFile(p, []byte(content), mode)
	}
	// clean files of the other style
	for _, x := range append(dirsOf(w), ".") {
		os.Remove(filepath.Join(w.Root, x, ".merlin"))
		os.Remove(filepath.Join(w.Root, x, "dune"))
	}
	os.Remove(filepath.Join(w.Root, "dune-project"))
	switch *style {
	case "dune":
		write("dune-project", ocamlgen.DuneProject+"; generated by bob from bob.go — do not edit\n", 0o644)
		for _, lb := range w.Libs {
			write(filepath.Join(lb.Src, "dune"), ocamlgen.DuneLib(lb, cflags[lb.Name], ldflags[lb.Name]), 0o644)
			write(lb.Name+".opam", "# generated by bob — do not edit\n", 0o644)
		}
		for _, x := range w.Exes {
			write(filepath.Join(x.Src, "dune"), ocamlgen.DuneExe(x), 0o644)
		}
	case "merlin":
		for _, lb := range w.Libs {
			m := "# generated by bob from bob.go — do not edit\nS .\nB .\nFLG -open " + capital(lb.Name) + "__\n"
			for _, p := range lb.Libs {
				m += "PKG " + p + "\n"
			}
			// the alias module lives in bob's output
			m += "B " + libOut[lb.Name] + "\n"
			write(filepath.Join(lb.Src, ".merlin"), m, 0o644)
		}
		for _, x := range w.Exes {
			m := "# generated by bob from bob.go — do not edit\nS .\nB .\n"
			for _, p := range x.Libs {
				if o := libOut[p]; o != "" {
					m += "B " + o + "\n"
				} else {
					m += "PKG " + p + "\n"
				}
			}
			write(filepath.Join(x.Src, ".merlin"), m, 0o644)
		}
	}
	// .bob/bin shims (ADR 0002 Decision 5): fixed tool versions, OCAMLPATH from the store.
	path := []string{g.Tool("ocamlPackages.ocaml") + "/bin", g.Tool("ocamlPackages.findlib") + "/bin", g.Tool("ocamlPackages.dune_3") + "/bin",
		g.Tool("ocamlPackages.merlin") + "/bin", g.Tool("ocamlPackages.dot-merlin-reader") + "/bin", g.Tool("stdenv.cc") + "/bin", g.Tool("stdenv.cc.bintools") + "/bin"}
	envs := fmt.Sprintf("export OCAMLPATH=%s\nexport PATH=%s:$PATH\n", strings.Join(ocamlpath, ":"), strings.Join(path, ":"))
	tools := map[string]string{"ocamllsp": g.Tool("ocamlPackages.ocaml-lsp") + "/bin/ocamllsp"}
	for _, n := range []string{"ocaml", "ocamlc", "ocamlopt", "ocamlfind", "dune", "ocamlmerlin", "dot-merlin-reader"} {
		tools[n] = ""
	}
	var names []string
	for n := range tools {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		target := tools[n]
		if target == "" {
			for _, d := range path {
				if _, err := os.Stat(filepath.Join(d, n)); err == nil {
					target = filepath.Join(d, n)
					break
				}
			}
		}
		write(filepath.Join(".bob", "bin", n), "#!/bin/sh\n# generated by bob dev\n"+envs+"exec "+target+" \"$@\"\n", 0o755)
	}
	fmt.Fprintf(os.Stderr, "wrote %d files in %.2fs: %s\n", len(written), time.Since(t0).Seconds(), strings.Join(written, " "))
	return nil
}

func dirsOf(w *Workspace) []string {
	var out []string
	for _, lb := range w.Libs {
		out = append(out, lb.Src)
	}
	for _, x := range w.Exes {
		out = append(out, x.Src)
	}
	return out
}

func capital(s string) string { return strings.ToUpper(s[:1]) + s[1:] }
