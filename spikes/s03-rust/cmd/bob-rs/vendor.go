package main

import (
	"context"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"bobspike/s03/crates"
	"bobspike/s03/drv"
)

// cmdVendor materialises a cargo directory source for the generated Cargo.toml/Cargo.lock so
// cargo-based tooling (rust-analyzer's cargo mode) works offline: one directory per locked
// crate whose entries are symlinks into the unpacked source in the store, plus the
// .cargo-checksum.json cargo requires.
func cmdVendor(wsPath, lockPath string) error {
	w, err := crates.ReadWorkspace(wsPath)
	if err != nil {
		return err
	}
	l, err := crates.ReadLock(lockPath)
	if err != nil {
		return err
	}
	vdir := filepath.Join(w.Root, ".bob", "vendor")
	if err := os.MkdirAll(vdir, 0o755); err != nil {
		return err
	}
	fromStore, fromCache := 0, 0
	for _, c := range l.Crates {
		raw, _ := base64.StdEncoding.DecodeString(strings.TrimPrefix(c.NarHash, "sha256-"))
		sp := drv.FixedOutputPath(sanitize(c.Name+"-"+c.Version), "recursive", raw)
		if _, err := os.Stat(sp); err != nil {
			// not realised yet (e.g. a Windows-only crate): unpack from the verified download
			f, err := crates.Download(context.Background(), cacheDir(), c)
			if err != nil {
				return err
			}
			sp = filepath.Join(os.Getenv("BOB_TMP"), "unpacked", c.Name+"-"+c.Version)
			if _, err := os.Stat(sp); err != nil {
				_ = os.MkdirAll(filepath.Dir(sp), 0o755)
				if out, err := exec.Command("tar", "-xzf", f, "-C", filepath.Dir(sp)).CombinedOutput(); err != nil {
					return fmt.Errorf("unpack %s: %v %s", f, err, out)
				}
			}
			fromCache++
		} else {
			fromStore++
		}
		d := filepath.Join(vdir, c.Name+"-"+c.Version)
		_ = os.RemoveAll(d)
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
		ents, err := os.ReadDir(sp)
		if err != nil {
			return err
		}
		for _, e := range ents {
			if err := os.Symlink(filepath.Join(sp, e.Name()), filepath.Join(d, e.Name())); err != nil {
				return err
			}
		}
		b, _ := base64.StdEncoding.DecodeString(strings.TrimPrefix(c.Checksum, "sha256-"))
		ck := fmt.Sprintf(`{"files":{},"package":%q}`, hex.EncodeToString(b))
		if err := os.WriteFile(filepath.Join(d, ".cargo-checksum.json"), []byte(ck), 0o644); err != nil {
			return err
		}
	}
	cfg := "# generated by bob; do not edit\n[source.crates-io]\nreplace-with = \"bob-vendor\"\n\n[source.bob-vendor]\ndirectory = \".bob/vendor\"\n\n[net]\noffline = true\n"
	if err := os.MkdirAll(filepath.Join(w.Root, ".cargo"), 0o755); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "vendored %d crates (%d from the store, %d unpacked from the download cache)\n", len(l.Crates), fromStore, fromCache)
	return os.WriteFile(filepath.Join(w.Root, ".cargo", "config.toml"), []byte(cfg), 0o644)
}

func sanitize(s string) string {
	return strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("+-._?=", r) {
			return r
		}
		return '-'
	}, s)
}
