package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"bobspike/s03/crates"
)

// cmdCargo writes the generated native files for tooling (R-RS-003): a workspace Cargo.toml at
// the root, one Cargo.toml per crate, and Cargo.lock. If -lock is given, its versions win.
func cmdCargo(wsPath, lockPath, out string) error {
	w, err := crates.ReadWorkspace(wsPath)
	if err != nil {
		return err
	}
	if out == "" {
		out = w.Root
	}
	var members []string
	for _, c := range w.Crates {
		members = append(members, c.Src)
		rel := func(o *crates.WsCrate) string {
			r, _ := filepath.Rel(filepath.Join(out, c.Src), filepath.Join(out, o.Src))
			return r
		}
		dir := filepath.Join(out, c.Src)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, "Cargo.toml"), []byte(w.CargoToml(c, rel)), 0o644); err != nil {
			return err
		}
	}
	sort.Strings(members)
	q := make([]string, len(members))
	for i, m := range members {
		q[i] = fmt.Sprintf("%q", m)
	}
	root := "# generated by bob from bob.go; do not edit\n[workspace]\nresolver = \"2\"\nmembers = [" + strings.Join(q, ", ") + "]\n"
	if err := os.WriteFile(filepath.Join(out, "Cargo.toml"), []byte(root), 0o644); err != nil {
		return err
	}
	if lockPath != "" {
		l, err := crates.ReadLock(lockPath)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(out, "Cargo.lock"), []byte(crates.CargoLockFromLock(w, l)), 0o644)
	}
	return nil
}
