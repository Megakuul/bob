package crates

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

// Workspace stands in for what bob.go declares (rust.Library / rust.Binary + crates.io deps).
type Workspace struct {
	Root   string     `json:"root"` // absolute; crate Src paths are relative to it
	Crates []*WsCrate `json:"crates"`
	CC     []*WsCC    `json:"cc,omitempty"`
	Go     []*WsGo    `json:"go,omitempty"`
	// Native lists nixpkgs packages a crates.io crate's build script needs (pkg-config, system
	// libraries). Stand-in for rust.Crate("openssl-sys").Uses(nixpkgs.Pkg("openssl")).
	Native map[string][]string `json:"native,omitempty"`
}

// WsCC is a bob C library or program (stand-in for cc.Library / cc.Binary).
type WsCC struct {
	Name     string   `json:"name"`
	Src      string   `json:"src"`
	Srcs     []string `json:"srcs"`
	Hdrs     string   `json:"hdrs,omitempty"`
	Kind     string   `json:"kind"`               // static | shared | bin
	RustDeps []string `json:"rustDeps,omitempty"` // Rust staticlib/cdylib crates to link
	LinkArgs []string `json:"linkArgs,omitempty"`
}

// WsGo is a cgo binary linking Rust staticlibs (stand-in for go.Binary).
type WsGo struct {
	Name     string   `json:"name"`
	Src      string   `json:"src"`
	Main     string   `json:"main"`
	RustDeps []string `json:"rustDeps"`
	LdExtra  []string `json:"ldExtra,omitempty"`
}

type WsCrate struct {
	Name     string              `json:"name"`
	Version  string              `json:"version"`
	Edition  string              `json:"edition"`
	Type     string              `json:"type"` // lib | bin | staticlib | cdylib | proc-macro
	Src      string              `json:"src"`
	Root     string              `json:"root"` // crate root file relative to Src
	Hdrs     string              `json:"hdrs,omitempty"`
	Deps     []WsDep             `json:"deps"`
	Features map[string][]string `json:"features,omitempty"`
	Enable   []string            `json:"enable,omitempty"` // features enabled on this local crate for the build
	CLibs    []string            `json:"clibs,omitempty"`  // bob C libraries to link (labels, spike: prebuilt store dirs)
	BuildRS  string              `json:"buildRs,omitempty"`
}

type WsDep struct {
	Name      string   `json:"name"`            // name used in code
	Crate     string   `json:"crate,omitempty"` // crates.io name if renamed
	Req       string   `json:"req,omitempty"`
	Local     bool     `json:"local,omitempty"`
	Features  []string `json:"features,omitempty"`
	NoDefault bool     `json:"noDefault,omitempty"`
	Optional  bool     `json:"optional,omitempty"`
	Kind      string   `json:"kind,omitempty"`
}

func ReadWorkspace(path string) (*Workspace, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var w Workspace
	if err := json.Unmarshal(b, &w); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &w, nil
}

func (w *Workspace) Get(name string) *WsCrate {
	for _, c := range w.Crates {
		if c.Name == name {
			return c
		}
	}
	return nil
}

func (w *Workspace) Locals() []*Local {
	var out []*Local
	for _, c := range w.Crates {
		l := &Local{Name: c.Name, Version: c.Version, Features: c.Features}
		for _, d := range c.Deps {
			id := IndexDep{Name: d.Name, Package: d.Crate, Req: d.Req, Features: d.Features, DefaultFeatures: !d.NoDefault,
				Optional: d.Optional, Kind: d.Kind}
			if id.Kind == "" {
				id.Kind = "normal"
			}
			if d.Local {
				id.Registry, id.Req = "local", "*"
			}
			l.Deps = append(l.Deps, id)
		}
		out = append(out, l)
	}
	return out
}

// CargoToml renders the generated manifest of one local crate (tooling only, R-RS-003).
func (w *Workspace) CargoToml(c *WsCrate, relRoot func(*WsCrate) string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by bob from bob.go; do not edit\n[package]\nname = %q\nversion = %q\nedition = %q\npublish = false\nautobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n", c.Name, c.Version, c.Edition)
	if c.BuildRS != "" {
		fmt.Fprintf(&b, "build = %q\n", c.BuildRS)
	} else {
		b.WriteString("build = false\n")
	}
	switch c.Type {
	case "bin":
		fmt.Fprintf(&b, "\n[[bin]]\nname = %q\npath = %q\n", c.Name, c.Root)
	default:
		fmt.Fprintf(&b, "\n[lib]\npath = %q\n", c.Root)
		switch c.Type {
		case "proc-macro":
			b.WriteString("proc-macro = true\n")
		case "staticlib", "cdylib":
			fmt.Fprintf(&b, "crate-type = [%q]\n", c.Type)
		}
	}
	sections := map[string][]string{}
	for _, d := range c.Deps {
		sec := "dependencies"
		switch d.Kind {
		case "build":
			sec = "build-dependencies"
		case "dev":
			sec = "dev-dependencies"
		}
		var kv []string
		if d.Local {
			kv = append(kv, fmt.Sprintf("path = %q", relRoot(w.Get(d.Name))))
		} else {
			kv = append(kv, fmt.Sprintf("version = %q", d.Req))
		}
		if d.Crate != "" {
			kv = append(kv, fmt.Sprintf("package = %q", d.Crate))
		}
		if len(d.Features) > 0 {
			q := make([]string, len(d.Features))
			for i, f := range d.Features {
				q[i] = fmt.Sprintf("%q", f)
			}
			kv = append(kv, "features = ["+strings.Join(q, ", ")+"]")
		}
		if d.NoDefault {
			kv = append(kv, "default-features = false")
		}
		if d.Optional {
			kv = append(kv, "optional = true")
		}
		sections[sec] = append(sections[sec], fmt.Sprintf("%s = { %s }", d.Name, strings.Join(kv, ", ")))
	}
	for _, sec := range []string{"dependencies", "build-dependencies", "dev-dependencies"} {
		if len(sections[sec]) > 0 {
			fmt.Fprintf(&b, "\n[%s]\n%s\n", sec, strings.Join(sections[sec], "\n"))
		}
	}
	if len(c.Features) > 0 {
		b.WriteString("\n[features]\n")
		var ks []string
		for k := range c.Features {
			ks = append(ks, k)
		}
		sort.Strings(ks)
		for _, k := range ks {
			q := []string{}
			for _, f := range c.Features[k] {
				q = append(q, fmt.Sprintf("%q", f))
			}
			fmt.Fprintf(&b, "%s = [%s]\n", k, strings.Join(q, ", "))
		}
	}
	return b.String()
}
